// node tests/k17.test.js — срок исковой давности
const assert = require("assert");
const { run, val, U, t, done } = require("./_loadcalc")("k17");

t("долг: срок возврата 10.01.2023 → 10.01.2026 (суббота) → 12.01.2026", () => {
  // 10.01.2026 — суббота, переносится на понедельник 12.01.2026
  const r = run({ kind: "debt", start: "2023-01-10" });
  assert.equal(val(r, "Последний день"), "12.01.2026");
  assert(r.summary[1].label === "Срок истёк" && r.notes.some(x => x.includes("п. 2 ст. 199")));
});

t("обычный будний день: 15.06.2024 → 15.06.2027 (вт)", () => {
  assert.equal(val(run({ kind: "debt", start: "2024-06-15" }), "Последний день"), "15.06.2027");
});

t("до востребования: требование 01.03.2024 → +30 дней 31.03.2024 → 31.03.2027 (ср)", () => {
  assert.equal(val(run({ kind: "demand", start: "2024-03-01" }), "Последний день"), "31.03.2027");
});

t("признание долга 20.05.2025 — срок заново до 20.05.2028", () => {
  const r = run({ kind: "debt", start: "2023-01-10", ack: "yes", ack_date: "2025-05-20" });
  assert.equal(val(r, "Последний день"), "22.05.2028"); // 20.05.2028 — суббота
  assert(r.table.rows.some(x => x[0].startsWith("Признание долга")));
});

t("судебный приказ: срок до 15.06.2027, приказ 01.06.2027–20.06.2027 → остаток 14 дней < 6 мес → до 20.12.2027", () => {
  const r = run({ kind: "debt", start: "2024-06-15", order: "yes", order_filed: "2027-06-01", order_cancel: "2027-06-20" });
  assert.equal(val(r, "Последний день"), "20.12.2027");
});

t("приказ при большом остатке — просто прибавляем время у судьи", () => {
  // срок до 15.06.2027; приказ 01.02.2025–01.03.2025 (28 дней) → 13.07.2027
  assert.equal(val(run({ kind: "debt", start: "2024-06-15", order: "yes", order_filed: "2025-02-01", order_cancel: "2025-03-01" }), "Последний день"), "13.07.2027");
});

t("предел 10 лет: признания продлевают, но не дальше 10 лет со дня нарушения", () => {
  const r = run({ kind: "debt", start: "2018-03-01", ack: "yes", ack_date: "2026-04-01" });
  assert.equal(val(r, "Последний день"), "01.03.2028");
  assert(r.table.rows.some(x => x[0] === "Предел"));
});

t("увольнение — 1 месяц: копия приказа 30.10.2026 → 30.11.2026 (пн)", () => {
  const r = run({ kind: "fired", start: "2026-10-30" });
  assert.equal(val(r, "Последний день"), "30.11.2026");
  assert(!r.table.rows.some(x => x[0].startsWith("Признание")) && r.related.some(x => x.id === "d26"));
});

t("зарплата — 1 год; страховка имущества — 2 года; оспоримая сделка — 1 год", () => {
  assert.equal(val(run({ kind: "salary", start: "2026-02-10" }), "Последний день"), "10.02.2027");
  assert.equal(val(run({ kind: "insurance", start: "2026-02-10" }), "Последний день"), "10.02.2028");
  assert.equal(val(run({ kind: "voidable", start: "2026-02-10" }), "Последний день"), "10.02.2027");
});

t("признание и приказ не применяются к трудовым спорам, даже если остались в ответах", () => {
  assert.equal(val(run({ kind: "fired", start: "2026-10-30", ack: "yes", ack_date: "2026-11-05" }), "Последний день"), "30.11.2026");
});

t("напоминания: последний день и за месяц", () => {
  const r = run({ kind: "debt", start: U.iso(U.addDays(U.today(), -100)) });
  assert(r.reminders.length === 2 && r.reminders[0].title.includes("исковая давность"));
});

done();
