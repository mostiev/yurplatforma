/*
 * К-12. Налог при продаже квартиры, дома, дачи, земли, гаража или машины.
 * Основа: НК РФ (ред. 425-ФЗ с 01.01.2026 — владение должно быть непрерывным):
 * ст. 217.1 п. 2 (освобождение при непрерывном владении не меньше минимального срока; срок по ДДУ и ЖСК — с даты
 * полной оплаты), п. 2.1 (семьи с двумя и более детьми — без срока при покупке другого жилья большей площади или
 * кадастровой стоимости в том же году или до 30 апреля следующего; кадастровая стоимость проданного — не больше 50 млн;
 * нет более 50% в другом большем жилье), п. 3 (3 года: наследство; дарение от члена семьи или близкого родственника;
 * приватизация; рента; единственное жильё — без учёта купленного за 90 дней до продажи), п. 4 (иначе 5 лет);
 * ст. 217 п. 17.1 (иное имущество — непрерывно 3 года и более); ст. 214.10 п. 2 (доход от продажи недвижимости — не меньше
 * кадастровой стоимости на 1 января года регистрации × 0,7; регион может менять коэффициент — п. 9 ст. 214.10, пп. 2 п. 6
 * ст. 217.1), п. 3 (без декларации налог посчитает инспекция); ст. 220 пп. 1 п. 2 (вычет 1 000 000 ₽ — жильё, садовые
 * дома, земля; 250 000 ₽ — иная недвижимость; 250 000 ₽ — иное имущество), пп. 2 п. 2 (вместо вычета — расходы на
 * покупку, для наследства и дарения — расходы наследодателя или дарителя); ст. 210 п. 6, 224 п. 1.1 (13% до 2,4 млн,
 * 15% свыше — по сумме «особых» баз); ст. 229 п. 1, 4 (декларация до 30 апреля; не нужна, если доход не больше вычета),
 * ст. 228 п. 4 (уплата до 15 июля), ст. 119, 122 (штрафы). Мена — постановление КС от 15.01.2026 № 1-П (правило 70% к мене
 * не применяется механически) — в калькуляторе не считается. Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const rub = n => U.money(Math.round(n)) + " ₽";
  const n = x => (typeof x === "number" && x > 0 ? x : 0);

  const HOW = {
    buy: ["Купил(а)", 5],
    ddu: ["Купил(а) в новостройке по ДДУ или через ЖСК", 5],
    inherit: ["Получил(а) по наследству", 3],
    gift_family: ["Подарил член семьи или близкий родственник", 3],
    gift_other: ["Подарил кто-то другой", 5],
    privat: ["Приватизация", 3],
    rent: ["По договору пожизненного содержания с иждивением", 3],
  };
  const KIND = {
    home: { label: "Квартира, комната, дом, садовый дом, земельный участок", ded: 1000000, realty: true },
    other_realty: { label: "Гараж, машино-место, нежилое помещение", ded: 250000, realty: true },
    movable: { label: "Машина или другое имущество", ded: 250000, realty: false },
  };
  function ndfl(base) { return base <= 2400000 ? base * 0.13 : 312000 + (base - 2400000) * 0.15; }

  const spec = {
    id: "k12",
    code: "К-12",
    title: "Налог при продаже квартиры или машины",
    lead: "Нужно ли платить налог с продажи, сколько и когда продавать без налога. Учтём срок владения, вычет, расходы на покупку и правило 70% кадастровой стоимости.",
    status: "draft",
    defaults: { kind: "home", how: "buy", only_home: "no", family: "no", coef: 0.7 },

    fields: [
      { id: "kind", type: "select", label: "Что продаёте", options: Object.entries(KIND).map(([value, k]) => ({ value, label: k.label })) },
      { id: "how", type: "select", label: "Как получили", show: a => KIND[a.kind] && KIND[a.kind].realty, options: Object.entries(HOW).map(([value, h]) => ({ value, label: h[0] })) },
      { id: "owned_from", type: "date", label: a => a.how === "ddu" ? "Когда полностью оплатили по договору" : a.how === "inherit" ? "Дата смерти наследодателя" : "Когда стали собственником", hint: a => a.how === "ddu" ? "По ДДУ и ЖСК срок считается с даты полной оплаты" : a.how === "inherit" ? "Наследство — ваше со дня открытия наследства" : "Дата регистрации права в ЕГРН (для машины — дата покупки)" },
      { id: "sale_date", type: "date", future: true, label: "Дата продажи", hint: "Для недвижимости — дата регистрации перехода права к покупателю. Можно поставить будущую дату — посчитаем, есть ли смысл подождать" },
      { id: "only_home", type: "choice", label: "На дату продажи это ваше единственное жильё?", show: a => a.kind === "home" && HOW[a.how] && HOW[a.how][1] === 5, hint: "Включая совместную собственность супругов. Жильё, купленное за 90 дней до продажи, не считается", options: [
        { value: "no", label: "Нет, есть ещё жильё" },
        { value: "yes", label: "Да, единственное", hint: "Тогда минимальный срок — 3 года" },
      ] },
      { id: "family", type: "choice", label: "У вас (или супруга) двое и больше детей, и вы покупаете другое жильё больше по площади или по кадастровой стоимости?", show: a => a.kind === "home", options: [
        { value: "no", label: "Нет" },
        { value: "yes", label: "Да", hint: "Покупка — в том же году или до 30 апреля следующего. Проверим отдельно" },
      ] },
      { id: "price", type: "money", label: "Цена продажи по договору", suffix: "₽" },
      { id: "cadastral", type: "money", label: "Кадастровая стоимость на 1 января года продажи", suffix: "₽", required: false, show: a => KIND[a.kind] && KIND[a.kind].realty, hint: "Есть в выписке из ЕГРН или на сайте Росреестра. Налог считают не меньше чем с 70% от неё" },
      { id: "coef", type: "number", label: "Понижающий коэффициент в вашем регионе", min: 0, step: "0.01", required: false, show: a => KIND[a.kind] && KIND[a.kind].realty && n(a.cadastral) > 0, hint: "Обычно 0,7. Регион может установить другой — от 0 до 1" },
      { id: "spent", type: "money", label: a => a.how === "inherit" || String(a.how).startsWith("gift") ? "Сколько заплатил за это наследодатель или даритель" : "Сколько вы заплатили при покупке", suffix: "₽", required: false, hint: "Только если есть документы: договор, расписка, платёжки. Можно вычесть вместо стандартного вычета" },
    ],

    compute(a) {
      const K = KIND[a.kind];
      const from = U.date(a.owned_from), sale = U.date(a.sale_date);
      const price = n(a.price);
      if (!K || !from || !sale || !price) return null;
      if (sale < from) return { error: "Дата продажи раньше, чем вы стали собственником." };
      let term = 3, why = "иное имущество — 3 года (п. 17.1 ст. 217 НК)";
      if (K.realty) {
        const h = HOW[a.how] || HOW.buy;
        term = h[1];
        why = term === 3 ? `${h[0].toLowerCase()} — 3 года (п. 3 ст. 217.1 НК)` : "5 лет (п. 4 ст. 217.1 НК)";
        if (term === 5 && a.kind === "home" && a.only_home === "yes") { term = 3; why = "единственное жильё — 3 года (пп. 4 п. 3 ст. 217.1 НК)"; }
      }
      const freeFrom = U.addMonths(from, 12 * term);
      const notes = [];
      const year = sale.getFullYear();
      const decl = C.nextWorkday(new Date(year + 1, 3, 30)), pay = C.nextWorkday(new Date(year + 1, 6, 15));
      const summary = [{ label: "Минимальный срок владения", value: `${term} ${C.plural(term, "год", "года", "лет")}` }];

      if (sale >= freeFrom) {
        summary.push({ label: "Налог", value: "0 ₽", big: true });
        notes.push(`Вы владели дольше минимального срока (${why}): доход не облагается, декларацию подавать не нужно (п. 17.1 ст. 217, п. 2 ст. 217.1 НК).`, "С 2026 года владение должно быть непрерывным: если объект выходил из вашей собственности и возвращался, срок, скорее всего, считается заново.");
        return { summary, notes };
      }
      if (a.kind === "home" && a.family === "yes") {
        summary.push({ label: "Налог", value: "0 ₽ — если выполните условия", big: true });
        notes.push("Семьи с двумя и более детьми (до 18 лет, до 24 — если учатся очно, или недееспособными) не платят налог независимо от срока владения, если одновременно (п. 2.1 ст. 217.1 НК):",
          `• в ${year} году или до 30.04.${year + 1} купили другое жильё и зарегистрировали право (или полностью оплатили по ДДУ);`,
          "• новое жильё больше проданного по общей площади или по кадастровой стоимости (с учётом долей семьи);",
          "• кадастровая стоимость проданного — не больше 50 млн ₽;",
          "• у вас, супруга и несовершеннолетних детей нет больше 50% в другом жилье, которое больше купленного.",
          `Если условия не выполнятся, налог придётся заплатить. Посчитайте вариант «Нет» выше, чтобы знать сумму.`);
        return { summary, notes };
      }

      let income = price;
      const cad = n(a.cadastral);
      const coef = typeof a.coef === "number" && a.coef >= 0 && a.coef <= 1 ? a.coef : 0.7;
      if (K.realty && cad && price < cad * coef) {
        income = cad * coef;
        notes.push(`Цена в договоре меньше ${String(coef).replace(".", ",")} кадастровой стоимости, поэтому доходом считается ${rub(income)} (п. 2 ст. 214.10 НК).`);
      }
      const spent = n(a.spent);
      const useSpent = spent > K.ded;
      const ded = useSpent ? spent : K.ded;
      const base = Math.max(0, income - ded);
      const tax = Math.round(ndfl(base));
      summary.push(
        { label: "Доход для налога", value: rub(income) },
        { label: useSpent ? "Минус расходы на покупку" : "Минус вычет", value: rub(Math.min(ded, income)) },
        { label: "Налог", value: rub(tax), big: true },
      );
      const days = U.daysBetween(sale, freeFrom);
      notes.push(`Продать без налога можно с ${U.fmtDate(freeFrom)} — ${why}. ${days > 0 ? `Это через ${days} ${C.plural(days, "день", "дня", "дней")} после выбранной даты.` : ""}`);
      notes.push(useSpent
        ? "Вместо стандартного вычета вычли документально подтверждённые расходы на покупку — это выгоднее (пп. 2 п. 2 ст. 220 НК)."
        : `Применён вычет ${rub(K.ded)} (пп. 1 п. 2 ст. 220 НК).${spent ? " Расходы на покупку меньше вычета — выгоднее вычет." : " Если есть документы о расходах на покупку — укажите их, может выйти выгоднее."}`);
      if (income <= K.ded) notes.push("Доход не больше вычета — декларацию можно не подавать (п. 4 ст. 229 НК).");
      else notes.push(`Подайте декларацию 3-НДФЛ до ${U.fmtDate(decl)} и заплатите налог до ${U.fmtDate(pay)} (п. 1 ст. 229, п. 4 ст. 228 НК). Декларация нужна, даже если налог выйдет 0 из-за расходов. Не подали — штраф 5% налога за каждый месяц (не меньше 1 000 ₽), не заплатили — 20% (ст. 119, 122 НК)${K.realty ? "; по недвижимости инспекция всё равно посчитает налог сама по данным Росреестра (п. 3 ст. 214.10)" : ""}.`);
      if (base > 2400000) notes.push("Часть свыше 2,4 млн ₽ облагается по 15%. Порог общий для продаж, дивидендов, процентов по вкладам за год (п. 1.1 ст. 224 НК) — если были и такие доходы, налог может быть больше.");
      if (a.kind === "home") notes.push("Продаёте долю или вместе с другими собственниками одним договором — вычет 1 млн делится между всеми пропорционально долям (ст. 220 НК).");
      return { summary, notes };
    },
  };

  global.CALCS = global.CALCS || {};
  global.CALCS.k12 = spec;
})(typeof window !== "undefined" ? window : globalThis);
