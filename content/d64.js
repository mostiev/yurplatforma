/*
 * Д-64. Увольнение по соглашению сторон: соглашение о расторжении трудового договора или предложение работодателю.
 * Основа: ТК РФ — п. 1 ч. 1 ст. 77, ст. 78 (в любое время по соглашению сторон), ст. 84.1 (приказ; день прекращения —
 * последний день работы; в день прекращения — трудовая книжка или сведения о трудовой деятельности и расчёт), ст. 127
 * (компенсация за все неиспользованные отпуска), ст. 140 (расчёт в день увольнения), ст. 66.1, ст. 349.3 ч. 3 (соглашения
 * с руководителями, заместителями, главбухами госкорпораций, госкомпаний, ГУП и т. п. не могут содержать выплат).
 * Пленум ВС от 17.03.2004 № 2 п. 20 (аннулировать договорённость — только по взаимному согласию). Обзор судебной практики
 * ВС № 2 (2026), утв. 01.07.2026, п. 6 (соглашение без гарантий работнику, давление, непонимание последствий — признаки
 * вынужденного подписания). Постановление КС от 13.07.2023 № 40-П (выходное пособие по соглашению законно). НДФЛ и взносы —
 * ст. 217, 422 НК (не облагается в пределах трёхкратного среднего месячного заработка; для НДФЛ с 2025 г. средний — как
 * для пособий). Пособие по безработице — ст. 45 закона № 565-ФЗ (основание увольнения по соглашению не уменьшает).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  function derive(a) {
    const pay = a.payment === "yes" && typeof a.pay_amount === "number" && a.pay_amount > 0 ? a.pay_amount : 0;
    return { last: U.date(a.last_day), date: U.date(a.doc_date), pay, payDate: a.pay_when === "date" ? U.date(a.pay_date) : null, contractDate: U.date(a.contract_date) };
  }

  const spec = {
    id: "d64",
    code: "Д-64",
    title: "Увольнение по соглашению сторон",
    lead: "Соглашение о расторжении трудового договора с выходным пособием — или письмо работодателю с предложением уволиться по соглашению. Займёт около 5 минут.",
    status: "draft",
    defaults: { route: "agreement", payment: "yes", pay_when: "dismissal", state_co: "no" },

    steps: [
      {
        id: "terms", title: "Условия",
        questions: [
          { id: "route", type: "choice", label: "Что составить?", options: [
            { value: "agreement", label: "Соглашение — подпишем с работодателем" },
            { value: "proposal", label: "Предложение работодателю + проект соглашения", hint: "Если о соглашении ещё не договорились" },
          ] },
          { id: "last_day", type: "date", future: true, label: "Последний рабочий день", hint: "Это и есть день увольнения (ч. 3 ст. 84.1 ТК)" },
          { id: "payment", type: "choice", label: "Будет выплата сверх обычного расчёта (выходное пособие)?", options: [
            { value: "yes", label: "Да" },
            { value: "no", label: "Нет", hint: "Соглашение без каких-либо гарантий суд может счесть вынужденным" },
          ] },
          { id: "pay_amount", type: "money", label: "Размер выходного пособия", suffix: "₽", show: a => a.payment === "yes", hint: "Часто договариваются о 1–3 окладах. До трёх средних месячных заработков НДФЛ не удерживают" },
          { id: "pay_when", type: "choice", label: "Когда выплатить пособие", show: a => a.payment === "yes", options: [
            { value: "dismissal", label: "В день увольнения" },
            { value: "date", label: "К другой дате" },
          ] },
          { id: "pay_date", type: "date", future: true, label: "Дата выплаты", show: a => a.payment === "yes" && a.pay_when === "date" },
          { id: "extra", type: "textarea", label: "Другие условия", required: false, placeholder: "Работник передаёт дела и имущество работодателя до 14.10.2026.\nРаботодатель не возражает против освобождения работника от работы с 07.10.2026 с сохранением среднего заработка." },
          { id: "state_co", type: "choice", label: "Вы руководитель, заместитель или главбух госкорпорации, госкомпании, ГУП или организации с долей государства больше 50%?", options: [
            { value: "no", label: "Нет" },
            { value: "yes", label: "Да" },
          ] },
        ],
      },
      {
        id: "job", title: "Стороны",
        questions: [
          ...C.jobQuestions(),
          { id: "head_basis", type: "text", label: "На каком основании действует руководитель", placeholder: "Устава", required: false },
          { id: "contract_no", type: "text", label: "Номер трудового договора", required: false },
          { id: "contract_date", type: "date", label: "Дата трудового договора" },
          { id: "city", type: "text", label: "Город", placeholder: "г. Москва" },
          { id: "doc_date", type: "date", future: true, label: "Дата соглашения (предложения)" },
        ],
      },
    ],

    derive,

    stop(a, d) {
      if (a.state_co === "yes" && d.pay) return { title: "В вашем случае соглашение не может содержать выплат.", text: "С руководителями, их заместителями и главными бухгалтерами госкорпораций, госкомпаний, унитарных предприятий, организаций с долей государства больше 50% и ряда других нельзя договориться о выходном пособии или компенсации в соглашении об увольнении (ч. 3 ст. 349.3 ТК). Уберите выплату — соглашение подготовим без неё." };
      if (d.last && d.date && d.last < d.date) return { title: "Последний рабочий день раньше даты соглашения.", text: "Соглашение подписывают до увольнения. Проверьте даты." };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      const lastDay = F(U.fmtDate(d.last), "последний день");
      const contract = `трудовой договор от ${F(U.fmtDate(d.contractDate), "дата договора")}` + (a.contract_no ? ` № ${a.contract_no}` : "");
      const payWhen = d.payDate ? `не позднее ${U.fmtDate(d.payDate)}` : "в день увольнения";

      const agreement = () => {
        P.push({ text: "СОГЛАШЕНИЕ", align: "center", bold: true, after: 0 });
        P.push({ text: `о расторжении трудового договора от ${F(U.fmtDate(d.contractDate), "дата договора")}` + (a.contract_no ? ` № ${a.contract_no}` : ""), align: "center", after: 240 });
        P.push({ text: `${F(a.city, "город")}                                                                          ${a.route === "proposal" ? "«___» __________ 20__ г." : F(U.fmtDateLong(d.date), "дата")}`, align: "left", after: 240 });
        T(`${F(a.org_name, "работодатель")} (далее — Работодатель), от имени которого действует ${F(a.head_position ? a.head_position[0].toLowerCase() + a.head_position.slice(1) : null, "должность руководителя")} ${F(a.head_name, "ФИО руководителя")}, на основании ${a.head_basis || "Устава"}, и работник ${F(a.buyer_name, "ФИО работника")}, должность: ${F(a.position, "должность")}${a.department ? ", " + a.department : ""} (далее — Работник), вместе именуемые Стороны, заключили настоящее соглашение о нижеследующем.`);
        let k = 1;
        T(`${k++}. Стороны договорились расторгнуть ${contract} по соглашению сторон на основании пункта 1 части первой статьи 77 и статьи 78 Трудового кодекса РФ.`);
        T(`${k++}. Последний день работы Работника (день прекращения трудового договора) — ${lastDay}.`);
        T(`${k++}. В последний день работы Работодатель выплачивает Работнику заработную плату за отработанное время и компенсацию за все неиспользованные отпуска (статьи 127, 140 Трудового кодекса РФ), выдаёт трудовую книжку (если она ведётся) и сведения о трудовой деятельности (статьи 66.1, 84.1 Трудового кодекса РФ).`);
        if (d.pay) T(`${k++}. Помимо выплат, указанных в пункте ${k - 2}, Работодатель выплачивает Работнику выходное пособие в размере ${C.rubles(d.pay)} ${payWhen} путём перечисления на банковский счёт, на который Работнику выплачивается заработная плата.`);
        if (a.extra) String(a.extra).split(/\n+/).map(x => x.trim()).filter(Boolean).forEach(x => T(`${k++}. ${x.replace(/\.?$/, ".")}`));
        T(`${k++}. Настоящее соглашение может быть изменено или отменено только по взаимному согласию Сторон.`);
        T(`${k++}. Соглашение составлено в двух экземплярах, имеющих одинаковую юридическую силу, по одному для каждой из Сторон, и вступает в силу с момента подписания.`);
        P.push({ text: `Работодатель:\n${F(a.org_name, "работодатель")}\n${F(a.head_position, "должность")} ____________ / ${F(U.shortName(a.head_name), "И. О. Фамилия")}\nМ. П. (при наличии)`, align: "left", before: 360, keepLines: true, keepNext: true });
        P.push({ text: `Работник:\n____________ / ${F(U.shortName(a.buyer_name), "И. О. Фамилия")}`, align: "left", before: 240, keepLines: true });
        P.push({ text: "Второй экземпляр соглашения получил(а): ____________ «___» __________ 20__ г.", align: "left", before: 240 });
      };

      if (a.route === "proposal") {
        C.jobHeader(P, a);
        C.title(P, "ПРЕДЛОЖЕНИЕ", "о расторжении трудового договора по соглашению сторон");
        T(`Предлагаю расторгнуть ${contract} по соглашению сторон (пункт 1 части первой статьи 77, статья 78 Трудового кодекса РФ) с последним рабочим днём ${lastDay}` + (d.pay ? ` и выплатой мне выходного пособия в размере ${C.rubles(d.pay)} ${payWhen}` : "") + ".");
        T("Проект соглашения прилагаю. Прошу рассмотреть предложение и сообщить о решении в течение 5 рабочих дней.");
        C.attachments(P, ["Проект соглашения о расторжении трудового договора."]);
        P.push({ text: `${F(U.fmtDate(d.date), "дата")}            ____________ / ${F(U.shortName(a.buyer_name), "И. О. Фамилия")}`, align: "left", before: 360 });
        P.push({ pageBreak: true });
        P.push({ text: "Проект", align: "right", after: 120 });
      }
      agreement();
      return P;
    },

    guidance(a, d) {
      const g = [
        { title: "Подпишите два экземпляра — один оставьте себе.", text: "Проверьте, что на вашем экземпляре есть подпись руководителя (и печать, если она используется). Без вашего экземпляра потом сложно доказать условия." },
        { title: "Передумать в одиночку нельзя.", text: "Отменить или изменить соглашение можно только вместе с работодателем (п. 20 Пленума ВС № 2). Исключение — если вас вынудили подписать: это можно доказать в суде, в том числе перепиской и свидетелями (Обзор практики ВС № 2 за 2026 г.)." },
        { title: "В последний день — полный расчёт.", text: "Зарплата, компенсация за неиспользованный отпуск (посчитайте в К-9)" + (d.pay ? ", выходное пособие" : "") + ", трудовая книжка или сведения о трудовой деятельности (ст. 84.1, 140 ТК). За задержку — компенсация по ст. 236 (К-4)." },
      ];
      if (d.pay) g.push({ title: "Налог с выходного пособия.", text: "НДФЛ и взносы не берут с суммы до трёх средних месячных заработков (на Крайнем Севере — шести); с превышения удержат 13% (ст. 217, 422 НК)." });
      g.push(
        { title: "Пособие по безработице не пострадает.", text: "Увольнение по соглашению не уменьшает пособие: первые 3 месяца — 75% среднего заработка, следующие 3 — 60%, в пределах максимума (ст. 45 закона № 565-ФЗ). Встать на учёт можно через Госуслуги или «Работу России»." },
        { title: "Если вы беременны — подумайте дважды.", text: "При сокращении беременную уволить нельзя, а соглашение лишает этой защиты. Если о беременности вы узнали уже после подписания, суды признают право отказаться от соглашения." },
      );
      return g;
    },

    reminders(a, d) { return [{ date: d.last, title: "Последний рабочий день: расчёт, трудовая книжка" + (d.pay && !d.payDate ? ", выходное пособие" : "") }, d.payDate && { date: d.payDate, title: "Срок выплаты выходного пособия по соглашению" }].filter(Boolean); },

    fileName(a) { return (a.route === "proposal" ? "Предложение об увольнении по соглашению" : "Соглашение о расторжении трудового договора") + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d64 = spec;
})(typeof window !== "undefined" ? window : globalThis);
