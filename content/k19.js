/*
 * К-19. Семейная налоговая выплата: положена ли и сколько (ориентировочно).
 * Основа: Федеральный закон от 13.07.2024 № 179-ФЗ «О ежегодной семейной выплате гражданам Российской Федерации,
 * имеющим двух и более детей» (с 01.01.2026): работающий родитель, двое и более детей до 18 лет (до 23 лет —
 * при очном обучении), НДФЛ с доходов за прошлый год уплачен по ставке 13%, среднедушевой доход семьи — не выше
 * 1,5 прожиточного минимума на душу населения в регионе за прошлый год, нет долга по алиментам, имущественные
 * критерии — как для единого пособия. Размер — разница между уплаченным НДФЛ и НДФЛ, пересчитанным по ставке 6%.
 * Заявление в СФР (Госуслуги, МФЦ) — с 1 июня по 30 сентября года, следующего за отчётным.
 * Статус: ЧЕРНОВИК, не проверен юристом. Имущественные критерии и точный порядок расчёта не моделируются.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const rub = x => U.money(Math.round(x)) + " ₽";
  const n = x => (typeof x === "number" && x > 0 ? x : 0);

  const spec = {
    id: "k19",
    code: "К-19",
    title: "Семейная налоговая выплата: положена ли и сколько",
    lead: "Семьи с двумя и более детьми могут вернуть часть НДФЛ — разницу между 13% и 6%. Проверим главное условие по доходу и посчитаем примерную сумму.",
    status: "draft",
    actual: "17.11.2026",
    defaults: { members: 4, kids: 2, rate13: "yes", alimony: "no" },

    fields: [
      { id: "kids", type: "number", label: "Детей до 18 лет (или до 23 — очно учатся)", min: 0 },
      { id: "members", type: "number", label: "Всего человек в семье", hint: "Родители (супруги) и дети", min: 1 },
      { id: "family_income", type: "money", label: "Доход всей семьи за прошлый год до вычета налогов", suffix: "₽", hint: "Зарплаты, пособия, пенсии, стипендии, алименты, проценты по вкладам" },
      { id: "pm", type: "money", label: "Прожиточный минимум на душу населения в регионе за прошлый год", suffix: "₽", hint: "Есть на сайте правительства региона или СФР" },
      { id: "my_income", type: "money", label: "Ваша зарплата за прошлый год до вычета НДФЛ", suffix: "₽" },
      { id: "rate13", type: "choice", label: "Весь ваш доход облагался по ставке 13%?", hint: "Если доход больше 2,4 млн ₽ — часть по 15%", options: [{ value: "yes", label: "Да" }, { value: "no", label: "Нет" }] },
      { id: "alimony", type: "choice", label: "Есть долг по алиментам?", options: [{ value: "no", label: "Нет" }, { value: "yes", label: "Есть" }] },
      { id: "refunds", type: "money", label: "Сколько НДФЛ уже вернули вычетами за этот год", suffix: "₽", required: false, hint: "Имущественный, социальный — они уменьшают уплаченный налог" },
    ],

    compute(a) {
      const kids = Math.floor(n(a.kids)), members = Math.max(1, Math.floor(n(a.members)));
      if (!n(a.family_income) || !n(a.pm) || !n(a.my_income)) return null;
      const perCapita = n(a.family_income) / 12 / members;
      const limit = n(a.pm) * 1.5;
      const reasons = [];
      if (kids < 2) reasons.push("Нужно двое и более детей до 18 лет (студентов-очников — до 23).");
      if (perCapita > limit) reasons.push(`Среднедушевой доход ${rub(perCapita)} в месяц больше 1,5 прожиточного минимума (${rub(limit)}).`);
      if (a.rate13 === "no") reasons.push("Выплата — только если доход облагался по ставке 13%.");
      if (a.alimony === "yes") reasons.push("При долге по алиментам выплату не назначают.");
      const paid = n(a.my_income) * 0.13 - n(a.refunds);
      const pay = Math.max(0, Math.round(paid - n(a.my_income) * 0.06));
      const ok = !reasons.length;
      const y = U.today().getFullYear();
      const summary = [
        { label: "Среднедушевой доход в месяц", value: rub(perCapita) },
        { label: "Предел: 1,5 ПМ", value: rub(limit) },
        { label: ok ? "Примерная выплата" : "Выплата", value: ok ? rub(pay) : "не положена", big: true },
      ];
      const notes = ok
        ? [`Выплата — разница между уплаченным НДФЛ и налогом по ставке 6%: примерно 7% вашей зарплаты${n(a.refunds) ? " минус уже возвращённый вычетами налог" : ""}. Точную сумму посчитает Социальный фонд по данным налоговой.`,
          `Заявление — в СФР через Госуслуги, клиентскую службу СФР или МФЦ, с 1 июня по 30 сентября года, следующего за годом дохода. За ${y - 1} год приём в ${y} году ${U.today() > new Date(y, 8, 30) ? "уже закрыт — следующий приём за " + y + " год с 1 июня " + (y + 1) + " года" : "открыт до 30 сентября"}.`,
          "Мы не проверили имущественные критерии (как для единого пособия: не больше одной квартиры с площадью сверх нормы, машины и т. п.) — СФР проверит их сам.",
          "Выплату может получить каждый работающий родитель, если условия выполнены."]
        : reasons;
      return { summary, notes, related: [{ id: "k6", text: "Налоговый вычет: сколько вернут" }, { id: "d101", text: "Вычет на детей у работодателя" }] };
    },
  };

  global.CALCS = global.CALCS || {};
  global.CALCS.k19 = spec;
})(typeof window !== "undefined" ? window : globalThis);
