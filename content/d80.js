(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const POWERS = {
    court: "представлять интересы Доверителя во всех судах судебной системы Российской Федерации, в том числе в арбитражных судах и судах общей юрисдикции всех инстанций, со всеми правами, предоставленными законом истцу, ответчику, третьему лицу, заявителю и заинтересованному лицу, включая право подписывать и подавать исковое заявление, отзыв на исковое заявление, заявление об обеспечении иска, полностью или частично отказываться от исковых требований и признавать иск, изменять основание или предмет иска, заключать мировое соглашение и соглашение по фактическим обстоятельствам, передавать дело в третейский суд, обжаловать судебные акты, требовать принудительного исполнения судебного акта, получать присуждённые денежные средства и иное имущество, знакомиться с материалами дела, подавать документы в электронном виде (ст. 62 АПК РФ, ст. 54 ГПК РФ)",
    tax: "представлять интересы Доверителя в налоговых органах, Социальном фонде России и иных государственных органах и внебюджетных фондах, подписывать и подавать от имени Доверителя заявления, налоговую и иную отчётность, пояснения, возражения и жалобы, получать документы, в том числе в электронном виде",
    bank: "представлять интересы Доверителя в кредитных организациях, сдавать и получать документы, получать выписки и справки по счетам Доверителя (без права распоряжения денежными средствами на счетах)",
    goods: "получать от поставщиков и перевозчиков товарно-материальные ценности, предназначенные Доверителю, подписывать накладные, универсальные передаточные документы и акты приёма-передачи",
    contracts: "вести переговоры, подписывать от имени Доверителя договоры, дополнительные соглашения, акты, счета, претензии и ответы на них, акты сверки",
    post: "получать и отправлять почтовую корреспонденцию Доверителя, в том числе регистрируемые почтовые отправления",
  };

  function derive(a) {
    const ps = (Array.isArray(a.powers) ? a.powers : []).filter(k => POWERS[k]);
    const date = U.date(a.doc_date);
    const until = U.date(a.until) || (date ? U.addDays(U.addMonths(date, 12), -1) : null);
    return { ps, date, until };
  }

  const spec = {
    id: "d80",
    code: "Д-80",
    title: "Доверенность от организации или ИП",
    lead: "На суд, налоговую, банк, получение товара или подписание договоров — с полномочиями, которые суды требуют прописывать отдельно. Подскажем, когда нужен нотариус и когда — машиночитаемая доверенность. Займёт около 3 минут.",
    status: "draft",
    actual: "08.11.2026",
    defaults: { powers: ["contracts"], sub: "no", pr_kind: "org" },

    steps: [
      {
        id: "powers", title: "Полномочия",
        questions: [
          { id: "powers", type: "multi", label: "Что может представитель", options: [
            { value: "court", label: "Суд (арбитраж и суды общей юрисдикции)", hint: "Все специальные полномочия ст. 62 АПК — включая отказ от иска и мировое" },
            { value: "tax", label: "Налоговая, Социальный фонд, госорганы" },
            { value: "bank", label: "Банк — документы и выписки", hint: "Без права распоряжаться деньгами" },
            { value: "goods", label: "Получение товара" },
            { value: "contracts", label: "Переговоры и подписание договоров, актов" },
            { value: "post", label: "Почта" },
          ] },
          { id: "goods_list", type: "text", label: "Какой товар и от кого", required: false, show: (a, d) => d.ps.includes("goods"), placeholder: "кофейное оборудование по счёту № 45 от ООО «Поставка»" },
          { id: "sub", type: "choice", label: "Может передоверить другому?", options: [{ value: "no", label: "Нет" }, { value: "yes", label: "Да" }] },
          { id: "until", type: "date", future: true, label: "Действует до", required: false, hint: "Пусто — год со дня выдачи (ст. 186 ГК)" },
          { id: "city", type: "text", label: "Город", placeholder: "г. Москва" },
          { id: "doc_date", type: "date", future: true, label: "Дата выдачи" },
          { id: "doc_no", type: "text", label: "Номер доверенности", required: false },
        ],
      },
      { id: "principal", title: "Доверитель", questions: C.bizParty("pr", "Доверитель") },
      {
        id: "agent", title: "Представитель",
        questions: [
          { id: "ag_name", type: "text", label: "ФИО представителя" },
          { id: "ag_birth", type: "date", label: "Дата рождения", required: false },
          { id: "ag_passport", type: "text", label: "Паспорт: серия, номер, кем и когда выдан" },
          { id: "ag_pos", type: "text", label: "Должность у доверителя", required: false, placeholder: "юрист" },
        ],
      },
    ],

    derive,

    render(a, d) {
      const P = [];
      P.push({ text: `ДОВЕРЕННОСТЬ${a.doc_no ? ` № ${a.doc_no}` : ""}`, align: "center", bold: true, after: 120 });
      P.push({ text: `${F(a.city, "город")}                                                                          ${F(U.fmtDateLong(d.date), "дата")}`, align: "left", after: 240 });
      const ag = `${F(a.ag_name, "ФИО представителя")}${a.ag_birth ? `, ${U.fmtDate(U.date(a.ag_birth))} г. р.` : ""}, паспорт ${F(a.ag_passport, "паспорт")}${a.ag_pos ? `, ${a.ag_pos}` : ""}`;
      P.push({ indent: true, text: `${C.bizLine(a, "pr", "Доверитель")}, настоящей доверенностью уполномочивает ${ag} (далее — Представитель):`.replace(/^./, c => c.toUpperCase()) });
      d.ps.forEach((k, i) => P.push({ indent: true, text: `${i + 1}) ${POWERS[k]}${k === "goods" && a.goods_list ? `, в том числе: ${a.goods_list}` : ""};` }));
      if (!d.ps.length) P.push({ indent: true, text: F(null, "полномочия") });
      P.push({ indent: true, text: "Для этого Представитель вправе подписывать и подавать заявления, документы и ходатайства, получать документы и совершать иные действия, связанные с выполнением настоящего поручения." });
      P.push({ indent: true, text: `Доверенность выдана без права передоверия` .replace("без права", a.sub === "yes" ? "с правом" : "без права") + ` сроком до ${F(U.fmtDate(d.until), "дата")} включительно.` });
      P.push({ text: `Подпись Представителя ____________ удостоверяю.`, align: "left", before: 240 });
      P.push({ text: `${a.pr_kind === "ip" ? "Индивидуальный предприниматель" : F(a.pr_head_pos, "должность")}            ____________ / ${F(U.shortName(a.pr_kind === "ip" ? a.pr_name : a.pr_head), "И. О. Фамилия")}` + (a.pr_kind === "ip" ? "" : "\nМ. П. (при наличии)"), align: "left", before: 240 });
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (d.ps.includes("court")) g.push({ title: "В арбитраже представитель — только юрист.", text: "С высшим юридическим образованием или учёной степенью (ч. 3 ст. 59 АПК). Диплом или его копию берите в каждое заседание. Руководитель организации может участвовать сам без диплома." });
      if (d.ps.includes("tax") && a.pr_kind === "ip") g.push({ title: "От ИП в налоговую — нотариальная или электронная доверенность.", text: "Простая бумажная доверенность от ИП налоговой не подходит (п. 3 ст. 29 НК). Оформите машиночитаемую доверенность в личном кабинете или у нотариуса." });
      g.push({ title: "Подписывает документы электронно? Нужна МЧД.", text: "С 1 сентября 2024 года работник подписывает отчётность и документы в ЭДО своей электронной подписью вместе с машиночитаемой доверенностью. Её оформляют в сервисе ФНС, на Госуслугах или у оператора ЭДО. Бумажная доверенность для этого не годится." });
      g.push({ title: "Сделки с недвижимостью и регистрация — у нотариуса.", text: "Доверенность на подачу документов в Росреестр, распоряжение зарегистрированными правами и нотариальные сделки удостоверяется нотариально (п. 1 ст. 185.1 ГК)." });
      g.push({ title: "Отменили доверенность — сообщите всем.", text: "Представителю и тем, с кем он должен был взаимодействовать (ст. 189 ГК). Иначе его действия до получения извещения будут обязательны для вас." });
      return g;
    },

    reminders(a, d) { return d.until ? [{ date: U.addDays(d.until, -14), title: `Через 2 недели истекает доверенность: ${a.ag_name || "представитель"}` }] : []; },

    fileName(a) { return "Доверенность" + (a.ag_name ? " — " + U.shortName(a.ag_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d80 = spec;
})(typeof window !== "undefined" ? window : globalThis);
