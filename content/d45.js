      T(`Прошу в срок не позднее пяти рабочих дней со дня получения требования сообщить мне об изменении условий договора (ч. 11 ст. 6.1-2) ${{ email: `по электронной почте ${F(a.buyer_email, "почта")}`, sms: `СМС-сообщением на номер ${F(a.buyer_phone, "телефон")}`, mail: `письмом по адресу: ${F(a.buyer_address, "адрес")}` }[a.notify] || F(null, "способ ответа")}.`);
