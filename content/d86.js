      T(`${F(U.fmtDate(d.bought), "дата")} я приобрёл(а) товар вашего производства: ${F(clean(a.product), "товар")}` + (a.serial ? `, серийный номер ${a.serial}` : "") + `, цена — ${d.price ? C.rubles(d.price) : F(null, "цена")}.`);
      T(`${F(U.fmtDate(d.found), "дата")} обнаружен недостаток: ${F(clean(a.defect), "в чём недостаток")}.`);
      const g = (a.grounds || []).map(k => GROUNDS[k]).filter(Boolean);
