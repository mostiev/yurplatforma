/*
 * Д-79. Решение единственного участника ООО: назначение или продление полномочий директора, распределение прибыли,
 * утверждение годовой отчётности, смена адреса в пределах населённого пункта.
 * Основа: Федеральный закон № 14-ФЗ «Об обществах с ограниченной ответственностью» — ст. 39 (решение оформляется письменно,
 * в случаях, предусмотренных законом, подтверждается нотариально — ред. 287-ФЗ с 01.09.2024), ст. 40 п. 1 (избрание
 * единоличного исполнительного органа — факт принятия решения удостоверяется нотариусом; Р13014 направляет нотариус —
 * ст. 103.10-1 Основ о нотариате, письмо ФНС от 30.08.2024 № КВ-4-14/9965@; продление полномочий того же лица —
 * тоже через нотариуса по позиции ФНП), ст. 28, 29 (распределение прибыли раз в квартал, полугодие или год; выплата —
 * не позднее 60 дней; запреты: УК не оплачен, признаки банкротства, чистые активы меньше УК и резервного фонда),
 * ст. 34 (годовое решение — с 1 марта по 30 апреля), ст. 45 п. 6, 46 п. 9 (не применяются, если единственный участник —
 * директор); ГК РФ ст. 67.1 п. 3 и Обзор ВС от 25.12.2019, п. 3 (прочие решения — нотариус или иной способ, закреплённый
 * в уставе; часть судов допускает простую письменную форму); закон № 129-ФЗ ст. 5 п. 5, ст. 17 (Р13014, 3 рабочих дня);
 * НК РФ ст. 210 п. 2.1, 224 п. 1.1, 226 (НДФЛ с дивидендов: 13% до 2,4 млн ₽, 15% сверх — отдельная совокупность баз).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;
  const num = v => typeof v === "number" && !isNaN(v) ? v : null;

  const KINDS = {
    director: "Назначить директора",
    prolong: "Продлить полномочия директора",
    dividends: "Распределить прибыль (дивиденды)",
    annual: "Утвердить годовую отчётность",
    address: "Сменить адрес в том же городе",
  };

  function derive(a) {
    const ks = (Array.isArray(a.kinds) ? a.kinds : []).filter(k => KINDS[k]);
    const notary = ks.includes("director") || ks.includes("prolong");
    const div = num(a.div_sum);
    const tax = div ? Math.round(div <= 2400000 ? div * 0.13 : 312000 + (div - 2400000) * 0.15) : 0;
    const date = U.date(a.doc_date);
    return { ks, notary, div, tax, date, payBy: date ? U.addDays(date, 60) : null };
  }

  const spec = {
    id: "d79",
    code: "Д-79",
    title: "Решение единственного участника ООО",
    lead: "Назначение или продление полномочий директора, дивиденды, годовая отчётность, смена адреса — одним решением. Подскажем, где с 2024 года обязателен нотариус и что подавать в налоговую. Займёт около 5 минут.",
    status: "draft",
    actual: "08.11.2026",
    defaults: { kinds: ["prolong"], term_years: 5, period: "year", charter_method: "unknown" },

    steps: [
      {
        id: "what", title: "Что решаем",
        questions: [
          { id: "kinds", type: "multi", label: "Вопросы", options: Object.entries(KINDS).map(([value, label]) => ({ value, label, hint: value === "director" || value === "prolong" ? "С 01.09.2024 — только у нотариуса" : null })) },
          { id: "dir_name", type: "text", label: "ФИО директора", show: (a, d) => d.notary },
          { id: "dir_pos", type: "text", label: "Должность", show: (a, d) => d.notary, placeholder: "Генеральный директор" },
          { id: "term_years", type: "number", label: "Срок полномочий, лет", min: 1, show: (a, d) => d.notary, hint: "Как в уставе. Если в уставе срок не указан — можно назначить бессрочно, впишите 0", validate: v => v < 0 ? "Не меньше 0" : null, required: false },
          { id: "dir_from", type: "date", future: true, label: "С какой даты", show: (a, d) => d.notary },
          { id: "period", type: "choice", label: "За какой период прибыль", show: (a, d) => d.ks.includes("dividends"), options: [
            { value: "year", label: "За год" }, { value: "half", label: "За полугодие" }, { value: "quarter", label: "За квартал" },
          ] },
          { id: "period_text", type: "text", label: "Период", show: (a, d) => d.ks.includes("dividends"), placeholder: "2025 год" },
          { id: "div_sum", type: "money", label: "Сколько направить на дивиденды", suffix: "₽", show: (a, d) => d.ks.includes("dividends") },
          { id: "annual_year", type: "text", label: "Отчётность за год", show: (a, d) => d.ks.includes("annual"), placeholder: "2025" },
          { id: "new_address", type: "text", label: "Новый адрес", show: (a, d) => d.ks.includes("address"), placeholder: "г. Москва, ул. Ленина, д. 5, пом. II, комн. 3" },
          { id: "address_basis", type: "text", label: "Основание пользования помещением", show: (a, d) => d.ks.includes("address"), placeholder: "договор аренды от 01.10.2026 № 12" },
          { id: "charter_method", type: "choice", label: "В уставе указан способ подтверждения решений без нотариуса?", show: (a, d) => d.ks.some(k => k !== "director" && k !== "prolong"), hint: "По позиции Верховного суда без такого пункта решение безопаснее удостоверить у нотариуса (п. 3 ст. 67.1 ГК)", options: [
            { value: "yes", label: "Да — подпись участника" }, { value: "unknown", label: "Нет или не знаю" },
          ] },
        ],
      },
      {
        id: "company", title: "Общество и участник",
        questions: [
          { id: "org_name", type: "text", label: "Полное наименование ООО", placeholder: "Общество с ограниченной ответственностью «Ромашка»" },
          { id: "org_inn", type: "text", label: "ИНН", validate: v => /^\d{10}$/.test(String(v).trim()) ? null : "10 цифр" },
          { id: "org_ogrn", type: "text", label: "ОГРН", validate: v => /^\d{13}$/.test(String(v).trim()) ? null : "13 цифр" },
          { id: "org_address", type: "text", label: "Адрес ООО" },
          { id: "owner", type: "text", label: "Единственный участник (ФИО)", placeholder: "Иванов Иван Иванович" },
          { id: "owner_passport", type: "text", label: "Паспорт участника", placeholder: "45 12 345678, выдан ГУ МВД России по г. Москве 01.02.2020" },
          { id: "doc_no", type: "text", label: "Номер решения", required: false, placeholder: "3" },
          { id: "city", type: "text", label: "Город", placeholder: "г. Москва" },
          { id: "doc_date", type: "date", future: true, label: "Дата решения" },
        ],
      },
    ],

    derive,

    stop: null,

    render(a, d) {
      const P = [];
      P.push({ text: `РЕШЕНИЕ${a.doc_no ? ` № ${a.doc_no}` : ""}`, align: "center", bold: true, after: 0 });
      P.push({ text: `единственного участника ${F(a.org_name, "наименование ООО")}`, align: "center", after: 120 });
      P.push({ text: `${F(a.city, "город")}                                                                          ${F(U.fmtDateLong(d.date), "дата")}`, align: "left", after: 240 });
      P.push({ indent: true, text: `Я, ${F(a.owner, "ФИО участника")}, паспорт ${F(a.owner_passport, "паспорт")}, являясь единственным участником ${F(a.org_name, "ООО")} (ИНН ${F(a.org_inn, "ИНН")}, ОГРН ${F(a.org_ogrn, "ОГРН")}, адрес: ${F(a.org_address, "адрес")}; далее — Общество), в соответствии со ст. 39 Федерального закона «Об обществах с ограниченной ответственностью»` });
      P.push({ text: "РЕШИЛ:", align: "left", bold: true, before: 120, after: 120 });
      let n = 0; const T = t => { n++; P.push({ text: `${n}. ${t}`, indent: true }); };
      const term = num(a.term_years);
      const termText = term ? `сроком на ${term} ${C.plural(term, "год", "года", "лет")}` : "без ограничения срока";
      if (d.ks.includes("director")) T(`Избрать (назначить) на должность «${F(a.dir_pos, "должность")}» Общества ${F(a.dir_name, "ФИО директора")} ${termText} с ${F(U.fmtDate(U.date(a.dir_from)), "дата")}. Полномочия прежнего единоличного исполнительного органа прекращаются с этой даты.`);
      if (d.ks.includes("prolong")) T(`Продлить полномочия единоличного исполнительного органа Общества (${F(a.dir_pos, "должность")}) ${F(a.dir_name, "ФИО директора")} ${termText} с ${F(U.fmtDate(U.date(a.dir_from)), "дата")}.`);
      if (d.ks.includes("annual")) T(`Утвердить годовую бухгалтерскую (финансовую) отчётность Общества за ${F(a.annual_year, "год")} год.`);
      if (d.ks.includes("dividends")) {
        T(`Направить на выплату дивидендов часть чистой прибыли Общества за ${F(a.period_text, "период")} в размере ${d.div ? C.rubles(d.div) : F(null, "сумма")}. Выплатить дивиденды единственному участнику в денежной форме не позднее ${F(U.fmtDate(d.payBy), "дата")} (п. 3 ст. 28 Закона) с удержанием налога на доходы физических лиц.`);
        T("Подтверждаю, что на дату решения уставный капитал Общества оплачен полностью, Общество не отвечает признакам несостоятельности (банкротства) и они не появятся в результате выплаты, стоимость чистых активов не меньше уставного капитала и резервного фонда и не станет меньше в результате выплаты (ст. 29 Закона).");
      }
      if (d.ks.includes("address")) {
        T(`Изменить адрес Общества в пределах места нахождения Общества на: ${F(a.new_address, "новый адрес")}. Основание пользования помещением: ${F(a.address_basis, "основание")}.`);
        T("Поручить единоличному исполнительному органу Общества представить в регистрирующий орган заявление по форме Р13014 в течение 3 рабочих дней.");
      }
      if (d.ks.length && d.ks.every(k => k !== "director" && k !== "prolong") && a.charter_method === "yes") T("Подписание настоящего решения единственным участником является способом подтверждения его принятия, предусмотренным уставом Общества (подп. 3 п. 3 ст. 67.1 ГК РФ).");
      if (!d.ks.length) T(F(null, "выберите вопросы"));
      P.push({ text: `Единственный участник ____________ / ${F(U.shortName(a.owner), "И. О. Фамилия")}`, align: "left", before: 360 });
      if (d.notary) P.push({ text: "Принятие решения и состав участника, присутствовавшего при его принятии, подлежат удостоверению нотариусом (п. 1 ст. 40 Закона, ст. 103.10-1 Основ законодательства РФ о нотариате). Не подписывайте решение до визита к нотариусу.", align: "left", before: 240 });
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (d.notary) g.push(
        { title: "Решение о директоре — только у нотариуса.", text: "С 1 сентября 2024 года нотариус удостоверяет решение и сам на следующий рабочий день отправляет в налоговую форму Р13014 (при смене директора). Возьмите этот проект, паспорт, устав, свидетельства (листы записи) ОГРН и ИНН, документы о прежних решениях — нотариус сверит и оформит." },
        { title: "Продление тому же директору — тоже через нотариуса.", text: "Форму Р13014 подавать не нужно: сведения в ЕГРЮЛ не меняются. Но без нотариуса решение могут счесть недействительным." },
      );
      if (d.ks.includes("dividends")) g.push({ title: `НДФЛ с дивидендов — ${U.money(d.tax)} ₽.`, text: "13% до 2,4 млн ₽ за год, 15% сверх — отдельно от зарплаты. ООО удерживает налог при выплате и перечисляет его: удержанный с 1 по 22 число — до 28-го, с 23-го — до 5-го числа следующего месяца. Платите дивиденды не чаще раза в квартал и только при положительных чистых активах." });
      if (d.ks.some(k => k !== "director" && k !== "prolong") && a.charter_method !== "yes") g.push({ title: "Остальные решения — подпись участника или нотариус.", text: "Верховный суд считает, что решения единственного участника подтверждаются у нотариуса, если устав не предусматривает другой способ. Надёжнее один раз внести в устав пункт «подписание решения участником» (это изменение — через нотариуса), и дальше решения не потребуют визитов." });
      if (d.ks.includes("annual")) g.push({ title: "Годовое решение — с 1 марта по 30 апреля.", text: "Ст. 34 закона об ООО. Аудит малому ООО не нужен, если выручка и активы ниже порогов закона об аудите." });
      if (d.ks.includes("address")) g.push({ title: "Новый адрес — заявление Р13014 в 3 рабочих дня.", text: "Подаётся на сайте ФНС с электронной подписью директора, через МФЦ или нотариуса. В тот же город устав менять не нужно. Приложите документ на помещение." });
      return g;
    },

    reminders(a, d) {
      const ev = [];
      if (d.ks.includes("dividends") && d.payBy) ev.push({ date: d.payBy, title: "Последний день выплаты дивидендов (60 дней)" });
      if (d.ks.includes("address") && d.date) ev.push({ date: C.addWorkdays(d.date, 3), title: "Подать Р13014 о смене адреса" });
      const term = num(a.term_years), from = U.date(a.dir_from);
      if (d.notary && term && from) ev.push({ date: U.addMonths(from, term * 12 - 1), title: "Через месяц истекают полномочия директора — продлить у нотариуса" });
      return ev;
    },

    fileName(a) { return "Решение единственного участника" + (a.org_name ? " — " + String(a.org_name).replace(/^Общество с ограниченной ответственностью\s*/i, "ООО ").replace(/[«»"]/g, "").slice(0, 30) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d79 = spec;
})(typeof window !== "undefined" ? window : globalThis);
