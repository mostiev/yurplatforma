      g.push({ title: "Ответ — в течение 10 рабочих дней.", text: "Старший пристав выносит постановление по жалобе (ст. 126). Отказали или не ответили — жалоба в управление ФССП по региону или административный иск в районный суд в течение 10 рабочих дней (ст. 218, 219 КАС). Если одновременно подать в суд, рассмотрение жалобы приостанавливается." });
