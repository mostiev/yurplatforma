/*
 * Д-83. Договор дарения квартиры (или доли) между гражданами — с передаточным актом.
 * Основа: ГК РФ — ст. 572 (безвозмездность; встречное предоставление делает договор притворным), 574 (письменная форма;
 * регистрируется переход права), 575 (от имени малолетних и недееспособных дарить нельзя), 576 (дарение совместного
 * имущества — с согласия супруга), 577 (отказ от исполнения обещания), 578 (отмена дарения; п. 4 — право отменить, если
 * даритель переживёт одаряемого), 292 (права проживающих); закон № 218-ФЗ ч. 1.1 ст. 42, ч. 2 ст. 54 (нотариус — для доли
 * и имущества ребёнка); СК РФ ст. 35 п. 3, ст. 36 (подаренное — личная собственность одаряемого); НК РФ ст. 217 п. 18.1
 * (освобождены члены семьи и близкие родственники: супруги, родители и дети, в т. ч. усыновители и усыновлённые,
 * дедушки, бабушки и внуки, полнородные и неполнородные братья и сёстры), ст. 224 (13% до 2,4 млн ₽, 15% сверх),
 * ст. 333.33 (пошлина за регистрацию).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;
  const num = v => typeof v === "number" && !isNaN(v) ? v : null;
  const CLOSE = { spouse: "супруг(а)", child: "сын или дочь", parent: "мать или отец", grand: "внук или внучка", grandparent: "бабушка или дедушка", sibling: "брат или сестра" };

  function derive(a) {
    const close = !!CLOSE[a.relation];
    const cad = num(a.cad_value);
    const tax = !close && cad ? Math.round(cad <= 2400000 ? cad * 0.13 : 312000 + (cad - 2400000) * 0.15) : 0;
    return { close, cad, tax, notary: C.notaryRequired(a), date: U.date(a.doc_date) };
  }

  const spec = {
    id: "d83",
    code: "Д-83",
    title: "Договор дарения квартиры",
    lead: "Подарить квартиру или долю родственнику или другому человеку: договор, передаточный акт, расчёт налога для одаряемого и что делать, если нужен нотариус. Займёт около 5 минут.",
    status: "draft",
    actual: "30.10.2026",
    defaults: { shares: "one", minor_owner: "no", married: "no", relation: "child", stay: "no", revoke: "no" },

    steps: [
      { id: "flat", title: "Квартира", questions: [...C.flatQuestions({ gift: true }), { id: "cad_value", type: "money", label: "Кадастровая стоимость", suffix: "₽", required: false, hint: "Для расчёта налога одаряемого, если он не близкий родственник" }] },
      {
        id: "terms", title: "Условия",
        questions: [
          { id: "relation", type: "select", label: "Кем одаряемый приходится дарителю", options: [...Object.entries(CLOSE).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })), { value: "other", label: "Другой родственник или не родственник", hint: "Одаряемый платит НДФЛ" }] },
          { id: "stay", type: "choice", label: "Даритель остаётся жить в квартире?", options: [{ value: "no", label: "Нет" }, { value: "yes", label: "Да, сохраняет право пожизненно" }] },
          { id: "revoke", type: "choice", label: "Вернуть квартиру дарителю, если одаряемый умрёт раньше?", hint: "Можно предусмотреть в договоре (п. 4 ст. 578 ГК)", options: [{ value: "no", label: "Нет" }, { value: "yes", label: "Да" }] },
          { id: "city", type: "text", label: "Город", placeholder: "г. Москва" },
          { id: "doc_date", type: "date", future: true, label: "Дата договора" },
        ],
      },
      { id: "donor", title: "Даритель", questions: C.personFields("dn", "даритель") },
      { id: "donee", title: "Одаряемый", questions: C.personFields("de", "одаряемый") },
    ],

    derive,

    render(a, d) {
      const P = [];
      let n = 0;
      const T = t => { n++; P.push({ text: `${n}. ${t}`, indent: true }); };
      const sign = () => P.push({ table: { widths: [4677, 4678], head: 1, rows: [["Даритель", "Одаряемый"], [`${F(a.dn_name, "ФИО")}\n\n____________ / ${F(U.shortName(a.dn_name), "И. О. Фамилия")}`, `${F(a.de_name, "ФИО")}\n\n____________ / ${F(U.shortName(a.de_name), "И. О. Фамилия")}`]] } });
      if (d.notary) P.push({ text: "ПРОЕКТ ДЛЯ НОТАРИУСА", align: "right", bold: true, after: 120 });
      P.push({ text: "ДОГОВОР ДАРЕНИЯ КВАРТИРЫ", align: "center", bold: true, after: 120 });
      P.push({ text: `${F(a.city, "город")}                                                                          ${F(U.fmtDateLong(d.date), "дата")}`, align: "left", after: 240 });
      P.push({ indent: true, text: `${C.personLine(a, "dn", "Даритель")}, и ${C.personLine(a, "de", "Одаряемый")}, заключили настоящий договор о нижеследующем.` });
      T(`Даритель безвозмездно передаёт в собственность Одаряемому, а Одаряемый принимает в дар ${C.flatLine(a)} (далее — Квартира).`);
      T(`Квартира принадлежит Дарителю на праве собственности на основании: ${F(a.own_doc, "основание")}.`);
      T("Даритель заверяет, что Квартира не продана, не заложена, в споре и под арестом не состоит, свободна от прав третьих лиц, кроме указанных в договоре.");
      T(a.married === "yes" ? "Нотариально удостоверенное согласие супруга Дарителя на дарение Квартиры получено (п. 3 ст. 35 СК РФ) и прилагается." : "Даритель заверяет, что согласие супруга на дарение Квартиры не требуется.");
      T(a.stay === "yes"
        ? `Даритель сохраняет право пожизненного пользования Квартирой и регистрации в ней (п. 1 ст. 558, ст. 292 ГК РФ). Иных лиц, сохраняющих право пользования, нет.`
        : "Лиц, сохраняющих право пользования Квартирой после её перехода к Одаряемому, нет.");
      if (a.revoke === "yes") T("Даритель вправе отменить дарение, если переживёт Одаряемого (п. 4 ст. 578 ГК РФ).");
      T("Квартира передаётся по передаточному акту. Право собственности Одаряемого возникает с момента государственной регистрации перехода права (ст. 131, 574 ГК РФ). Расходы на регистрацию несёт Одаряемый.");
      T(`Договор составлен в двух экземплярах${d.notary ? " и подлежит нотариальному удостоверению" : ""}.`);
      sign();
      P.push({ pageBreak: true });
      P.push({ text: "ПЕРЕДАТОЧНЫЙ АКТ", align: "center", bold: true, after: 0 });
      P.push({ text: `к договору дарения квартиры от ${F(U.fmtDate(d.date), "дата")}`, align: "center", after: 240 });
      P.push({ indent: true, text: `Даритель ${F(a.dn_name, "ФИО")} передал, а Одаряемый ${F(a.de_name, "ФИО")} принял квартиру по адресу: ${F(a.address, "адрес")}, кадастровый номер ${F(a.cadastral, "номер")}, и ключи от неё. Претензий стороны не имеют.` });
      sign();
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (d.notary) g.push({ title: "Дарение доли или имущества ребёнка — у нотариуса.", text: `Пошлина — 0,5% стоимости, но не больше 20 000 ₽, плюс техническая работа по тарифу палаты.${a.minor_owner === "yes" ? " От имени ребёнка дарить нельзя (ст. 575 ГК)." : ""}` });
      g.push(d.close
        ? { title: "Налога нет.", text: "Близкие родственники и члены семьи освобождены от НДФЛ при получении квартиры в дар (п. 18.1 ст. 217 НК). Декларацию подавать не нужно." }
        : { title: `Одаряемому — НДФЛ${d.tax ? ` около ${U.money(d.tax)} ₽` : ""}.`, text: "13% от кадастровой стоимости (15% с суммы свыше 2,4 млн ₽). Декларация 3-НДФЛ — до 30 апреля следующего года, оплата — до 15 июля. Иногда выгоднее купля-продажа — но притворное «дарение за деньги» суд признает куплей-продажей." });
      g.push(
        { title: "Регистрация — в МФЦ или онлайн.", text: "Пошлина 4 000 ₽ (если кадастровая стоимость до 20 млн ₽). Договор сам не регистрируется — только переход права." },
        { title: "Подаренная квартира — не совместная собственность.", text: "Она остаётся личной собственностью одаряемого и при разводе не делится (ст. 36 СК)." },
      );
      return g;
    },

    fileName(a) { return "Договор дарения квартиры" + (a.address ? " — " + String(a.address).slice(0, 30) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d83 = spec;
})(typeof window !== "undefined" ? window : globalThis);
