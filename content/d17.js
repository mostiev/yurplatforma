/*
 * Д-17. Претензия о возмещении ущерба от залива квартиры.
 * Виновник — сосед (собственник/наниматель): ст. 15, 1064 ГК РФ, ч. 4 ст. 30 ЖК РФ.
 * Виновник — управляющая компания (авария на общем имуществе: стояки до первого отключающего устройства, кровля):
 *   ч. 2.3 ст. 161 ЖК РФ, п. 5 Правил содержания общего имущества (ПП РФ № 491), ст. 14 Закона РФ № 2300-1,
 *   штраф п. 6 ст. 13. Акт о заливе — п. 152 Правил № 354 (не позднее 12 часов с момента обращения в АДС).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  function derive(a) {
    const damage = typeof a.damage === "number" ? a.damage : null;
    const extra = (typeof a.appraisal === "number" ? a.appraisal : 0) + (typeof a.other_costs === "number" ? a.other_costs : 0);
    const total = damage != null ? Math.round((damage + extra) * 100) / 100 : null;
    return { damage, extra, total, uk: a.culprit === "uk", flood: U.date(a.flood_date) };
  }

  const spec = {
    id: "d17",
    code: "Д-17",
    title: "Претензия о возмещении ущерба от залива квартиры",
    lead: "Затопили соседи сверху или прорвало общий стояк, протекла крыша — требуем возместить ремонт. Займёт около 7 минут.",
    status: "draft",

    steps: [
      {
        id: "what", title: "Залив",
        questions: [
          { id: "flood_date", type: "date", label: "Когда произошёл залив?" },
          { id: "culprit", type: "choice", label: "Кто виноват?", hint: "Обычно это видно из акта о заливе", options: [
            { value: "neighbor", label: "Соседи", hint: "Сорвало шланг стиральной машины, забыли кран, прорвало трубу после их крана" },
            { value: "uk", label: "Управляющая компания", hint: "Прорвало общий стояк, протекла крыша, засор общей канализации" },
            { value: "unknown", label: "Пока непонятно" },
          ] },
          { id: "act", type: "choice", label: "Управляющая компания составила акт о заливе?", hint: "Она обязана сделать это не позднее 12 часов после вашего обращения в аварийную службу", options: [
            { value: "yes", label: "Да" }, { value: "no", label: "Нет" },
          ] },
          { id: "act_date", type: "date", label: "Дата акта", show: a => a.act === "yes" },
          { id: "cause", type: "text", label: "Причина залива по акту", placeholder: "Разрыв гибкой подводки к смесителю в кв. 49", show: a => a.act === "yes" },
          { id: "damage_desc", type: "textarea", label: "Что повреждено?", placeholder: "Кухня: потолок — пятна и отслоение краски; обои на стене 3 м² отошли; ламинат вздулся 6 м². Повреждён кухонный гарнитур" },
        ],
      },
      {
        id: "money", title: "Сумма",
        questions: [
          { id: "estimate_type", type: "choice", label: "Как оценён ущерб?", options: [
            { value: "appraiser", label: "Отчёт независимого оценщика", hint: "Самый сильный вариант для суда" },
            { value: "smeta", label: "Смета ремонтной организации" },
            { value: "own", label: "Мой расчёт по чекам и ценам" },
          ] },
          { id: "estimate_doc", type: "text", label: "Номер и дата отчёта или сметы", placeholder: "Отчёт об оценке № 123/26 от 20.09.2026, ООО «Оценка-Про»", show: a => a.estimate_type !== "own" },
          { id: "damage", type: "money", label: "Стоимость восстановительного ремонта и повреждённого имущества", suffix: "₽", min: 1 },
          { id: "appraisal", type: "money", label: "Сколько заплатили оценщику?", suffix: "₽", required: false, show: a => a.estimate_type === "appraiser" },
          { id: "other_costs", type: "money", label: "Другие расходы из-за залива", hint: "Химчистка, сушка, аренда жилья на время ремонта. Оставьте пустым, если нет", suffix: "₽", required: false },
          C.refundQuestion(),
        ],
      },
      {
        id: "parties", title: "Стороны",
        questions: [
          { id: "to_name", type: "text", label: "Кому претензия", hint: "ФИО соседа-собственника или название управляющей компании", placeholder: "Сидоров Сидор Сидорович / ООО «УК Жилкомфорт»" },
          { id: "to_address", type: "text", label: "Адрес", hint: "Для соседа — адрес его квартиры" },
          { id: "my_address", type: "text", label: "Адрес вашей квартиры, которую залили" },
          ...C.personQuestions(),
        ],
      },
    ],

    derive,

    stop(a) {
      if (a.culprit === "unknown") return { title: "Сначала нужно понять, кто виноват", text: "Вызовите управляющую компанию и потребуйте акт о заливе с указанием причины — это её обязанность. Если причина в квартире соседа после его крана — претензия соседу, если в общем стояке или кровле — управляющей компании. Если УК отказывается составлять акт, зафиксируйте залив с двумя соседями и сделайте фото." };
      return null;
    },

    render(a, d) {
      const P = [];
      C.header({ name: a.to_name, nameLabel: "кому", address: a.to_address }, C.from(a), P);
      C.title(P, "ПРЕТЕНЗИЯ", "о возмещении ущерба, причинённого заливом квартиры");
      P.push({ text: `${F(U.fmtDate(d.flood), "дата залива")} произошёл залив принадлежащей мне квартиры по адресу: ${F(a.my_address, "адрес")}.` + (a.act === "yes" ? ` Согласно акту от ${F(U.fmtDate(U.date(a.act_date)), "дата акта")}, причиной залива является: ${F(a.cause, "причина")}.` : ""), indent: true });
      P.push({ text: `В результате залива повреждено: ${F(a.damage_desc, "что повреждено")}.`, indent: true });
      const est = { appraiser: `отчётом независимого оценщика (${F(a.estimate_doc, "отчёт")})`, smeta: `сметой (${F(a.estimate_doc, "смета")})`, own: "расчётом, составленным по документам о стоимости работ и материалов" }[a.estimate_type] || F(null, "чем подтверждается");
      P.push({ text: `Стоимость восстановительного ремонта и повреждённого имущества составляет ${F(U.money(d.damage), "сумма")} руб., что подтверждается ${est}.` + (typeof a.appraisal === "number" && a.appraisal > 0 ? ` Расходы на оценку составили ${U.money(a.appraisal)} руб.` : "") + (typeof a.other_costs === "number" && a.other_costs > 0 ? ` Иные расходы, вызванные заливом, — ${U.money(a.other_costs)} руб.` : ""), indent: true });

      if (d.uk) {
        P.push({ text: `Залив произошёл вследствие ненадлежащего содержания общего имущества многоквартирного дома, за которое отвечает управляющая организация (ч. 2.3 ст. 161 Жилищного кодекса РФ, п. 5 Правил содержания общего имущества в многоквартирном доме, утв. постановлением Правительства РФ от 13.08.2006 № 491). Вред, причинённый имуществу потребителя вследствие недостатков услуги, подлежит возмещению в полном объёме (ст. 14 ${C.LAW_ZOZPP}).`, indent: true });
        P.push({ text: "ТРЕБУЮ:", indent: true, keepNext: true });
        P.push({ text: `возместить причинённый ущерб и расходы в общей сумме ${F(U.money(d.total), "сумма")} руб. ${C.refundText(a.refund_method)} в течение 10 дней со дня получения настоящей претензии.`, indent: true });
        P.push({ text: C.courtThreat("none"), indent: true });
      } else {
        P.push({ text: "Собственник помещения обязан поддерживать его в надлежащем состоянии и несёт ответственность за вред, причинённый вследствие ненадлежащего содержания находящегося в нём оборудования (ч. 4 ст. 30 Жилищного кодекса РФ). Вред, причинённый имуществу гражданина, подлежит возмещению в полном объёме лицом, причинившим вред (ст. 1064 Гражданского кодекса РФ); лицо, право которого нарушено, вправе требовать полного возмещения убытков (ст. 15 ГК РФ).", indent: true });
        P.push({ text: "ПРОШУ:", indent: true, keepNext: true });
        P.push({ text: `в добровольном порядке возместить причинённый ущерб и расходы в общей сумме ${F(U.money(d.total), "сумма")} руб. ${C.refundText(a.refund_method)} в течение 10 дней со дня получения настоящей претензии.`, indent: true });
        P.push({ text: "В противном случае я буду вынужден(а) обратиться в суд с иском о возмещении ущерба, а также расходов на оценку, государственную пошлину и иных судебных расходов.", indent: true });
      }

      const att = [];
      if (a.act === "yes") att.push("Копия акта о заливе.");
      if (a.estimate_type === "appraiser") att.push("Копия отчёта об оценке.", "Копия документа об оплате услуг оценщика.");
      if (a.estimate_type === "smeta") att.push("Копия сметы.");
      att.push("Фотографии повреждений.", "Копия документа о праве собственности на квартиру.");
      C.attachments(P, att);
      C.sign(P, a);
      return P;
    },

    guidance(a, d) {
      const g = [
        { title: "Не делайте ремонт до осмотра и оценки.", text: "Позовите виновника на осмотр телеграммой или письмом с датой и временем. Оценщик должен увидеть повреждения до ремонта." },
        { title: "Сфотографируйте всё сразу.", text: "Потолок, стены, пол, мебель, технику — с датой. Сохраните повреждённые вещи до оценки." },
      ];
      if (a.act === "no") g.push({ title: "Требуйте акт у управляющей компании.", text: "Позвоните в аварийную службу и запишите номер заявки. Акт должны составить не позднее 12 часов с момента обращения. Отказываются — зафиксируйте залив с двумя соседями." });
      if (!d.uk) g.push({ title: "Если сосед — наниматель, а не собственник.", text: "Претензию можно направить и собственнику квартиры, и нанимателю: суд определит, кто отвечает." });
      if (d.uk) g.push({ title: "С управляющей компании можно взыскать штраф 50%.", text: "Если УК не заплатит добровольно, суд добавит к сумме штраф по закону о защите прав потребителей. Госпошлину потребитель не платит при цене иска до 1 млн ₽." });
      return g;
    },

    fileName(a) { return "Претензия о заливе" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d17 = spec;
})(typeof window !== "undefined" ? window : globalThis);
