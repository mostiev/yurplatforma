/*
 * М-04. Требование вернуть паспорт и другие документы иностранного гражданина + заявление в полицию.
 * Основа: ТК РФ — ч. 1 ст. 65 и ст. 327.3 (при приёме на работу документы предъявляются работодателю, а не передаются
 * ему); закон не даёт работодателю, посреднику или арендодателю права удерживать документы, удостоверяющие личность.
 * Заявление в полицию — ст. 144 УПК РФ (приём, регистрация и проверка сообщения о преступлении, талон-уведомление);
 * конкретную квалификацию даёт полиция. Признаки принуждения к труду, лишения свободы, требования денег —
 * сразу в полицию (112). Норма КоАП о паспорте (ст. 19.17) касается паспорта гражданина и в тексте не используется.
 * Статус: ЧЕРНОВИК, не проверен юристом. Раздел повышенного риска.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const DOCS_ = {
    passport: "национальный паспорт",
    card: "миграционная карта",
    patent: "патент",
    notice: "отрывная часть уведомления о прибытии",
    dms: "полис добровольного медицинского страхования",
    other: null,
  };
  const HOLDER = { employer: "работодатель", agent: "посредник (кадровое агентство, бригадир)", landlord: "арендодатель", other: "другое лицо" };

  function derive(a) {
    const docs = (a.docs || []).map(k => k === "other" ? a.docs_other : DOCS_[k]).filter(Boolean);
    return { docs, since: U.date(a.since_date), coercion: a.coercion === "yes", police: a.coercion === "yes" || a.police === "yes" };
  }

  const spec = {
    id: "m04",
    code: "М-04",
    title: "Вернуть паспорт и документы",
    lead: "Работодатель, посредник или арендодатель забрал паспорт, патент или миграционную карту и не отдаёт. Составим письменное требование и заявление в полицию. Займёт около 7 минут.",
    status: "draft",
    disclaimer: "Документы составлены по вашим ответам и не являются юридической консультацией. Если вас удерживают, угрожают или заставляют работать — звоните 112, не ждите ответа на требование.",

    steps: [
      {
        id: "what", title: "Что случилось",
        questions: [
          { id: "coercion", type: "choice", label: "Вас не отпускают, угрожают или заставляют работать?", options: [
            { value: "no", label: "Нет, просто не отдают документы" },
            { value: "yes", label: "Да", hint: "Сразу подготовим заявление в полицию. Если опасность прямо сейчас — звоните 112" },
          ] },
          { id: "holder_type", type: "choice", label: "У кого документы?", options: Object.entries(HOLDER).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })) },
          { id: "holder", type: "text", label: "Кто именно: организация или ФИО", placeholder: "ООО «Склад-Сервис», бригадир Рахимов Б." },
          { id: "holder_address", type: "text", label: "Адрес", required: false, hint: "Где работаете или где вы отдали документы" },
          { id: "docs", type: "multi", label: "Какие документы не отдают?", options: Object.entries(DOCS_).map(([value, label]) => ({ value, label: label ? label[0].toUpperCase() + label.slice(1) : "Другое" })) },
          { id: "docs_other", type: "text", label: "Какие ещё", show: a => (a.docs || []).includes("other"), placeholder: "трудовой договор" },
          { id: "since_date", type: "date", label: "Когда вы их отдали" },
          { id: "story", type: "textarea", label: "Как это произошло", required: false, hint: "Коротко: зачем забрали, что обещали, что говорят сейчас",
            placeholder: "Забрали при приёме на работу «для оформления», обещали вернуть через неделю. С 10.09.2026 отказываются отдавать, пока не отработаю ещё месяц." },
          { id: "money", type: "choice", label: "За возврат требуют деньги или отработку?", options: [
            { value: "no", label: "Нет" },
            { value: "yes", label: "Да" },
          ] },
          { id: "police", type: "choice", label: "Подготовить сразу и заявление в полицию?", show: a => a.coercion !== "yes", options: [
            { value: "no", label: "Нет, сначала требование" },
            { value: "yes", label: "Да" },
          ] },
          { id: "police_dept", type: "text", label: "Отдел полиции", required: false, show: a => a.coercion === "yes" || a.police === "yes", hint: "Можно не указывать — впишете в дежурной части", placeholder: "ОМВД России по району Хамовники г. Москвы" },
        ],
      },
      {
        id: "you", title: "Вы",
        questions: [
          { id: "buyer_name", type: "text", label: "Фамилия, имя, отчество (при наличии)", placeholder: "Каримов Азиз Рустамович" },
          { id: "citizenship", type: "text", label: "Гражданство", placeholder: "Республика Узбекистан" },
          { id: "birth_date", type: "date", label: "Дата рождения" },
          { id: "passport_no", type: "text", label: "Номер паспорта, если помните", required: false, placeholder: "FA 1234567" },
          { id: "buyer_address", type: "text", label: "Где вы живёте сейчас" },
          { id: "buyer_phone", type: "tel", label: "Телефон" },
        ],
      },
    ],

    derive,

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      const docsText = d.docs.length ? d.docs.join(", ") : F(null, "какие документы");
      const me = `${F(a.buyer_name, "ФИО")}, гражданин(ка) ${F(a.citizenship, "гражданство")}, ${F(U.fmtDate(U.date(a.birth_date)), "дата рождения")} г. р.` + (a.passport_no ? `, паспорт ${a.passport_no}` : "");
      const story = a.story ? String(a.story).trim().replace(/\.$/, "") + "." : "";
      const fromBlock = `от ${F(a.buyer_name, "ФИО")}\nгражданство: ${F(a.citizenship, "гражданство")}\nадрес: ${F(a.buyer_address, "адрес")}\nтел.: ${F(a.buyer_phone, "телефон")}`;

      if (!d.coercion) {
        P.push({ text: `Кому: ${F(a.holder, "кто удерживает документы")}` + (a.holder_address ? `\nАдрес: ${a.holder_address}` : ""), align: "left", leftIndent: 4500, after: 120 });
        P.push({ text: fromBlock, align: "left", leftIndent: 4500, after: 360 });
        C.title(P, "ТРЕБОВАНИЕ", "о возврате документов");
        T(`${F(U.fmtDate(d.since), "дата")} я передал(а) вам ${a.holder_type === "employer" ? "при оформлении на работу " : ""}следующие документы: ${docsText}. Документы до сих пор не возвращены.` + (story ? ` ${story}` : ""));
        if (a.money === "yes") T("Возврат документов вы обусловливаете уплатой денег или выполнением работы. Такие условия незаконны.");
        T(a.holder_type === "employer"
          ? "Работодатель не вправе удерживать документы работника. При приёме на работу документы, в том числе документ, удостоверяющий личность, и патент, только предъявляются работодателю (ч. 1 ст. 65, ст. 327.3 Трудового кодекса РФ). Закон не предоставляет работодателю права хранить их у себя или удерживать."
          : "Никто не вправе удерживать документы, удостоверяющие личность, и миграционные документы другого человека. Закон не предоставляет вам права хранить их у себя или удерживать.");
        T("Без этих документов я не могу подтвердить свою личность и законность пребывания в Российской Федерации, что грозит мне привлечением к ответственности.");
        P.push({ text: "ТРЕБУЮ:", indent: true, keepNext: true });
        T(`немедленно, не позднее следующего дня после получения настоящего требования, вернуть мне документы: ${docsText}.`);
        T("В случае невозврата я обращусь в полицию" + (a.holder_type === "employer" ? ", государственную инспекцию труда" : "") + " и прокуратуру.");
        C.sign(P, a);
      }

      if (d.police) {
        if (!d.coercion) P.push({ pageBreak: true });
        P.push({ text: `Начальнику\n${a.police_dept || "________________________________"}`, align: "left", leftIndent: 4500, after: 120 });
        P.push({ text: fromBlock, align: "left", leftIndent: 4500, after: 360 });
        P.push({ text: "ЗАЯВЛЕНИЕ", align: "center", bold: true, after: 240 });
        T(`Я, ${me}, сообщаю следующее. ${F(U.fmtDate(d.since), "дата")} я передал(а) свои документы: ${docsText}. Документы получил(а) и не возвращает: ${F(a.holder, "кто удерживает документы")}` + (HOLDER[a.holder_type] ? ` (${HOLDER[a.holder_type]})` : "") + (a.holder_address ? `, адрес: ${a.holder_address}` : "") + "." + (story ? ` ${story}` : ""));
        if (a.money === "yes") T("За возврат документов от меня требуют деньги или выполнения работы.");
        if (d.coercion) T("Мне угрожают, не отпускают и (или) принуждают к работе.");
        T("Без документов я не могу подтвердить свою личность и законность пребывания в Российской Федерации.");
        P.push({ text: "ПРОШУ:", indent: true, keepNext: true });
        T("1. Провести проверку по изложенным фактам в порядке ст. 144 УПК РФ и принять меры к возврату моих документов.");
        T("2. Привлечь виновных лиц к ответственности, предусмотренной законом.");
        T("3. Выдать мне талон-уведомление о принятии заявления и сообщить о принятом решении.");
        C.sign(P, a);
      }
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (d.coercion) g.push({ title: "Если опасность прямо сейчас — звоните 112.", text: "Звонок бесплатный с любого телефона, в том числе без сим-карты." });
      if (!d.coercion) g.push({ title: "Вручите требование под подпись или отправьте письмом.", text: "Сделайте второй экземпляр и попросите поставить отметку о получении. Если отказываются — отправьте заказным письмом с описью или отправьте фото требования в мессенджер и сохраните переписку." });
      if (d.police) g.push({ title: "Заявление в полицию — в любой отдел, круглосуточно.", text: "Дежурная часть обязана принять заявление и выдать талон-уведомление. Сохраните его: он подтверждает, что вы сообщили о пропаже документов." });
      g.push(
        { title: "Сохраните всё, что подтверждает передачу документов.", text: "Переписку, свидетелей, фото. Если есть копии паспорта и патента — держите их при себе." },
        { title: "Обратитесь в посольство или консульство своей страны.", text: "Там помогут и, если паспорт не вернут, выдадут документ для возвращения на родину или новый паспорт." },
        { title: "Патент и регистрация продолжают действовать.", text: "Платите за патент вовремя, даже пока нет документов: пропуск оплаты прекращает патент." },
      );
      if (a.holder_type === "employer") g.push({ title: "Жалоба в трудовую инспекцию.", text: "Если работодатель не отдаёт документы и не платит — жалоба в инспекцию (Д-26) и требование о зарплате (Д-27)." });
      return g;
    },

    fileName(a) { return (a.coercion === "yes" ? "Заявление в полицию" : "Требование вернуть документы") + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.m04 = spec;
})(typeof window !== "undefined" ? window : globalThis);
