/*
 * Д-29. Договор возмездного оказания услуг (выполнения работ) для самозанятого исполнителя.
 * Основа: ГК РФ — ст. 779 (договор возмездного оказания услуг), ст. 781 (оплата в сроки и порядке договора),
 * ст. 782 (отказ заказчика с оплатой фактических расходов исполнителя; отказ исполнителя с возмещением убытков),
 * ст. 783 (общие положения о подряде, в т. ч. о приёмке — ст. 720), ст. 395. Федеральный закон от 27.11.2018 № 422-ФЗ
 * (ред. 04.08.2026): ч. 3 ст. 14 (чек — в момент расчёта, при безналичном расчёте не наличными/ЭСП — не позднее 9-го
 * числа следующего месяца), п. 8 ч. 6 ст. 14 (ИНН заказчика-организации в чеке), пп. 8 п. 2 ст. 6 (доход от
 * работодателя или бывшего работодателя менее двух лет — не облагается НПД), пп. 8 ч. 2 ст. 4 (лимит 2,4 млн ₽ в год).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  function derive(a) {
    const price = typeof a.price === "number" ? a.price : null;
    const prepay = typeof a.prepay_pct === "number" && price ? Math.round(price * a.prepay_pct / 100 * 100) / 100 : null;
    return { price, prepay, signed: U.date(a.doc_date), deadline: U.date(a.deadline) };
  }

  const spec = {
    id: "d29",
    code: "Д-29",
    title: "Договор оказания услуг для самозанятого",
    lead: "Договор самозанятого с заказчиком: что сделать, сроки, цена, предоплата, приёмка и чек. Для дизайнеров, разработчиков, репетиторов, фотографов и всех, кто работает на НПД. Займёт около 7 минут.",
    status: "draft",
    disclaimer: "Договор составлен по вашим ответам и не является юридической консультацией.",

    steps: [
      {
        id: "work", title: "Работа",
        questions: [
          { id: "subject", type: "textarea", label: "Что вы делаете для заказчика?", hint: "Конкретно: что, в каком объёме, в каком виде результат", placeholder: "Разработка дизайна сайта: главная страница и 5 внутренних страниц, макеты в Figma" },
          { id: "deadline", type: "date", future: true, label: "Срок выполнения" },
          { id: "price", type: "money", label: "Цена", suffix: "₽", min: 1 },
          { id: "pay", type: "choice", label: "Порядок оплаты", options: [
            { value: "after", label: "После подписания акта" },
            { value: "prepay", label: "Предоплата, остаток после акта" },
            { value: "full_prepay", label: "100% предоплата" },
          ] },
          { id: "prepay_pct", type: "number", label: "Предоплата, %", min: 1, show: a => a.pay === "prepay", validate: v => v >= 100 ? "Меньше 100" : null },
          { id: "pay_days", type: "number", label: "За сколько дней оплатить после акта (или счёта)?", min: 1, hint: "Обычно 5 рабочих дней" },
          { id: "accept_days", type: "number", label: "Сколько дней у заказчика на проверку и подписание акта?", min: 1, hint: "Если не подпишет и не пришлёт возражений — работа считается принятой" },
          { id: "rights", type: "choice", label: "Результат — объект авторских прав (дизайн, текст, код, фото)?", options: [
            { value: "alienate", label: "Да, права переходят заказчику" },
            { value: "license", label: "Да, заказчик получает лицензию, права остаются у меня" },
            { value: "none", label: "Нет, это услуга без такого результата" },
          ] },
          { id: "former_employer", type: "choice", label: "Заказчик был вашим работодателем за последние 2 года?", options: [
            { value: "no", label: "Нет" },
            { value: "yes", label: "Да" },
          ] },
          { id: "city", type: "text", label: "Город", placeholder: "г. Москва" },
          { id: "doc_date", type: "date", future: true, label: "Дата договора" },
        ],
      },
      { id: "me", title: "Вы", questions: C.freelancerQuestions() },
      { id: "client", title: "Заказчик", questions: C.clientQuestions() },
    ],

    derive,

    stop(a) {
      if (a.former_employer === "yes") return { title: "С бывшим работодателем в первые 2 года НПД не применяется.", text: "Такой доход не облагается налогом на профессиональный доход (пп. 8 п. 2 ст. 6 закона № 422-ФЗ). Работать можно, но налог будет другим — НДФЛ, который удержит заказчик. Уточните у бухгалтера заказчика." };
      return null;
    },

    render(a, d) {
      const P = [];
      const H = t => P.push({ text: t, align: "center", bold: true, before: 180, after: 60, keepNext: true });
      const T = t => P.push({ text: t, indent: true });
      P.push({ text: "ДОГОВОР ВОЗМЕЗДНОГО ОКАЗАНИЯ УСЛУГ", align: "center", bold: true, after: 120 });
      P.push({ text: `${F(a.city, "город")}                                                                          ${F(U.fmtDateLong(d.signed), "дата")}`, align: "left", after: 240 });
      T(`${C.clLine(a)}, именуемый(ая) в дальнейшем «Заказчик», с одной стороны, и ${C.exLine(a)}, именуемый(ая) в дальнейшем «Исполнитель», с другой стороны, заключили настоящий договор о нижеследующем.`);
      H("1. Предмет договора");
      T(`1.1. Исполнитель обязуется по заданию Заказчика оказать услуги (выполнить работы): ${F(a.subject ? String(a.subject).trim().replace(/\.$/, "") : null, "что делаете")}, а Заказчик обязуется принять и оплатить их.`);
      T(`1.2. Срок оказания услуг — не позднее ${F(U.fmtDate(d.deadline), "срок")}.`);
      T("1.3. Исполнитель оказывает услуги лично, самостоятельно определяет способы их оказания и не подчиняется правилам внутреннего трудового распорядка Заказчика.");
      H("2. Цена и порядок расчётов");
      T(`2.1. Цена услуг составляет ${d.price ? C.rubles(d.price) : F(null, "цена")}. НДС не облагается: Исполнитель применяет специальный налоговый режим «Налог на профессиональный доход».`);
      if (a.pay === "full_prepay") T(`2.2. Заказчик вносит 100% цены в течение ${F(a.pay_days, "число")} рабочих дней со дня подписания договора.`);
      else if (a.pay === "prepay") T(`2.2. Заказчик вносит предоплату ${F(a.prepay_pct, "процент")}% цены (${F(d.prepay != null ? U.money(d.prepay) : null, "сумма")} руб.) в течение ${F(a.pay_days, "число")} рабочих дней со дня подписания договора, оставшуюся часть — в течение ${F(a.pay_days, "число")} рабочих дней со дня подписания акта.`);
      else T(`2.2. Заказчик оплачивает услуги в течение ${F(a.pay_days, "число")} рабочих дней со дня подписания акта.`);
      T("2.3. Оплата производится на банковский счёт Исполнителя по реквизитам, указанным в разделе 7. Исполнитель формирует и передаёт Заказчику чек в порядке, установленном ст. 14 Федерального закона от 27.11.2018 № 422-ФЗ.");
      T("2.4. Исполнитель обязуется сообщить Заказчику об утрате права на применение налога на профессиональный доход в течение 3 рабочих дней.");
      H("3. Сдача и приёмка");
      T(`3.1. По завершении Исполнитель направляет Заказчику результат и акт. Заказчик в течение ${F(a.accept_days, "число")} рабочих дней подписывает акт или направляет мотивированный отказ с перечнем замечаний.`);
      T(`3.2. Если в срок, указанный в п. 3.1, Заказчик не подписал акт и не направил мотивированный отказ, услуги считаются оказанными и принятыми в полном объёме.`);
      T("3.3. Замечания в пределах задания Исполнитель устраняет безвозмездно в согласованный срок.");
      if (a.rights !== "none") {
        H("4. Интеллектуальные права");
        T(a.rights === "alienate"
          ? "4.1. Исключительное право на результат переходит к Заказчику в полном объёме с момента полной оплаты. Вознаграждение за отчуждение права включено в цену услуг."
          : "4.1. Исключительное право на результат остаётся у Исполнителя. С момента полной оплаты Заказчик получает простую (неисключительную) лицензию на использование результата любыми способами для своих целей на весь срок действия исключительного права на территории всего мира. Вознаграждение включено в цену услуг.");
      }
      const n = a.rights !== "none" ? 5 : 4;
      H(`${n}. Ответственность и расторжение`);
      T(`${n}.1. За просрочку оплаты Заказчик уплачивает проценты по ст. 395 ГК РФ.`);
      T(`${n}.2. Заказчик вправе отказаться от договора, оплатив Исполнителю фактически понесённые расходы и стоимость уже оказанных услуг (ст. 782 ГК РФ).`);
      T(`${n}.3. Споры разрешаются переговорами; претензионный порядок обязателен, срок ответа на претензию — 10 рабочих дней. Далее — в суде по месту нахождения ответчика.`);
      H(`${n + 1}. Заключительные положения`);
      T(`${n + 1}.1. Стороны признают юридическую силу документов и сообщений, направленных по электронной почте и в мессенджерах по контактам, указанным в договоре, в том числе сканов подписанных документов.`);
      T(`${n + 1}.2. Договор составлен в двух экземплярах, по одному для каждой стороны.`);
      H(`${n + 2}. Реквизиты и подписи`);
      P.push({ text: `Заказчик:\n${C.clRequisites(a)}\n\n____________ / ______________`, align: "left", after: 240 });
      P.push({ text: `Исполнитель:\n${C.exRequisites(a)}\n\n____________ / ${F(U.shortName(a.ex_name), "И. О. Фамилия")}`, align: "left" });
      return P;
    },

    guidance(a) {
      return [
        { title: "Чек — обязательно.", text: "В «Мой налог»: при оплате картой или переводом от физлица — сразу; от организации безналично — не позднее 9-го числа следующего месяца. С ИНН заказчика-организации. Без чека заказчик-организация рискует доначислением НДФЛ и страховых взносов с выплат вам." },
        { title: "Следите за лимитом 2,4 млн ₽ в год.", text: "При превышении право на НПД теряется до конца года." },
        { title: "Не превращайте договор в трудовой.", text: "Нет графика, подчинения и «должности» — только результат и сроки. Иначе налоговая может переквалифицировать отношения." },
        { title: "После работы — акт (Д-30) и счёт (Д-31).", text: "Если не платят — претензия (Д-32)." },
      ];
    },

    fileName(a) { return "Договор оказания услуг" + (a.cl_name ? " — " + String(a.cl_name).replace(/[«»"]/g, "").slice(0, 30) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d29 = spec;
})(typeof window !== "undefined" ? window : globalThis);
