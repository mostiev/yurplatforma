    const paused = of && oc && oc >= of ? U.daysBetween(of, oc) : 0;
    // по платежам со сроком раньше этой даты давность истекла (п. 24 Пленума № 43; ст. 204 ГК — время у мирового судьи не считается)
    // п. 3 ст. 204 ГК: если после отмены приказа осталось меньше 6 месяцев, срок удлиняется до 6 месяцев. Поэтому при иске,
    // поданном в течение 6 месяцев после отмены, сохраняются все платежи, срок по которым не истёк на день заявления о приказе
    const ext = !!(filed && paused >= 0 && of && oc && oc >= of && filed <= U.addMonths(oc, 6));
    const boundary = !filed ? null : ext ? U.addMonths(of, -36) : U.addDays(U.addMonths(filed, -36), -paused);
    const last = U.date(a.last_due);
    const allBarred = !!(has("limitation") && boundary && last && last < boundary);
    const partBarred = !!(has("limitation") && boundary && last && last >= boundary && a.schedule === "yes");
    const claim = num(a.claim_sum), penaltySum = num(a.penalty_sum);
    // всего с учётом суммы займа: 100% с 01.04.2026, 130% с 01.07.2023, 150% с 01.01.2020, 2-кратный размер с 01.07.2019,
    // 2,5-кратный с 28.01.2019 (554-ФЗ от 27.12.2018); для более ранних договоров предел не считаем
