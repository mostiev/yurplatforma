  function parseKids(text) {
    return String(text || "").split("\n").map(s => s.trim()).filter(Boolean).map(line => {
      const p = line.split(/\s*;\s*/);
      const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(p[1] || "");
      return { name: p[0], birth: m ? U.date(`${m[3]}-${m[2]}-${m[1]}`) : null, raw: line };
    });
  }
