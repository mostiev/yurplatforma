/*
 * Д-15. Заявление о перерасчёте платы за коммунальные услуги.
 * Основа: Правила предоставления коммунальных услуг, утв. ПП РФ от 06.05.2011 № 354:
 *  — ненадлежащее качество / перерывы сверх допустимых: разд. IX–X (пп. 98, 105–111), Приложение 1
 *    (горячая вода: перерыв 8 ч в месяц суммарно, 4 ч единовременно, 24 ч при аварии на тупиковой магистрали;
 *    снижение платы 0,15% за каждый час сверх допустимого);
 *  — временное отсутствие: разд. VIII (пп. 86–93): только без ИПУ при технической невозможности установки,
 *    более 5 полных календарных дней подряд, заявление до начала или не позднее 30 дней после окончания,
 *    перерасчёт в течение 5 рабочих дней; не пересчитываются отопление, электроснабжение, ОДН;
 *  — неправильное начисление: ч. 6 ст. 157 ЖК РФ (штраф 50% превышения) — формулировку сверяет юрист.
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const SERVICES = {
    hot: "горячее водоснабжение", cold: "холодное водоснабжение", heat: "отопление", power: "электроснабжение", gas: "газоснабжение", sewer: "водоотведение",
  };
  const RULES = "Правил предоставления коммунальных услуг собственникам и пользователям помещений в многоквартирных домах и жилых домов, утв. постановлением Правительства РФ от 06.05.2011 № 354 (далее — Правила)";

  function derive(a) {
    const from = U.date(a.from_date), to = U.date(a.to_date);
    const days = from && to ? U.daysBetween(from, to) + 1 : null; // включительно
    const fullDays = from && to ? U.daysBetween(from, to) - 1 : null; // полные дни между датами выезда и возвращения
    const today = U.today();
    const lateAbsence = a.reason === "absence" && to ? U.daysBetween(to, today) > 30 : false;
    const tooShort = a.reason === "absence" && fullDays != null && fullDays <= 5;
    return { from, to, days, fullDays, today, lateAbsence, tooShort };
  }

  const spec = {
    id: "d15",
    code: "Д-15",
    title: "Заявление о перерасчёте платы за ЖКУ",
    lead: "Не было горячей воды, холодные батареи, начислили лишнее или вы долго не жили дома — просим пересчитать плату. Займёт около 5 минут.",
    status: "draft",

    steps: [
      {
        id: "reason", title: "Причина",
        questions: [
          { id: "reason", type: "choice", label: "Почему нужен перерасчёт?", options: [
            { value: "quality", label: "Услугу не предоставляли или она была плохого качества", hint: "Нет горячей воды, холодные батареи, слабый напор, отключения" },
            { value: "wrong", label: "Начислили неправильно", hint: "Ошибка в показаниях, лишние жильцы, услуга, которой нет" },
            { value: "absence", label: "Я долго не жил(а) дома", hint: "Работает только в квартире без счётчиков" },
          ] },
          { id: "service", type: "select", label: "Какая услуга?", show: a => a.reason === "quality", options: Object.entries(SERVICES).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })) },
          { id: "quality_desc", type: "textarea", label: "Что было не так?", placeholder: "Горячей воды не было с 10:00 12.09 до 18:00 14.09 без предупреждения", show: a => a.reason === "quality" },
          { id: "ads", type: "choice", label: "Вы сообщали в аварийно-диспетчерскую службу?", hint: "С этого момента услуга считается некачественной, если проверка это подтвердит", show: a => a.reason === "quality", options: [
            { value: "yes", label: "Да" }, { value: "no", label: "Нет" },
          ] },
          { id: "ads_no", type: "text", label: "Номер и время регистрации обращения", placeholder: "№ 1234 от 12.09.2026, 10:15", show: a => a.ads === "yes" },
          { id: "check_act", type: "choice", label: "Составили акт проверки?", show: a => a.reason === "quality", options: [
            { value: "executor", label: "Да, с представителем управляющей компании" },
            { value: "neighbors", label: "Да, без УК: с двумя соседями и председателем совета дома" },
            { value: "no", label: "Нет" },
          ] },
          { id: "wrong_desc", type: "textarea", label: "Что начислено неправильно?", placeholder: "В квитанции за август начислено 340 м³ холодной воды, по счётчику 12 м³ — фото показаний прилагаю", show: a => a.reason === "wrong" },
          { id: "overcharge", type: "money", label: "На сколько, по вашему расчёту, завышена плата?", suffix: "₽", min: 1, required: false, show: a => a.reason === "wrong" },
          { id: "no_meters", type: "choice", label: "В квартире нет счётчиков, и их нельзя установить технически?", hint: "Перерасчёт за отсутствие делают только в этом случае; нужен акт обследования", show: a => a.reason === "absence", options: [
            { value: "yes", label: "Да, есть акт о технической невозможности" },
            { value: "no", label: "Нет, счётчики есть или их можно поставить" },
          ] },
          { id: "absence_docs", type: "text", label: "Чем подтверждаете отсутствие?", placeholder: "Билеты, командировочное удостоверение, справка из санатория", show: a => a.reason === "absence" },
        ],
      },
      {
        id: "period", title: "Период",
        questions: [
          { id: "from_date", type: "date", label: "С какого дня?" },
          { id: "to_date", type: "date", label: "По какой день?", validate: (v, a) => a.from_date && v < a.from_date ? "Не раньше начала" : null },
          { id: "account", type: "text", label: "Номер лицевого счёта", hint: "Есть в квитанции" },
          { id: "address", type: "text", label: "Адрес квартиры" },
        ],
      },
      {
        id: "parties", title: "Стороны",
        lead: "Заявление подаётся тому, кто выставляет квитанцию: управляющей компании, ТСЖ или ресурсоснабжающей организации.",
        questions: [
          { id: "org_name", type: "text", label: "Кому", placeholder: "ООО «УК Жилкомфорт»" },
          C.innQuestion("org_inn"),
          { id: "org_address", type: "text", label: "Адрес организации" },
          ...C.personQuestions(),
        ],
      },
    ],

    derive,

    stop(a, d) {
      if (a.reason === "absence" && a.no_meters === "no") return { title: "Перерасчёт за отсутствие не положен", text: "Если в квартире есть счётчики или их можно установить, платите по показаниям — за время отсутствия они почти не изменятся. Перерасчёт по п. 86 Правил № 354 делают только без счётчиков при технической невозможности их установки." };
      if (d.tooShort) return { title: "Нужно отсутствовать больше 5 полных дней", text: "Перерасчёт положен при отсутствии более 5 полных календарных дней подряд, не считая дней выезда и возвращения (п. 86 Правил № 354)." };
      if (d.lateAbsence) return { title: "Срок подачи заявления прошёл", text: "Заявление о перерасчёте за отсутствие подают до отъезда или не позднее 30 дней после возвращения (п. 91 Правил № 354)." };
      return null;
    },

    render(a, d) {
      const P = [];
      C.header({ name: a.org_name, nameLabel: "организация", inn: a.org_inn, address: a.org_address }, C.from(a), P);
      C.title(P, "ЗАЯВЛЕНИЕ", "о перерасчёте платы за коммунальные услуги");
      P.push({ text: `Я являюсь потребителем коммунальных услуг по адресу: ${F(a.address, "адрес")}, лицевой счёт № ${F(a.account, "лицевой счёт")}. Отношения по предоставлению коммунальных услуг регулируются ${RULES}.`, indent: true });
      const period = `с ${F(U.fmtDate(d.from), "дата")} по ${F(U.fmtDate(d.to), "дата")}`;

      if (a.reason === "quality") {
        P.push({ text: `В период ${period} коммунальная услуга «${F(SERVICES[a.service], "услуга")}» предоставлялась ненадлежащего качества и (или) с перерывами, превышающими допустимую продолжительность: ${F(a.quality_desc, "что было")}.`, indent: true });
        if (a.ads === "yes") P.push({ text: `Об этом я сообщил(а) в аварийно-диспетчерскую службу; обращение зарегистрировано: ${F(a.ads_no, "номер и время")} (пп. 105–106 Правил).`, indent: true });
        if (a.check_act === "executor") P.push({ text: "Факт нарушения качества зафиксирован в акте проверки, составленном с участием вашего представителя (п. 109 Правил).", indent: true });
        if (a.check_act === "neighbors") P.push({ text: "Поскольку ваш представитель на проверку не явился, акт о нарушении качества составлен и подписан двумя потребителями и председателем совета многоквартирного дома (п. 110(1) Правил).", indent: true });
        P.push({ text: `В соответствии с разделом IX Правил и Приложением № 1 к ним, за период предоставления коммунальной услуги ненадлежащего качества и (или) с перерывами сверх допустимой продолжительности размер платы подлежит снижению.`, indent: true });
        P.push({ text: "ПРОШУ:", indent: true, keepNext: true });
        P.push({ text: `1. Произвести перерасчёт (снизить размер платы) за коммунальную услугу «${F(SERVICES[a.service], "услуга")}» за указанный период в порядке, установленном Приложением № 1 к Правилам, и отразить его в ближайшем платёжном документе.\n2. Предоставить письменный расчёт суммы перерасчёта.`, indent: true });
      }
      if (a.reason === "wrong") {
        P.push({ text: `За период ${period} плата за коммунальные услуги начислена неправильно: ${F(a.wrong_desc, "что неправильно")}.` + (typeof a.overcharge === "number" ? ` По моему расчёту, плата завышена на ${U.money(a.overcharge)} руб.` : ""), indent: true });
        P.push({ text: `Исполнитель обязан производить расчёт размера платы в соответствии с Правилами. Лицо, нарушившее порядок расчёта платы за коммунальные услуги, что повлекло необоснованное увеличение её размера, обязано уплатить потребителю штраф в размере 50% величины превышения начисленной платы над размером платы, которую надлежало начислить (ч. 6 ст. 157 Жилищного кодекса РФ).`, indent: true });
        P.push({ text: "ПРОШУ:", indent: true, keepNext: true });
        P.push({ text: "1. Проверить правильность начисления платы за указанный период и произвести перерасчёт.\n2. Предоставить письменный расчёт.\n3. В случае подтверждения нарушения — уплатить штраф, предусмотренный ч. 6 ст. 157 ЖК РФ, путём снижения размера платы.", indent: true });
      }
      if (a.reason === "absence") {
        P.push({ text: `В период ${period} (${d.fullDays} полных календарных дней) я временно отсутствовал(а) в жилом помещении. Помещение не оборудовано индивидуальными приборами учёта; техническая возможность их установки отсутствует, что подтверждается актом обследования.`, indent: true });
        P.push({ text: `Отсутствие подтверждается следующими документами: ${F(a.absence_docs, "документы")}.`, indent: true });
        P.push({ text: `На основании пп. 86, 90–93 Правил ПРОШУ произвести перерасчёт размера платы за коммунальные услуги, подлежащие перерасчёту, за период моего отсутствия в течение 5 рабочих дней после получения настоящего заявления (п. 91 Правил).`, indent: true });
      }

      P.push({ text: "Ответ прошу направить в письменной форме по адресу, указанному выше.", indent: true });
      const att = [];
      if (a.reason === "quality" && a.check_act !== "no") att.push("Копия акта проверки качества коммунальной услуги.");
      if (a.reason === "wrong") att.push("Копия платёжного документа.", "Фото показаний приборов учёта (при наличии).");
      if (a.reason === "absence") att.push("Документы, подтверждающие временное отсутствие.", "Копия акта об отсутствии технической возможности установки приборов учёта.");
      C.attachments(P, att);
      C.sign(P, a);
      return P;
    },

    guidance(a) {
      const g = [
        { title: "Подайте заявление письменно.", text: "Лично в офис УК с отметкой на вашем экземпляре, ценным письмом с описью, через личный кабинет УК или ГИС ЖКХ." },
      ];
      if (a.reason === "quality") g.push({ title: "Главное доказательство — обращение в аварийную службу и акт.", text: "В следующий раз сразу звоните в диспетчерскую, записывайте номер обращения и требуйте проверку. Если УК не пришла, акт можно составить с двумя соседями и председателем совета дома." });
      if (a.reason === "absence") g.push({ title: "Не всё пересчитывают.", text: "За время отсутствия не пересчитывают отопление, электроснабжение, газ на отопление и плату за общедомовые нужды (п. 88 Правил № 354)." });
      g.push({ title: "Отказали или молчат больше 30 дней.", text: "Жалоба в государственную жилищную инспекцию (документ Д-16) и в Роспотребнадзор." });
      return g;
    },

    fileName(a) { return "Заявление о перерасчёте" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d15 = spec;
})(typeof window !== "undefined" ? window : globalThis);
