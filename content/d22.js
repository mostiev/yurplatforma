/*
 * Д-22. Проект соглашения об уплате алиментов на несовершеннолетних детей (для нотариального удостоверения).
 * Основа: СК РФ — ст. 99 (соглашение между плательщиком и получателем; за несовершеннолетнего — законный представитель),
 * п. 1 ст. 100 (письменная форма, нотариальное удостоверение обязательно), п. 2 ст. 100 (нотариальное соглашение имеет
 * силу исполнительного листа), п. 2 ст. 103 (размер на несовершеннолетних не ниже, чем при взыскании в суде: 1/4, 1/3, 1/2
 * по п. 1 ст. 81), ст. 104 (способы: доля, твёрдая сумма, периодически или единовременно, имуществом, комбинация),
 * ст. 105 (индексация — по соглашению, иначе по ст. 117 — пропорционально росту ПМ), п. 1 ст. 115 (ответственность по
 * соглашению — только как в соглашении; 0,1% по п. 2 — для алиментов по решению суда). Статус: ЧЕРНОВИК, не проверен юристом. Документ — проект для нотариуса.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const SHARE = { 1: 0.25, 2: 1 / 3 };
  const shareText = n => n >= 3 ? "половины" : n === 2 ? "одной трети" : "одной четверти";

  function parseKids(text) {
    return String(text || "").split("\n").map(s => s.trim()).filter(Boolean).map(line => {
      const p = line.split(/\s*;\s*/);
      const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(p[1] || "");
      return { name: p[0], birth: m ? U.date(`${m[3]}-${m[2]}-${m[1]}`) : null, raw: line };
    });
  }

  function derive(a) {
    const kids = parseKids(a.kids).filter(k => k.name && k.birth);
    const n = kids.length;
    const minShare = n >= 3 ? 0.5 : SHARE[n] || null;
    const income = typeof a.income === "number" ? a.income : null;
    const minAmount = minShare && income ? Math.round(income * minShare * 100) / 100 : null;
    let tooLow = false;
    if (a.method === "share" && typeof a.share_pct === "number" && minShare) tooLow = a.share_pct < Math.round(minShare * 10000) / 100 - 1e-9; // 33,33% на двоих — допустимо
    if (a.method === "fixed" && typeof a.fixed === "number" && minAmount) tooLow = a.fixed < minAmount;
    return { kids, n, minShare, minAmount, tooLow };
  }

  const spec = {
    id: "d22",
    code: "Д-22",
    title: "Соглашение об уплате алиментов",
    lead: "Родители договорились, сколько и как платить на детей. Проект соглашения, который удостоверит нотариус — тогда он действует как исполнительный лист. Займёт около 7 минут.",
    status: "draft",
    actual: "30.10.2026",
    disclaimer: "Это проект. Соглашение об алиментах действительно только после нотариального удостоверения; нотариус проверит его и может изменить формулировки.",

    steps: [
      {
        id: "kids", title: "Дети и размер",
        questions: [
          { id: "kids", type: "textarea", label: "Дети", hint: "Каждый с новой строки: ФИО; дата рождения", placeholder: "Петров Иван Петрович; 01.02.2016",
            validate: v => { const bad = parseKids(v).filter(k => !k.name || !k.birth); return bad.length ? `Не получилось прочитать: «${bad[0].raw}». Формат: ФИО; ДД.ММ.ГГГГ` : null; } },
          { id: "method", type: "choice", label: "Как платить?", options: [
            { value: "share", label: "Процент от дохода плательщика" },
            { value: "fixed", label: "Твёрдая сумма каждый месяц" },
          ] },
          { id: "share_pct", type: "number", label: "Сколько процентов дохода?", suffix: "%", min: 1, show: a => a.method === "share",
            hint: "Не меньше, чем присудил бы суд: 25% на одного ребёнка, 33,33% на двух, 50% на трёх и больше" },
          { id: "fixed", type: "money", label: "Сумма в месяц", suffix: "₽", min: 1, show: a => a.method === "fixed" },
          { id: "income", type: "money", label: "Доход плательщика в месяц после налога", suffix: "₽", required: false, show: a => a.method === "fixed",
            hint: "Для проверки: твёрдая сумма не должна быть меньше доли, которую присудил бы суд" },
          { id: "index", type: "choice", label: "Индексировать твёрдую сумму?", show: a => a.method === "fixed", options: [
            { value: "pm", label: "Да, по росту прожиточного минимума на детей", hint: "Так по закону, если в соглашении не сказано иное" },
            { value: "none", label: "Нет, сумма фиксированная", hint: "Можно, но при росте цен дети теряют" },
          ] },
          { id: "pay_day", type: "number", label: "До какого числа месяца платить?", min: 1, validate: v => v > 28 ? "Не позже 28-го" : null },
          { id: "how", type: "choice", label: "Куда платить?", options: [
            { value: "card", label: "На счёт получателя", hint: "Реквизиты впишете" },
            { value: "child", label: "На счёт, открытый на имя ребёнка" },
          ] },
          { id: "until", type: "choice", label: "До какого времени?", options: [
            { value: "adult", label: "До совершеннолетия каждого ребёнка" },
          ] },
          { id: "penalty", type: "number", label: "Неустойка за просрочку, % в день", suffix: "% в день", required: false, hint: "Ответственность по соглашению — только та, что в нём записана (п. 1 ст. 115 СК). Обычно ставят 0,1% в день — как по закону при алиментах по решению суда" },
        ],
      },
      {
        id: "parties", title: "Стороны",
        questions: [
          { id: "payer_name", type: "text", label: "Плательщик: ФИО" },
          { id: "payer_birth", type: "date", label: "Дата рождения" },
          { id: "payer_passport", type: "text", label: "Паспорт" },
          { id: "payer_address", type: "text", label: "Адрес регистрации" },
          { id: "payer_job", type: "text", label: "Место работы", required: false },
          { id: "rec_name", type: "text", label: "Получатель (второй родитель): ФИО" },
          { id: "rec_birth", type: "date", label: "Дата рождения" },
          { id: "rec_passport", type: "text", label: "Паспорт" },
          { id: "rec_address", type: "text", label: "Адрес регистрации" },
          { id: "city", type: "text", label: "Город", placeholder: "г. Москва" },
        ],
      },
    ],

    derive,

    stop(a, d) {
      if (d.tooLow) return { title: "Размер ниже, чем присудил бы суд.", text: `Закон этого не разрешает (п. 2 ст. 103 СК): на ${d.n} ${d.n === 1 ? "ребёнка" : "детей"} — не меньше ${shareText(d.n)} дохода` + (d.minAmount ? ` (при вашем доходе — ${U.money(d.minAmount)} ₽ в месяц)` : "") + ". Нотариус такое соглашение не удостоверит. Увеличьте размер — или взыщите алименты через суд.", link: { href: "d23.html", text: "Взыскать алименты через суд →" } };
      return null;
    },

    render(a, d) {
      const P = [];
      const H = t => P.push({ text: t, align: "center", bold: true, before: 180, after: 60, keepNext: true });
      const T = t => P.push({ text: t, indent: true });
      const who = (p, role) => `${F(a[p + "_name"], "ФИО")}, ${F(U.fmtDate(U.date(a[p + "_birth"])), "дата рождения")} г. р., паспорт ${F(a[p + "_passport"], "паспорт")}, зарегистрированный(ая) по адресу: ${F(a[p + "_address"], "адрес")}, именуемый(ая) в дальнейшем «${role}»`;
      const kidsTxt = d.kids.length ? d.kids.map(k => `${k.name}, ${U.fmtDate(k.birth)} г. р.`).join("; ") : F(null, "дети");
      P.push({ text: "СОГЛАШЕНИЕ ОБ УПЛАТЕ АЛИМЕНТОВ\nна содержание несовершеннолетних детей", align: "center", bold: true, after: 120 });
      P.push({ text: `${F(a.city, "город")}                                                                          «___» ____________ 20__ г.`, align: "left", after: 240 });
      T(`${who("payer", "Плательщик")}, с одной стороны, и ${who("rec", "Получатель")}, действующий(ая) в интересах несовершеннолетних детей, с другой стороны, в соответствии со ст. 99–105 Семейного кодекса РФ заключили настоящее соглашение о нижеследующем.`);
      H("1. Предмет соглашения");
      T(`1.1. Плательщик обязуется уплачивать алименты на содержание ${d.n === 1 ? "несовершеннолетнего ребёнка" : "несовершеннолетних детей"}: ${kidsTxt} (далее — ${d.n === 1 ? "Ребёнок" : "Дети"}).`);
      H("2. Размер и способ уплаты");
      let s2 = 0; const N2 = () => `2.${++s2}. `;
      const third = typeof a.share_pct === "number" && Math.abs(a.share_pct - 100 / 3) < 0.01;
      if (a.method === "share") T(N2() + `Алименты уплачиваются ежемесячно в размере ${third ? "одной трети" : F(typeof a.share_pct === "number" ? String(a.share_pct).replace(".", ",") + "%" : null, "процент")} заработка и (или) иного дохода Плательщика, после удержания налогов (ст. 104 СК РФ).`);
      else if (a.method === "fixed") {
        T(N2() + `Алименты уплачиваются ежемесячно в твёрдой денежной сумме ${F(typeof a.fixed === "number" ? C.rubles(a.fixed) : null, "сумма")} (ст. 104 СК РФ).`);
        T(N2() + (a.index === "none" ? "Размер алиментов не индексируется." : "Размер алиментов индексируется пропорционально росту величины прожиточного минимума для детей, установленной в субъекте Российской Федерации по месту жительства Получателя (ст. 105, 117 СК РФ)."));
      } else T(F(null, "способ уплаты"));
      T(N2() + `Алименты уплачиваются не позднее ${F(a.pay_day, "число")}-го числа каждого месяца за текущий месяц ` + (a.how === "child" ? "путём перечисления на банковский счёт, открытый на имя Ребёнка (Детей)" : "путём перечисления на банковский счёт Получателя") + " по реквизитам: ________________________________________.");
      T(N2() + `Алименты уплачиваются до достижения ${d.n === 1 ? "Ребёнком" : "каждым из Детей"} совершеннолетия.` + (d.n > 1 && a.method === "fixed" ? " При достижении совершеннолетия одним из Детей стороны заключат соглашение об изменении размера алиментов." : ""));
      H("3. Ответственность");
      T(typeof a.penalty === "number" && a.penalty > 0
        ? `3.1. При образовании задолженности по вине Плательщика он уплачивает неустойку в размере ${String(a.penalty).replace(".", ",")}% от суммы невыплаченных алиментов за каждый день просрочки (п. 1 ст. 115 СК РФ).`
        : "3.1. При образовании задолженности по вине Плательщика неустойка соглашением не предусмотрена (п. 1 ст. 115 СК РФ).");
      H("4. Заключительные положения");
      T("4.1. Соглашение может быть изменено или расторгнуто по взаимному согласию сторон в той же форме (ст. 101 СК РФ). Односторонний отказ от исполнения не допускается.");
      T("4.2. Соглашение подлежит нотариальному удостоверению и имеет силу исполнительного листа (ст. 100 СК РФ).");
      T("4.3. Плательщик обязан в трёхдневный срок сообщать Получателю о перемене места работы или жительства, а также о наличии дополнительного заработка или иного дохода (ст. 111 СК РФ).");
      H("5. Подписи сторон");
      P.push({ text: `Плательщик: ____________ / ${F(U.shortName(a.payer_name), "И. О. Фамилия")}\n\nПолучатель: ____________ / ${F(U.shortName(a.rec_name), "И. О. Фамилия")}`, align: "left" });
      return P;
    },

    guidance(a, d) {
      return [
        { title: "Соглашение подписывают у нотариуса.", text: "Без удостоверения оно недействительно (ст. 100 СК). Возьмите паспорта, свидетельства о рождении детей и этот проект. Нотариус берёт тариф и плату за техническую работу — уточните заранее." },
        { title: "Удостоверенное соглашение — как исполнительный лист.", text: "Если плательщик перестанет платить, его сразу можно отнести приставам или в бухгалтерию работодателя, без суда." },
        { title: "Меньше, чем присудил бы суд, договориться нельзя.", text: `На ${d.n || "одного"} ${d.n > 1 ? "детей" : "ребёнка"} — не меньше ${shareText(d.n || 1)} дохода плательщика.` },
      ];
    },

    fileName() { return "Соглашение об уплате алиментов (проект)"; },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d22 = spec;
})(typeof window !== "undefined" ? window : globalThis);
