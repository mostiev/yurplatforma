/*
 * Д-19. Претензия застройщику о недостатках квартиры (ДДУ).
 * Основа: ст. 7 214-ФЗ (ред. 266-ФЗ от 08.08.2024 и 482-ФЗ от 26.12.2024): ч. 2 (требования: безвозмездное устранение в
 * разумный срок, соразмерное уменьшение цены, возмещение расходов на устранение), ч. 3 (существенные недостатки —
 * отказ от договора), ч. 5 (гарантийный срок не менее 3 лет со дня передачи; до 01.09.2024 — 5 лет), ч. 5.1 (на
 * технологическое и инженерное оборудование — не менее 3 лет со дня передаточного акта), ч. 6 (требование — в
 * письменной форме с указанием недостатков; срок устранения согласуется), ч. 8 (неустойка 1/300 ставки ЦБ от стоимости
 * расходов на устранение, гражданину в двойном размере, но не более стоимости расходов); ст. 10 ч. 3 (штраф 5%),
 * ч. 4 (предел взыскания по отдельным недостаткам — 3% цены договора, если иное не установлено).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const DEMAND = {
    fix: "безвозмездно устранить недостатки",
    discount: "соразмерно уменьшить цену договора",
    costs: "возместить мои расходы на устранение недостатков",
  };

  function derive(a) {
    const handed = U.date(a.handed_date);
    const years = a.contract_new === "yes" ? 3 : 5;
    const warrantyEnd = handed ? U.addDays(U.addMonths(handed, 12 * years), -1) : null;
    const expired = !!(warrantyEnd && U.today() > warrantyEnd && a.stage === "after");
    const defects = String(a.defects || "").split("\n").map(s => s.trim()).filter(Boolean);
    return { handed, years, warrantyEnd, expired, defects };
  }

  const spec = {
    id: "d19",
    code: "Д-19",
    title: "Претензия о недостатках квартиры в новостройке",
    lead: "Кривые стены, продувающие окна, протечки — в новостройке по ДДУ. Требование к застройщику устранить недостатки, снизить цену или возместить расходы. Займёт около 7 минут.",
    status: "draft",

    steps: [
      {
        id: "flat", title: "Квартира",
        questions: [
          { id: "developer", type: "text", label: "Застройщик", placeholder: "ООО «СЗ Новый дом»" },
          C.innQuestion("developer_inn", "ИНН застройщика"),
          { id: "developer_address", type: "text", label: "Адрес застройщика" },
          { id: "ddu", type: "text", label: "ДДУ: номер и дата", placeholder: "№ ДДУ-123/45 от 10.03.2023" },
          { id: "contract_new", type: "choice", label: "Договор заключён после 1 сентября 2024 года?", hint: "От этого зависит гарантийный срок: 3 или 5 лет", options: [
            { value: "yes", label: "Да, после 01.09.2024" },
            { value: "no", label: "Нет, раньше" },
          ] },
          { id: "object", type: "text", label: "Квартира: адрес и номер", placeholder: "кв. № 45, г. Москва, ул. Строителей, корп. 2" },
          { id: "price", type: "money", label: "Цена договора", suffix: "₽", min: 1 },
          { id: "stage", type: "choice", label: "Квартиру уже приняли по акту?", options: [
            { value: "before", label: "Нет, недостатки нашли на осмотре" },
            { value: "after", label: "Да, недостатки обнаружились после" },
          ] },
          { id: "handed_date", type: "date", label: "Дата передаточного акта", show: a => a.stage === "after" },
          { id: "inspect_date", type: "date", label: "Дата осмотра", show: a => a.stage === "before" },
        ],
      },
      {
        id: "defects", title: "Недостатки",
        questions: [
          { id: "defects", type: "textarea", label: "Недостатки", hint: "Каждый с новой строки, конкретно: где, что, насколько", placeholder: "Отклонение стены в комнате 1 от вертикали — 12 мм на 2 м\nПродувание оконного блока на кухне\nТрещина в стяжке пола в коридоре" },
          { id: "expert", type: "text", label: "Заключение специалиста, если есть", required: false, placeholder: "ООО «Эксперт», заключение № 45 от 01.09.2026" },
          { id: "cost", type: "money", label: "Стоимость устранения по заключению", suffix: "₽", required: false },
          { id: "demand", type: "choice", label: "Что требуете?", options: Object.entries(DEMAND).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })) },
          { id: "fix_days", type: "number", label: "В какой срок устранить (дней)?", min: 1, show: a => a.demand === "fix", hint: "Разумный срок; часто просят 30–45 дней", validate: v => v > 60 ? "Не больше 60 дней" : null },
          { id: "discount_sum", type: "money", label: "На сколько снизить цену", suffix: "₽", show: a => a.demand === "discount" },
        ],
      },
      {
        id: "you", title: "Вы",
        questions: [...C.personQuestions()],
      },
    ],

    derive,

    stop(a, d) {
      if (d.expired) return { title: "Гарантийный срок, по вашим данным, истёк.", text: `Он закончился ${U.fmtDate(d.warrantyEnd)} (${d.years} года/лет с передачи). На инженерное оборудование срок может быть другим — проверьте договор. Для спора после гарантии нужна консультация юриста.` };
      if (a.demand === "costs" && typeof a.cost !== "number") return { title: "Для возмещения расходов нужна сумма.", text: "Укажите стоимость устранения по заключению специалиста или по смете." };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      C.header({ name: a.developer, nameLabel: "застройщик", inn: a.developer_inn, address: a.developer_address }, C.from(a), P);
      C.title(P, "ПРЕТЕНЗИЯ", "о недостатках объекта долевого строительства");
      T(`Между мной и ${F(a.developer, "застройщик")} заключён договор участия в долевом строительстве ${F(a.ddu, "номер и дата")}, объект — ${F(a.object, "квартира")}, цена договора — ${F(U.money(a.price), "цена")} руб.`);
      T(a.stage === "after"
        ? `Объект передан мне по акту ${F(U.fmtDate(d.handed), "дата")}. В течение гарантийного срока (ч. 5 ст. 7 Федерального закона от 30.12.2004 № 214-ФЗ) выявлены следующие недостатки:`
        : `При осмотре объекта ${F(U.fmtDate(U.date(a.inspect_date)), "дата")} выявлены следующие недостатки, в связи с которыми объект не соответствует условиям договора и обязательным требованиям:`);
      P.push({ text: d.defects.length ? d.defects.map((x, i) => `${i + 1}) ${x}`).join("\n") : F(null, "недостатки"), align: "left", leftIndent: 709 });
      if (a.expert) T(`Недостатки подтверждаются заключением ${a.expert}` + (typeof a.cost === "number" ? `; стоимость их устранения составляет ${U.money(a.cost)} руб.` : "."));
      T("В соответствии с ч. 2 и 6 ст. 7 Федерального закона № 214-ФЗ ТРЕБУЮ:");
      if (a.demand === "fix") T(`1. Безвозмездно устранить перечисленные недостатки в срок ${F(a.fix_days, "число")} календарных дней со дня получения претензии, предварительно согласовав со мной дату и время работ.`);
      else if (a.demand === "discount") T(`1. Соразмерно уменьшить цену договора на ${F(U.money(a.discount_sum), "сумма")} руб. и возвратить эту сумму в течение 10 дней со дня получения претензии.`);
      else if (a.demand === "costs") T(`1. Возместить мои расходы на устранение недостатков в размере ${F(U.money(a.cost), "сумма")} руб. в течение 10 дней со дня получения претензии.`);
      else T(F(null, "требование"));
      if (a.stage === "before") T("2. Составить акт осмотра с перечнем выявленных недостатков и передать объект после их устранения.");
      if (a.demand !== "fix") P.push({ text: "Денежные средства прошу перечислить по реквизитам:\n________________________________________________________________\n________________________________________________________________", indent: true, align: "left" });
      T(`При нарушении срока ${a.demand === "fix" ? "устранения недостатков" : "удовлетворения требования"} застройщик уплачивает неустойку в размере 1/300 ставки Банка России от стоимости расходов, необходимых для устранения недостатков, за каждый день просрочки в двойном размере (ч. 8 ст. 7 Федерального закона № 214-ФЗ). В случае отказа я обращусь в суд с требованием о взыскании также компенсации морального вреда и штрафа в размере 5% (ч. 2, 3 ст. 10 Федерального закона № 214-ФЗ).`);
      C.attachments(P, ["Копия договора участия в долевом строительстве.", a.stage === "after" ? "Копия передаточного акта." : null, a.expert ? "Копия заключения специалиста." : null, "Фотографии недостатков."].filter(Boolean));
      C.sign(P, a);
      return P;
    },

    guidance(a, d) {
      const g = [
        { title: "Отправьте ценным письмом с описью по юридическому адресу застройщика.", text: "Приложите фото с датой и заключение специалиста, если есть. Сохраните опись и чек." },
        { title: "Гарантия — по договору, но не меньше срока в законе.", text: `Для договоров после 01.09.2024 — не менее 3 лет, раньше — 5 лет со дня передачи. По вашим данным гарантия ${d.warrantyEnd ? "до " + U.fmtDate(d.warrantyEnd) : "— укажите дату акта"}.` },
        { title: "Лучше сразу получить заключение специалиста.", text: "Строительный эксперт составит перечень недостатков со стоимостью устранения. Это главное доказательство в суде." },
        { title: "Сумму по отдельным недостаткам закон ограничивает.", text: "С 2025 года по ряду недостатков общая сумма взыскания с застройщика не может превышать 3% цены договора (ч. 4 ст. 10 закона № 214-ФЗ). Уточните у юриста, касается ли это вашей ситуации." },
      ];
      if (a.stage === "before") g.unshift({ title: "При приёмке не подписывайте передаточный акт «без замечаний».", text: "Составьте акт осмотра с перечнем недостатков и приложите к нему фото. Если недостатки существенные, можно требовать их устранения до подписания." });
      return g;
    },

    fileName(a) { return "Претензия застройщику о недостатках" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d19 = spec;
})(typeof window !== "undefined" ? window : globalThis);
