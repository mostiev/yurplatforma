/*
 * Д-43. Заявление об отмене заочного решения суда.
 * Основа: ГПК РФ — ч. 1 ст. 237 (7 дней со дня вручения копии заочного решения), ч. 2 ст. 237 (апелляция — в течение
 * месяца после отказа в отмене), ст. 238 (содержание: суд, заявитель, уважительные причины неявки, о которых не мог
 * сообщить, и доказательства; обстоятельства и доказательства, которые могут повлиять на решение; просьба; перечень
 * приложений; копии по числу лиц), ст. 242 (основания отмены), ст. 243 (после отмены — рассмотрение по существу),
 * ч. 3 ст. 107 (рабочие дни), ст. 112 (восстановление срока). Госпошлиной не облагается.
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const ABSENCE = {
    no_notice: "я не был(а) извещён(а) о времени и месте судебного заседания: судебную повестку не получал(а)",
    elsewhere: "в период рассмотрения дела я не проживал(а) по адресу, по которому суд направлял извещения",
    ill: "в день судебного заседания я был(а) болен(на)",
    trip: "в день судебного заседания я находился(ась) в служебной командировке",
    other: "по иной уважительной причине",
  };
  const MERITS = {
    paid: "задолженность погашена полностью или частично",
    amount: "размер взысканной суммы определён неверно",
    limitation: "истцом пропущен срок исковой давности, о чём я заявляю (ст. 199 ГК РФ)",
    penalty: "неустойка явно несоразмерна последствиям нарушения обязательства и подлежит уменьшению (ст. 333 ГК РФ)",
    not_mine: "я не заключал(а) договор, на котором основаны требования, либо не получал(а) денежные средства",
    assign: "истец не доказал переход к нему права требования",
  };

  function derive(a) {
    const got = U.date(a.got_date);
    const deadline = got ? C.addWorkdays(got, 7) : null;
    const late = !!(deadline && U.today() > deadline);
    return { got, deadline, late };
  }

  const spec = {
    id: "d43",
    code: "Д-43",
    title: "Заявление об отмене заочного решения",
    lead: "Суд решил дело без вас, потому что вы не пришли на заседание, — часто вы о нём просто не знали. Заявление в тот же суд, чтобы дело рассмотрели заново. Займёт около 7 минут.",
    status: "draft",

    steps: [
      {
        id: "case", title: "Дело",
        questions: [
          { id: "court", type: "text", label: "Какой суд вынес решение", placeholder: "Хамовнический районный суд г. Москвы" },
          { id: "court_address", type: "text", label: "Адрес суда", required: false },
          { id: "case_no", type: "text", label: "Номер дела", placeholder: "2-1234/2026" },
          { id: "decision_date", type: "date", label: "Дата заочного решения" },
          { id: "plaintiff", type: "text", label: "Истец", placeholder: "ООО ПКО «Долговой центр»" },
          { id: "claim", type: "text", label: "Что взыскали или о чём решение", placeholder: "взыскана задолженность по кредитному договору 184 300 руб." },
          { id: "got_date", type: "date", label: "Когда вы получили копию заочного решения?", hint: "Семь рабочих дней на заявление считаются с этой даты. Если копию не получали — дата, когда вы получили её в суде" },
        ],
      },
      {
        id: "why", title: "Почему не пришли",
        questions: [
          { id: "absence", type: "select", label: "Почему вас не было на заседании?", options: Object.entries(ABSENCE).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })) },
          { id: "absence_desc", type: "textarea", label: "Коротко: подробности и даты", required: false, placeholder: "С 01.03.2026 живу и работаю в г. Казани по адресу …; повестки направлялись по старому адресу" },
          { id: "late_reason", type: "textarea", label: "Почему заявление подаёте позже 7 рабочих дней?", show: (a, d) => d.late, hint: "Срок прошёл — суд восстановит его только по уважительной причине" },
          { id: "merits", type: "multi", label: "С чем вы не согласны по существу?", hint: "Суд отменит решение, только если есть доводы, которые могут изменить результат. Выберите всё, что подходит",
            options: Object.entries(MERITS).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })).concat([{ value: "other", label: "Другое — опишу ниже" }]) },
          ...[false, true].map(needed => ({ id: "merits_desc", type: "textarea", label: "Ваши доводы подробнее", required: needed,
            show: a => (a.merits || []).length > 0 && (a.merits || []).includes("other") === needed,
            placeholder: "Последний платёж по кредиту был 10.01.2021, иск подан 15.05.2026 — срок давности истёк" })),
          { id: "proofs", type: "textarea", label: "Какие документы прикладываете?", required: false, hint: "Каждый с новой строки: подтверждение причины неявки и доводов",
            placeholder: "Копия договора аренды в г. Казани\nСправка банка о полном погашении кредита" },
        ],
      },
      {
        id: "you", title: "Вы",
        questions: [
          { id: "buyer_name", type: "text", label: "Ваши фамилия, имя и отчество", autocomplete: "name" },
          { id: "buyer_birth", type: "date", label: "Дата рождения", required: false },
          { id: "buyer_address", type: "text", label: "Адрес для писем суда", hint: "Где вы действительно получаете почту", autocomplete: "street-address" },
          { id: "buyer_phone", type: "tel", label: "Телефон", autocomplete: "tel" },
          { id: "buyer_email", type: "email", label: "Электронная почта", required: false, autocomplete: "email" },
        ],
      },
    ],

    derive,

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      P.push({ text: `В ${F(a.court, "суд")}` + (a.court_address ? `\nАдрес: ${a.court_address}` : ""), align: "left", leftIndent: 4500, after: 120 });
      P.push({ text: `Ответчик: ${F(a.buyer_name, "ваши ФИО")}` + (U.date(a.buyer_birth) ? `, ${U.fmtDate(U.date(a.buyer_birth))} г. р.` : "") + `\nАдрес: ${F(a.buyer_address, "адрес")}\nТел.: ${F(a.buyer_phone, "телефон")}` + (a.buyer_email ? `, e-mail: ${a.buyer_email}` : ""), align: "left", leftIndent: 4500, after: 120 });
      P.push({ text: `Истец: ${F(a.plaintiff, "истец")}\nДело № ${F(a.case_no, "номер дела")}`, align: "left", leftIndent: 4500, after: 360 });
      C.title(P, "ЗАЯВЛЕНИЕ", "об отмене заочного решения суда");
      T(`${F(U.fmtDate(U.date(a.decision_date)), "дата")} по делу № ${F(a.case_no, "номер")} по иску ${F(a.plaintiff, "истец")} ко мне вынесено заочное решение` + (a.claim ? `: ${String(a.claim).trim().replace(/\.$/, "")}` : "") + `. Копию заочного решения я получил(а) ${F(U.fmtDate(d.got), "дата")}.`);
      T(`Я не явился(ась) в судебное заседание по уважительной причине, о которой не имел(а) возможности своевременно сообщить суду: ${a.absence ? ABSENCE[a.absence] : F(null, "причина")}` + (a.absence_desc ? `. ${String(a.absence_desc).trim().replace(/\.$/, "")}` : "") + ".");
      const m = (a.merits || []).map(k => MERITS[k]).filter(Boolean);
      if (m.length || a.merits_desc) T("При этом имеются обстоятельства, которые могут повлиять на содержание решения суда:" + m.map(x => `\n— ${x};`).join("").replace(/;$/, ".") + (a.merits_desc ? (m.length ? "\n" : " ") + String(a.merits_desc).trim() : ""));
      else T(F(null, "доводы, которые могут изменить решение"));
      T("Моё участие в судебном заседании позволило бы представить эти доводы и доказательства. Поэтому заочное решение подлежит отмене (ст. 242 ГПК РФ).");
      if (d.late) T(`Срок подачи заявления, установленный ч. 1 ст. 237 ГПК РФ, пропущен по уважительной причине: ${F(a.late_reason ? String(a.late_reason).trim().replace(/\.$/, "") : null, "причина")}.`);
      P.push({ text: "На основании ст. 112, 237, 238, 242, 243 Гражданского процессуального кодекса РФ", indent: true, keepNext: true });
      P.push({ text: "ПРОШУ:", indent: true, keepNext: true });
      const items = [];
      if (d.late) items.push("Восстановить срок подачи заявления об отмене заочного решения.");
      items.push(`Отменить заочное решение от ${F(U.fmtDate(U.date(a.decision_date)), "дата")} по делу № ${F(a.case_no, "номер")}.`);
      items.push("Возобновить рассмотрение дела по существу и известить меня о времени и месте судебного заседания по указанному адресу.");
      items.forEach((x, i) => T(`${i + 1}. ${x}`));
      const att = String(a.proofs || "").split("\n").map(s => s.trim()).filter(Boolean);
      att.push("Копия заявления для истца.");
      C.attachments(P, att);
      C.sign(P, a);
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (!d.late && d.deadline) g.push({ title: `Подайте не позднее ${U.fmtDate(d.deadline)}.`, text: "Это 7 рабочих дней со дня получения копии решения (ч. 1 ст. 237, ч. 3 ст. 107 ГПК). По почте срок соблюдён, если письмо сдано до 24:00 последнего дня." });
      if (d.late) g.push({ title: "Срок прошёл — приложите доказательства причины.", text: "Суд рассмотрит просьбу о восстановлении срока (ст. 112 ГПК). Если откажет в отмене решения, останется апелляционная жалоба в течение месяца (ч. 2 ст. 237)." });
      g.push({ title: "Подайте в суд, который вынес решение, с копией для истца.", text: "Лично в канцелярию (второй экземпляр — с отметкой), заказным письмом с описью или через ГАС «Правосудие» со входом через Госуслуги. Госпошлину платить не нужно." });
      g.push({ title: "Главное — доводы по существу.", text: "Одной уважительной причины неявки мало: суд отменяет решение, если есть обстоятельства и доказательства, которые могут изменить результат (ст. 242 ГПК). Срок давности, погашение долга, завышенная неустойка — пишите конкретно и прикладывайте документы." });
      g.push({ title: "Если по решению уже взыскивают.", text: "После отмены решения дело рассмотрят заново. Можно попросить суд приостановить исполнительное производство — это отдельное заявление, с ним лучше к юристу." });
      return g;
    },

    fileName(a) { return "Заявление об отмене заочного решения" + (a.case_no ? " по делу " + String(a.case_no).replace(/[\\/:*?"<>|]/g, "-") : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d43 = spec;
})(typeof window !== "undefined" ? window : globalThis);
