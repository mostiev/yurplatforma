/*
 * Д-25. Заявление об увольнении по собственному желанию.
 * Основа: ст. 80 ТК РФ (предупреждение не позднее чем за 2 недели; ранее — по соглашению; ч. 3 — в срок, указанный
 * работником, при невозможности продолжения работы; ч. 4 — право отозвать), ст. 84.1 (оформление, трудовая книжка /
 * сведения о трудовой деятельности), ст. 127 (компенсация за неиспользованный отпуск), ст. 140 (расчёт в день увольнения).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const IMPOSSIBLE = {
    pension: "выходом на пенсию",
    study: "зачислением в образовательную организацию",
    violation: "установленным нарушением работодателем трудового законодательства",
    spouse: "переводом супруга на работу в другую местность",
    other: "иными обстоятельствами, исключающими продолжение работы",
  };

  function derive(a) {
    const submit = U.date(a.submit_date);
    const last = U.date(a.last_day);
    // срок предупреждения начинается на следующий день после получения заявления; 14 дней
    const earliest = submit ? U.addDays(submit, 14) : null;
    const early = !!(earliest && last && last < earliest);
    return { submit, last, earliest, early };
  }

  const spec = {
    id: "d25",
    code: "Д-25",
    title: "Заявление об увольнении по собственному желанию",
    lead: "Правильно оформленное заявление с датой, просьбой о расчёте и выдаче документов. Займёт около 3 минут.",
    status: "draft",

    steps: [
      {
        id: "when", title: "Когда",
        questions: [
          { id: "submit_date", type: "date", label: "Когда вы подадите заявление?", hint: "Две недели отсчитываются со следующего дня после того, как работодатель получит заявление" },
          { id: "mode", type: "choice", label: "Как хотите уволиться?", options: [
            { value: "standard", label: "Через две недели (с отработкой)" },
            { value: "agreement", label: "Раньше — договорился(ась) с работодателем" },
            { value: "impossible", label: "Раньше — не могу продолжать работу", hint: "Выход на пенсию, поступление на учёбу, нарушение работодателем трудовых прав и т. п." },
          ] },
          { id: "reason", type: "select", label: "Почему не можете продолжать работу?", show: a => a.mode === "impossible", options: Object.entries(IMPOSSIBLE).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })) },
          { id: "reason_desc", type: "text", label: "Коротко: что именно и чем подтверждается", required: false, placeholder: "Задержка зарплаты за июль и август, подтверждено ответом ГИТ № 123", show: a => a.mode === "impossible" },
          { id: "last_day", type: "date", label: "Последний рабочий день (дата увольнения)",
            validate: (v, a) => {
              const s = U.date(a.submit_date), l = U.date(v);
              if (s && l && l < s) return "Не раньше даты подачи";
              if (a.mode === "standard" && s && l && l < U.addDays(s, 14)) return `С отработкой — не раньше ${U.fmtDate(U.addDays(s, 14))}`;
              return null;
            } },
        ],
      },
      {
        id: "job", title: "Работа",
        questions: [
          { id: "org_name", type: "text", label: "Работодатель", placeholder: "ООО «Ромашка»" },
          { id: "head_position", type: "text", label: "Должность руководителя", placeholder: "Генеральный директор" },
          { id: "head_name", type: "text", label: "ФИО руководителя", placeholder: "Иванов Иван Иванович" },
          { id: "buyer_name", type: "text", label: "Ваши фамилия, имя и отчество", autocomplete: "name" },
          { id: "position", type: "text", label: "Ваша должность", placeholder: "Менеджер по продажам" },
          { id: "department", type: "text", label: "Отдел", required: false },
          { id: "book", type: "choice", label: "У вас бумажная трудовая книжка?", options: [
            { value: "paper", label: "Да, бумажная" },
            { value: "electronic", label: "Нет, электронная (отказался(ась) от бумажной)" },
            { value: "unknown", label: "Не знаю" },
          ] },
          { id: "vacation", type: "choice", label: "Остались неиспользованные дни отпуска?", options: [
            { value: "yes", label: "Да" }, { value: "no", label: "Нет" }, { value: "unknown", label: "Не знаю" },
          ] },
        ],
      },
    ],

    derive,

    render(a, d) {
      const P = [];
      P.push({ text: `Кому: ${F(a.head_position, "должность руководителя")} ${F(a.org_name, "работодатель")}\n${F(a.head_name, "ФИО руководителя")}\nОт: ${F(a.buyer_name, "ваши ФИО")}\nДолжность: ${F(a.position, "должность")}${a.department ? ", " + a.department : ""}`, align: "left", leftIndent: 4500, after: 360 });
      C.title(P, "ЗАЯВЛЕНИЕ", "об увольнении по собственному желанию");

      let main = `Прошу уволить меня по собственному желанию ${F(U.fmtDate(d.last), "дата увольнения")}`;
      if (a.mode === "standard") main += " (п. 3 ч. 1 ст. 77, ст. 80 Трудового кодекса РФ).";
      if (a.mode === "agreement") main += " — до истечения двухнедельного срока предупреждения по договорённости с работодателем (ч. 2 ст. 80 Трудового кодекса РФ).";
      if (a.mode === "impossible") main += ` в связи с ${F(IMPOSSIBLE[a.reason], "причина")}` + (a.reason_desc ? ` (${a.reason_desc})` : "") + ". В соответствии с ч. 3 ст. 80 Трудового кодекса РФ, прошу расторгнуть трудовой договор в указанный мной срок.";
      P.push({ text: main, indent: true });

      P.push({ text: `В день увольнения прошу произвести со мной окончательный расчёт (ст. 140 ТК РФ)` + (a.vacation === "no" ? "" : ", включая компенсацию за все неиспользованные отпуска (ст. 127 ТК РФ)") + (a.book === "electronic" ? ", и выдать сведения о трудовой деятельности (форма СТД-Р) (ст. 84.1 ТК РФ)." : a.book === "paper" ? ", и выдать трудовую книжку (ст. 84.1 ТК РФ)." : ", и выдать трудовую книжку либо сведения о трудовой деятельности (ст. 84.1 ТК РФ)."), indent: true });
      P.push({ text: "Также прошу выдать справку о сумме заработка за два календарных года, предшествующих году увольнения, и текущий год (для расчёта пособий) и копию приказа об увольнении.", indent: true });
      P.push({ text: `${F(U.fmtDate(d.submit), "дата подачи")}            ____________ / ${F(U.shortName(a.buyer_name), "И. О. Фамилия")}`, align: "left", before: 360 });
      return P;
    },

    guidance(a, d) {
      const g = [
        { title: "Отдайте заявление так, чтобы осталась отметка.", text: "Два экземпляра: на вашем пусть поставят дату и подпись о принятии (секретарь, отдел кадров). Не принимают — отправьте ценным письмом с описью; срок пойдёт со следующего дня после получения." },
        { title: "Заявление можно отозвать.", text: "До окончания двух недель — в любой момент, если на ваше место не пригласили в письменной форме другого работника (ст. 80 ТК)." },
        { title: "В последний день проверьте расчёт и документы.", text: "Зарплата, компенсация за отпуск, трудовая книжка или СТД-Р. Не выплатили в день увольнения — начисляется компенсация по ст. 236 ТК (документ Д-27)." },
      ];
      if (a.mode === "agreement") g.unshift({ title: "Договорённость об увольнении без отработки должна быть видна.", text: "Попросите руководителя поставить на заявлении «Согласовано, уволить с такой-то даты» и подпись." });
      if (a.mode === "impossible") g.unshift({ title: "Приложите подтверждение причины.", text: "Пенсионное удостоверение, справку из учебного заведения, акт или ответ инспекции о нарушении — чтобы работодатель не настаивал на отработке." });
      return g;
    },

    fileName(a) { return "Заявление об увольнении" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d25 = spec;
})(typeof window !== "undefined" ? window : globalThis);
