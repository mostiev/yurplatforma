/*
 * К-10. Выходное пособие и сохраняемый заработок при сокращении или ликвидации.
 * Основа: ТК РФ (ред. 306-ФЗ от 31.07.2025, с 11.08.2025 нумерация частей ст. 178 сдвинулась):
 * ст. 178 ч. 1 (выходное пособие — средний месячный заработок), ч. 2 (за 2-й месяц со дня увольнения, если не
 * трудоустроен, или часть пропорционально), ч. 3 (3-й месяц — по решению службы занятости при обращении в течение
 * 14 рабочих дней), ч. 5 (обращение к работодателю не позднее 15 рабочих дней после окончания 2-го месяца),
 * ч. 6 (вместо помесячных выплат — единовременная компенсация в размере двукратного среднего месячного заработка),
 * ч. 8 (двухнедельный средний заработок — п. 7–9 ст. 77, п. 1, 2, 5 ст. 83), ч. 9 (договором — больше);
 * ст. 180 ч. 2, 3 (предупреждение за 2 месяца; досрочно — компенсация пропорционально оставшемуся времени);
 * ст. 318 (Крайний Север: 2-й и 3-й месяц — работодатель; 4–6-й — по решению службы занятости); ст. 140.
 * Положение, утв. ПП РФ от 24.04.2025 № 540 (с 01.09.2025), п. 9: средний дневной = заработок за отработанные дни /
 * отработанные дни; средний месячный для выходного пособия = средний дневной × среднее число рабочих дней в месяце
 * в году увольнения (разъяснение Минтруда от 02.06.2026 № 14-1/ООГ-2290: рабочие дни года / 12, округление по правилам
 * математики; 2026 — 247 / 12 = 20,58). НДФЛ — ст. 217 НК, ред. 259-ФЗ и 425-ФЗ (не облагается в пределах 3-кратного, для Севера
 * 6-кратного среднего месячного). Производственный календарь — assets/calendar.js. Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const rub = n => U.money(Math.round(n * 100) / 100) + " ₽";
  const r2 = x => Math.round(x * 100) / 100;
  const num = x => String(x).replace(".", ",");

  const workdays = (from, to) => { let n = 0; for (let d = from; d <= to; d = U.addDays(d, 1)) if (C.isWorkday(d)) n++; return n; };
  const yearDays = y => workdays(new Date(y, 0, 1), new Date(y, 11, 31));
  const monthAvg = y => r2(yearDays(y) / 12);

  const spec = {
    id: "k10",
    code: "К-10",
    title: "Выходное пособие при сокращении",
    lead: "Сколько должны заплатить при сокращении или ликвидации: выходное пособие, средний заработок за второй и третий месяц, компенсация за досрочное увольнение. По новым правилам расчёта среднего заработка.",
    status: "draft",
    defaults: { reason: "reduction", days_mode: "auto", north: "no" },

    fields: [
      { id: "reason", type: "choice", label: "Почему увольняют?", options: [
        { value: "reduction", label: "Сокращение штата или ликвидация" },
        { value: "two_weeks", label: "Другое основание с пособием в две недели", hint: "Отказ от перевода по медицинским показаниям или от переезда с работодателем, отказ работать при изменении условий договора, призыв на военную службу, восстановление прежнего работника, полная нетрудоспособность" },
      ] },
      { id: "dism", type: "date", label: "День увольнения", future: true },
      { id: "notice", type: "date", label: "Когда вас письменно предупредили о сокращении", required: false, show: a => a.reason === "reduction", hint: "Если уволят раньше чем через 2 месяца — положена дополнительная компенсация" },
      { id: "north", type: "choice", label: "Работаете на Крайнем Севере или в приравненной местности?", show: a => a.reason === "reduction", options: [
        { value: "no", label: "Нет" },
        { value: "yes", label: "Да" },
      ] },
      { id: "h1", type: "heading", label: "Заработок за 12 месяцев" },
      { id: "pay", type: "money", label: "Сколько начислено за отработанное время за 12 календарных месяцев до месяца увольнения", suffix: "₽",
        hint: "До НДФЛ, с премиями. Без отпускных, больничных, материальной помощи" },
      { id: "days_mode", type: "choice", label: "Сколько дней вы отработали за эти 12 месяцев?", options: [
        { value: "auto", label: "Посчитать по календарю пятидневки", hint: "Укажете, сколько рабочих дней не работали" },
        { value: "manual", label: "Знаю точно", hint: "Из табеля или расчётных листков" },
      ] },
      { id: "absent", type: "number", label: "Сколько рабочих дней не работали: отпуск, больничный, отгулы", min: 0, required: false, show: a => a.days_mode === "auto" },
      { id: "worked", type: "number", label: "Отработано дней", min: 1, show: a => a.days_mode === "manual" },
    ],

    compute(a) {
      const dism = U.date(a.dism);
      const pay = typeof a.pay === "number" && a.pay > 0 ? a.pay : null;
      if (!dism || !pay) return null;
      const from = new Date(dism.getFullYear(), dism.getMonth() - 12, 1), to = U.addDays(new Date(dism.getFullYear(), dism.getMonth(), 1), -1);
      let worked;
      const notes = [];
      if (a.days_mode === "manual") worked = typeof a.worked === "number" && a.worked > 0 ? Math.floor(a.worked) : null;
      else {
        const all = workdays(from, to);
        worked = all - (Number(a.absent) || 0);
        notes.push(`Рабочих дней в расчётном периоде по производственному календарю — ${all}` + (a.absent ? `, минус ${a.absent} не отработанных` : "") + `. Проверьте по табелю: при сменном графике число будет другим.`);
        if (!C.calCovers(from) || !C.calCovers(to)) notes.push("Для части периода у нас нет производственного календаря — праздники могли не учесться. Уточните отработанные дни по табелю.");
      }
      if (!worked || worked <= 0) return null;
      const daily = r2(pay / worked);
      const mAvg = monthAvg(dism.getFullYear());
      const monthly = r2(daily * mAvg);
      notes.unshift(`Средний дневной заработок = ${U.money(pay)} ₽ ÷ ${worked} дн. = ${rub(daily)}. Средний месячный = ${rub(daily)} × ${num(mAvg)} (рабочих дней в ${dism.getFullYear()} году ÷ 12) = ${rub(monthly)} (п. 9 Положения, утв. ПП РФ от 24.04.2025 № 540).`);
      const summary = [{ label: "Средний месячный заработок", value: rub(monthly) }];
      const rows = [];
      let total = 0;
      const related = [{ id: "k9", text: "Компенсация за отпуск" }, { id: "k4", text: "Если задержали расчёт" }];

      if (a.reason === "two_weeks") {
        const end = U.addDays(dism, 14);
        const wd = workdays(U.addDays(dism, 1), end);
        const sum = r2(daily * wd);
        rows.push(["Выходное пособие — двухнедельный средний заработок", `${rub(daily)} × ${wd} раб. дн.`, rub(sum)]);
        summary.push({ label: "Выходное пособие", value: rub(sum), big: true });
        notes.push("Двухнедельный заработок посчитан как средний дневной × рабочие дни в двух неделях после увольнения (ч. 8 ст. 178 ТК). Выплачивается в день увольнения (ст. 140). Договором может быть предусмотрено больше.");
        return { summary, table: { head: ["Выплата", "Расчёт", "Сумма"], rows }, notes, related };
      }

      // сокращение
      rows.push(["Выходное пособие (1-й месяц)", "средний месячный, в день увольнения", rub(monthly)]);
      total += monthly;
      const notice = U.date(a.notice);
      let early = 0;
      if (notice) {
        const legal = U.addMonths(notice, 2);
        if (dism < legal) {
          const wd = workdays(U.addDays(dism, 1), legal);
          early = r2(daily * wd);
          rows.push(["Компенсация за досрочное увольнение", `${rub(daily)} × ${wd} раб. дн. до ${U.fmtDate(legal)}`, rub(early)]);
          total += early;
          notes.push(`Уволить без вашего письменного согласия можно не раньше ${U.fmtDate(legal)} — через 2 месяца после предупреждения. Если вы согласились уйти раньше, положена компенсация за оставшееся время (ч. 3 ст. 180 ТК).`);
        }
      }
      rows.push(["Средний заработок за 2-й месяц", "если не устроились на работу", rub(monthly)]);
      const north = a.north === "yes";
      if (north) rows.push(["3-й месяц", "если не устроились — платит работодатель (ст. 318)", rub(monthly)], ["4–6-й месяцы", "по решению службы занятости, каждый", rub(monthly)]);
      else rows.push(["3-й месяц", "в исключительных случаях — по решению службы занятости", rub(monthly)]);
      const max = monthly * (north ? 6 : 3) + early;
      summary.push({ label: "В день увольнения", value: rub(monthly + early), big: true }, { label: "Всего, если долго не найдёте работу", value: `до ${rub(max)}` });

      const m2end = U.addMonths(dism, 2);
      notes.push(
        `Если в течение второго месяца не устроитесь, работодатель доплатит средний месячный заработок, а если устроитесь в середине месяца — часть пропорционально (ч. 2 ст. 178 ТК). Подайте письменное заявление не позднее ${U.fmtDate(C.addWorkdays(m2end, 15))} — 15 рабочих дней после окончания второго месяца, приложите трудовую книжку или сведения о трудовой деятельности (ч. 5).`,
        `Чтобы получить ${north ? "4–6-й месяцы" : "3-й месяц"}, встаньте на учёт в службе занятости (через «Работу России» или Госуслуги) не позднее ${U.fmtDate(C.addWorkdays(dism, 14))} — в течение 14 рабочих дней после увольнения (${north ? "ч. 3 ст. 318" : "ч. 3 ст. 178"}).`,
        "Можно договориться с работодателем о единовременной компенсации вместо помесячных выплат — в размере двух средних месячных заработков (ч. 6 ст. 178).",
        `НДФЛ с выходного пособия и сохраняемого заработка не удерживают в пределах трёх средних месячных заработков${north ? " (на Севере — шести)" : ""} — около ${rub(monthly * (north ? 6 : 3))}; с превышения — 13% (ст. 217 НК). Для налога с 2025 года средний заработок считают по правилам пособий по беременности и уходу за ребёнком, поэтому точная граница у бухгалтерии может немного отличаться.`,
        "Компенсацию за неиспользованный отпуск тоже платят в день увольнения — посчитайте в К-9. Она облагается НДФЛ.",
      );
      const reminders = [
        { date: dism, title: "День увольнения: выходное пособие и расчёт", text: `В день увольнения — ${rub(monthly + early)} выходного пособия плюс зарплата и компенсация за отпуск (ст. 140, 178 ТК).` },
        { date: C.addWorkdays(dism, 14), title: "Последний день встать на учёт в службе занятости", text: "14 рабочих дней после увольнения — через «Работу России» или Госуслуги. Нужно, чтобы сохранить средний заработок за следующие месяцы." },
        { date: m2end, title: "Конец второго месяца после увольнения", text: `Если не устроились — подайте работодателю заявление о среднем заработке за 2-й месяц до ${U.fmtDate(C.addWorkdays(m2end, 15))} (ч. 5 ст. 178 ТК).` },
        { date: C.addWorkdays(m2end, 15), title: "Последний день подать заявление о заработке за 2-й месяц" },
      ];
      return { summary, table: { head: ["Выплата", "Когда и как", "Сумма"], rows }, notes, related, reminders };
    },
  };

  spec.monthAvg = monthAvg;
  global.CALCS = global.CALCS || {};
  global.CALCS.k10 = spec;
})(typeof window !== "undefined" ? window : globalThis);
