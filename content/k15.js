/*
 * К-15. Сколько стоит сделка с квартирой без риэлтора: госпошлина за регистрацию, нотариус (обязательный или по желанию),
 * выписки ЕГРН, вычет покупателя.
 * Основа: НК РФ — пп. 22 п. 1 ст. 333.33 (регистрация права физлицом: 4 000 ₽ при кадастровой стоимости до 20 млн ₽,
 * иначе 0,02% кадастровой стоимости, не больше 500 000 ₽ — ред. 275-ФЗ с 01.09.2025), пп. 5 п. 1 ст. 333.24 и ст. 22
 * Основ о нотариате (обязательное удостоверение — 0,5%, от 300 до 20 000 ₽), ст. 22.1 Основ (добровольное: супругу,
 * родителям, детям, внукам — 3 000 ₽ + 0,2%, свыше 10 млн — 23 000 ₽ + 0,1%, не больше 50 000 ₽; остальным — до 1 млн
 * 3 000 ₽ + 0,4%, до 10 млн 7 000 ₽ + 0,2%, свыше — 25 000 ₽ + 0,1%, не больше 100 000 ₽; база — не ниже кадастровой
 * стоимости), ст. 23 Основ (плата за техническую работу — по тарифам палаты), ст. 220 НК (вычет до 2 млн ₽ + проценты до
 * 3 млн ₽); приказ Росреестра № П/0335/24 (электронная выписка ЕГРН для физлиц — 580 ₽).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const rub = x => U.money(Math.round(x)) + " ₽";
  const n = x => (typeof x === "number" && x > 0 ? x : 0);

  const spec = {
    id: "k15",
    code: "К-15",
    title: "Сколько стоит сделка с квартирой",
    lead: "Госпошлина за регистрацию, нотариус (когда он обязателен и сколько стоит по желанию), выписки и вычет для покупателя — по правилам 2026 года.",
    status: "draft",
    defaults: { what: "all", notary: "no", close: "no", first: "yes" },

    fields: [
      { id: "price", type: "money", label: "Цена квартиры", suffix: "₽" },
      { id: "cad", type: "money", label: "Кадастровая стоимость", suffix: "₽", required: false, hint: "Есть в выписке ЕГРН или на карте Росреестра" },
      { id: "what", type: "choice", label: "Что продаётся", options: [
        { value: "all", label: "Вся квартира" }, { value: "share", label: "Доля", hint: "Нотариус обязателен" }, { value: "minor", label: "Квартира с собственником-ребёнком", hint: "Нотариус обязателен" },
      ] },
      { id: "notary", type: "choice", label: "Идёте к нотариусу по желанию?", show: a => a.what === "all", hint: "Нотариус проверит стороны и сам подаст документы — регистрация быстрее", options: [
        { value: "no", label: "Нет" }, { value: "yes", label: "Да" },
      ] },
      { id: "close", type: "choice", label: "Покупатель — супруг, родитель, ребёнок или внук продавца?", show: a => a.what === "all" && a.notary === "yes", options: [{ value: "no", label: "Нет" }, { value: "yes", label: "Да" }] },
      { id: "first", type: "choice", label: "Покупатель ещё не получал имущественный вычет?", options: [{ value: "yes", label: "Не получал или использовал не весь" }, { value: "no", label: "Уже получил полностью" }] },
      { id: "interest", type: "money", label: "Проценты по ипотеке за весь срок (если знаете)", suffix: "₽", required: false },
    ],

    compute(a) {
      const price = n(a.price);
      if (!price) return null;
      const cad = n(a.cad);
      const reg = C.regDuty(cad || price);
      const base = Math.max(price, cad);
      const required = a.what !== "all";
      const notary = required ? C.notaryDuty(base) : a.notary === "yes" ? C.notaryVoluntary(base, a.close === "yes") : 0;
      const egrn = 580 * 2;
      const deduct = a.first === "yes" ? Math.min(price, 2000000) * 0.13 : 0;
      const ded2 = a.first === "yes" ? Math.min(n(a.interest), 3000000) * 0.13 : 0;
      const summary = [
        { label: "Пошлина за регистрацию", value: rub(reg) },
        ...(notary ? [{ label: required ? "Нотариус: пошлина за обязательное удостоверение" : "Нотариус: тариф по желанию", value: rub(notary) }] : []),
        { label: "Выписки ЕГРН (до задатка и перед сделкой)", value: rub(egrn) },
        { label: "Итого обязательных расходов", value: rub(reg + notary + egrn), big: true },
        ...(deduct ? [{ label: "Вычет покупателю вернёт", value: `до ${rub(deduct + ded2)}` }] : []),
      ];
      const notes = [
        `Пошлина за регистрацию права — ${cad > 2e7 ? "0,02% кадастровой стоимости (не больше 500 000 ₽), так как она больше 20 млн ₽" : "4 000 ₽ при кадастровой стоимости до 20 млн ₽"} (ст. 333.33 НК, с 01.09.2025). Платит тот, кто регистрирует право, — обычно покупатель.`,
      ];
      if (required) notes.push("Нотариус обязателен: " + (a.what === "share" ? "продаётся доля (ч. 1.1 ст. 42 закона № 218-ФЗ). Если все собственники продают всю квартиру одним договором — нотариус не нужен." : "собственник — ребёнок или недееспособный (ч. 2 ст. 54 закона № 218-ФЗ), плюс разрешение опеки.") + " К пошлине 0,5% (не больше 20 000 ₽) добавится плата за правовую и техническую работу — её размер устанавливает нотариальная палата региона, обычно это основная часть счёта.");
      else if (a.notary === "yes") notes.push(`Тариф по ст. 22.1 Основ о нотариате считается от цены, но не ниже кадастровой стоимости${a.close === "yes" ? " — для близких родственников он ниже" : ""}. Плюс плата за техническую работу по тарифу палаты. Взамен — проверка сторон и регистрация от 1 рабочего дня.`);
      notes.push("Расчёты через аккредитив или безопасные расчёты стоят по тарифам банка — уточните заранее. Ипотека добавит оценку квартиры и страховку.");
      if (deduct) notes.push(`Вычет покупателю: 13% с расходов до 2 млн ₽ — до 260 000 ₽${ded2 ? `, плюс 13% с процентов по ипотеке до 3 млн ₽ — ${rub(ded2)}` : ""} (ст. 220 НК). Не положен при покупке у супруга, родителей, детей, братьев и сестёр.`);
      notes.push("Налог продавца посчитает К-12.");
      return { summary, notes, related: [{ id: "d82", text: "Договор купли-продажи", fill: { price: a.price, cad_value: a.cad } }, { id: "k12", text: "Налог продавца" }] };
    },
  };

  global.CALCS = global.CALCS || {};
  global.CALCS.k15 = spec;
})(typeof window !== "undefined" ? window : globalThis);
