/*
 * К-17. Срок исковой давности: не опоздал ли я в суд.
 * Основа: ГК РФ — ст. 191, 192 (начало и окончание сроков), ст. 193 (перенос с нерабочего дня), ст. 195, 196
 * (общий срок 3 года; не более 10 лет со дня нарушения — п. 2 ст. 196), ст. 199 (давность применяется только по
 * заявлению стороны), ст. 200 (начало: когда узнал о нарушении; для обязательств со сроком — по окончании срока;
 * до востребования — по окончании срока на исполнение требования, п. 2), ст. 203 (перерыв признанием долга),
 * ст. 204 (срок не течёт, пока дело в суде; после отмены судебного приказа остаток удлиняется до 6 месяцев, п. 3),
 * ст. 205 (восстановление для граждан), п. 1, 2 ст. 181 (недействительность сделок: 3 года и 1 год), п. 1 ст. 966
 * (имущественное страхование — 2 года). ТК РФ — ст. 392 (3 месяца, 1 месяц по увольнению, 1 год по зарплате),
 * ч. 3, 4 ст. 14 (окончание сроков). Пленум ВС РФ от 29.09.2015 № 43: п. 18 (судебный приказ), п. 20–22 (признание
 * долга), п. 24, 25 (повременные платежи — по каждому отдельно), п. 26 (вместе с основным долгом истекает и по
 * процентам и неустойке).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const D = dt => U.fmtDate(dt);

  const KINDS = {
    debt: { label: "Долг, заём, расписка, оплата по договору", years: 3, start: "Последний день, когда должны были вернуть или заплатить", law: "ст. 196, п. 2 ст. 200 ГК РФ" },
    demand: { label: "Заём «до востребования» — без даты возврата", years: 3, start: "Когда должник получил ваше требование вернуть долг", law: "абз. 2 п. 2 ст. 200 ГК РФ: срок начинается после 30 дней на исполнение требования (п. 1 ст. 810)" },
    schedule: { label: "Кредит или заём по графику платежей", years: 3, start: "Дата первого пропущенного платежа по графику", law: "п. 24 постановления Пленума ВС № 43: по каждому платежу срок считается отдельно" },
    damage: { label: "Ущерб, залив, ДТП, возврат денег за товар или услугу", years: 3, start: "Когда вы узнали о нарушении и о том, кто должен ответить", law: "ст. 196, п. 1 ст. 200 ГК РФ" },
    insurance: { label: "Страховка имущества (КАСКО, квартира)", years: 2, start: "Когда страховая отказала или должна была выплатить", law: "п. 1 ст. 966 ГК РФ — 2 года; по ОСАГО и страхованию ответственности — общий срок 3 года" },
    void: { label: "Ничтожная сделка — признать недействительной", years: 3, start: "Когда началось исполнение сделки", law: "п. 1 ст. 181 ГК РФ" },
    voidable: { label: "Оспоримая сделка: обман, угроза, заблуждение", years: 1, start: "Когда прекратилась угроза или вы узнали об обмане или заблуждении", law: "п. 2 ст. 181 ГК РФ" },
    fired: { label: "Незаконное увольнение", months: 1, labor: true, start: "Когда получили копию приказа об увольнении или трудовую книжку (сведения о трудовой деятельности)", law: "ч. 1 ст. 392 ТК РФ" },
    salary: { label: "Невыплаченная зарплата и другие выплаты работнику", years: 1, labor: true, start: "День, когда зарплату должны были выплатить", law: "ч. 2 ст. 392 ТК РФ — 1 год по каждой выплате" },
    labor: { label: "Другой спор с работодателем", months: 3, labor: true, start: "Когда узнали о нарушении своего права", law: "ч. 1 ст. 392 ТК РФ" },
  };

  function addYM(dt, k) { return k.years ? U.addMonths(dt, 12 * k.years) : U.addMonths(dt, k.months); }
  const fmtTerm = k => k.years ? `${k.years} ${C.plural(k.years, "год", "года", "лет")}` : `${k.months} ${C.plural(k.months, "месяц", "месяца", "месяцев")}`;

  const spec = {
    id: "k17",
    code: "К-17",
    title: "Срок исковой давности: не опоздал ли я в суд",
    lead: "Посчитаем последний день, когда можно подать иск: 3 года по долгам, 2 года по страховке, 1 месяц по увольнению. Учтём признание долга, судебный приказ и перенос с выходных.",
    status: "draft",
    actual: "17.11.2026",
    defaults: { kind: "debt", ack: "no", order: "no" },

    fields: [
      { id: "kind", type: "select", label: "О чём спор", options: Object.entries(KINDS).map(([value, k]) => ({ value, label: k.label })) },
      { id: "start", type: "date", label: a => (KINDS[a.kind] || KINDS.debt).start },
      { id: "ack", type: "choice", label: "Должник после этого признавал долг?", show: a => !(KINDS[a.kind] || {}).labor && ["debt", "demand", "schedule"].includes(a.kind),
        hint: "Письменно признал, попросил отсрочку, подписал акт сверки или заплатил часть с указанием, что это в счёт долга", options: [
          { value: "no", label: "Нет" }, { value: "yes", label: "Да" },
        ] },
      { id: "ack_date", type: "date", label: "Когда последний раз признал", show: a => a.ack === "yes" && ["debt", "demand", "schedule"].includes(a.kind) },
      { id: "order", type: "choice", label: "Был судебный приказ, который потом отменили?", show: a => !(KINDS[a.kind] || {}).labor && ["debt", "demand", "schedule"].includes(a.kind), options: [
        { value: "no", label: "Нет" }, { value: "yes", label: "Да" },
      ] },
      { id: "order_filed", type: "date", label: "Когда подали заявление о приказе", show: a => a.order === "yes" && ["debt", "demand", "schedule"].includes(a.kind) },
      { id: "order_cancel", type: "date", label: "Когда приказ отменили", show: a => a.order === "yes" && ["debt", "demand", "schedule"].includes(a.kind) },
    ],

    compute(a) {
      const k = KINDS[a.kind] || KINDS.debt;
      const start = U.date(a.start);
      if (!start) return null;
      const steps = [];
      const debtLike = ["debt", "demand", "schedule"].includes(a.kind);
      // начало течения
      let event = start;
      if (a.kind === "demand") { event = U.addDays(start, 30); steps.push([`Требование получено ${D(start)}`, `30 дней на возврат — до ${D(event)} (п. 1 ст. 810 ГК)`]); }
      else steps.push(["Начало", `${D(start)} — ${k.law}`]);
      let end = addYM(event, k);
      steps.push([`Срок — ${fmtTerm(k)}`, `до ${D(end)}`]);
      // перерыв признанием долга (ст. 203)
      const ack = debtLike && a.ack === "yes" ? U.date(a.ack_date) : null;
      if (ack && ack > event) { end = addYM(ack, k); steps.push([`Признание долга ${D(ack)}`, `срок начался заново — до ${D(end)} (ст. 203 ГК)`]); }
      // судебный приказ (ст. 204, п. 18 Пленума № 43)
      const of = debtLike && a.order === "yes" ? U.date(a.order_filed) : null, oc = debtLike && a.order === "yes" ? U.date(a.order_cancel) : null;
      let orderErr = null;
      if (of && oc) {
        if (oc < of) orderErr = "Дата отмены приказа раньше даты заявления — проверьте даты.";
        else if (of <= end) {
          const left = U.daysBetween(of, end); // сколько оставалось на день подачи
          const paused = U.daysBetween(of, oc);
          let e2 = U.addDays(end, paused);
          const six = U.addMonths(oc, 6);
          const ext = U.daysBetween(oc, e2) < U.daysBetween(oc, six);
          if (ext) e2 = six;
          steps.push([`Приказ: ${D(of)} — ${D(oc)}`, `пока дело было у судьи, срок не шёл (${paused} дн.)` + (ext ? `; остаток меньше 6 месяцев — удлиняется до ${D(six)} (п. 3 ст. 204 ГК)` : `; осталось ${left} дн. — до ${D(e2)}`)]);
          end = e2;
        } else steps.push([`Приказ подан ${D(of)}`, "уже после окончания срока — на давность не повлиял"]);
      }
      // предел 10 лет (п. 2 ст. 196)
      let capped = false;
      if (!k.labor && a.kind !== "voidable") {
        const cap = U.addMonths(event, 120);
        if (end > cap) { end = cap; capped = true; steps.push(["Предел", `не больше 10 лет со дня нарушения — ${D(cap)} (п. 2 ст. 196 ГК)`]); }
      }
      const last = C.nextWorkday(end);
      if (last.getTime() !== end.getTime()) steps.push(["Выходной", `${D(end)} — нерабочий день, срок переносится на ${D(last)} (ст. 193 ГК${k.labor ? ", ч. 4 ст. 14 ТК" : ""})`]);

      const today = U.today();
      const left = U.daysBetween(today, last);
      const expired = left < 0;
      const summary = [
        { label: "Последний день подать иск", value: D(last), big: true },
        { label: expired ? "Срок истёк" : "Осталось", value: expired ? `${-left} ${C.plural(-left, "день", "дня", "дней")} назад` : `${left} ${C.plural(left, "день", "дня", "дней")}` },
      ];
      const notes = [];
      if (orderErr) notes.push(orderErr);
      if (expired && !k.labor) notes.push("Иск всё равно можно подать: суд применяет давность только если ответчик сам об этом заявит (п. 2 ст. 199 ГК). Если заявит — в иске откажут. Гражданину суд может восстановить срок, если в последние 6 месяцев срока помешали тяжёлая болезнь, беспомощность или неграмотность (ст. 205 ГК).");
      if (expired && k.labor) notes.push("Пропущенный срок по трудовому спору суд может восстановить по уважительной причине: болезнь, уход за больным родственником, командировка, обращение в инспекцию труда или прокуратуру, если вы ждали ответа (ч. 4 ст. 392 ТК, п. 16 Пленума ВС № 15 от 29.05.2018). Попросите об этом в иске.");
      if (!expired && left <= 60) notes.push("Осталось меньше двух месяцев — не откладывайте. Если есть сомнения в дате начала, подайте иск раньше: суд может посчитать начало по-другому.");
      if (a.kind === "schedule") notes.push("По кредиту с графиком срок считается отдельно для каждого платежа. Мы посчитали для первого пропущенного: по более поздним платежам срок истекает позже. Если банк потребовал вернуть весь кредит досрочно, по всем оставшимся платежам срок идёт с даты, указанной в требовании (п. 24, 25 Пленума ВС № 43).");
      if (debtLike) notes.push("Частичная оплата сама по себе не означает признания всего долга — только той части, которую заплатили, если должник не указал иное (п. 20 Пленума ВС № 43). С истечением срока по основному долгу истекает и срок по процентам и неустойке (ст. 207 ГК).");
      if (capped) notes.push("Десятилетний предел не применяется к некоторым требованиям — например, о защите личных неимущественных прав и вкладов в банке (ст. 208 ГК).");
      if (a.kind === "damage") notes.push("Для претензий к качеству товара есть ещё гарантийный срок и 2 года на обнаружение недостатка (ст. 19 ЗоЗПП). Это не исковая давность: давность в 3 года начинается после того, как продавец отказал или не ответил на претензию.");
      if (!k.labor) notes.push("Если по закону для спора обязательна претензия (например, между компаниями), пока идёт этот порядок, давность не течёт — до 30 дней (п. 3 ст. 202 ГК). Добровольная претензия срок не продлевает.");

      const related = [];
      if (debtLike) related.push({ id: "d100", text: "На меня подали в суд — заявить о пропуске давности" }, { id: "d65", text: "Иск или судебный приказ о возврате долга" }, { id: "d35", text: "Претензия о возврате долга" });
      if (a.kind === "fired" || a.kind === "salary" || a.kind === "labor") related.push({ id: "d26", text: "Жалоба в трудовую инспекцию" });
      if (a.kind === "salary") related.push({ id: "k4", text: "Компенсация за задержку зарплаты" });
      if (a.kind === "damage") related.push({ id: "d63", text: "Иск к виновнику ДТП" });
      related.push({ id: "k7", text: "Сколько стоит подать иск" });

      const reminders = expired ? [] : [
        { date: last, title: "Последний день подать иск — исковая давность", text: k.label },
        ...(left > 31 ? [{ date: U.addDays(last, -30), title: "Через месяц истекает исковая давность", text: `Последний день — ${D(last)}.` }] : []),
      ];

      return { summary, table: { head: ["Шаг", "Что получается"], rows: steps, text: true }, notes, reminders, related };
    },
  };

  global.CALCS = global.CALCS || {};
  global.CALCS.k17 = spec;
})(typeof window !== "undefined" ? window : globalThis);
