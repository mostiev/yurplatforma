/*
 * Д-57. Заявление на отпуск: ежегодный, без сохранения зарплаты, с последующим увольнением, перенос.
 * Основа: ТК РФ — ст. 114, 115 (28 календарных дней), ст. 120 ч. 2 (нерабочие праздничные дни ст. 112 в отпуск не
 * включаются), ст. 122 (первый отпуск — после 6 месяцев; раньше — по соглашению и категориям ч. 3), ст. 123 (график,
 * извещение за 2 недели), ст. 124 ч. 1–2 (перенос: болезнь; отпускные не выплачены вовремя; извещение позже 2 недель),
 * ст. 125 (части, одна не менее 14 дней), ст. 127 ч. 2 (отпуск с последующим увольнением, день увольнения — последний
 * день отпуска), ст. 128 (без сохранения зарплаты; ч. 2 — обязательные случаи и максимумы, в т. ч. ред. 64-ФЗ от
 * 07.04.2025 и 90-ФЗ от 09.04.2026 с 01.09.2026), ст. 136 (отпускные не позднее чем за 3 дня), ст. 262.1, 262.2.
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  // ч. 2 ст. 128: обязательные случаи → [текст для заявления, максимум дней]
  const UNPAID = {
    agreement: ["по семейным обстоятельствам", null],
    pensioner: ["как работающему пенсионеру по старости (часть вторая статьи 128 ТК РФ)", 14],
    disabled: ["как работающему инвалиду (часть вторая статьи 128 ТК РФ)", 60],
    event: ["в связи с рождением ребёнка, регистрацией брака или смертью близкого родственника (часть вторая статьи 128 ТК РФ)", 5],
    military_dead: ["как члену семьи военнослужащего, погибшего (умершего) вследствие ранения, контузии или увечья (часть вторая статьи 128 ТК РФ)", 14],
    military_care: ["для ухода за членом семьи — военнослужащим, получившим ранение, контузию или увечье (часть вторая статьи 128 ТК РФ)", 35],
    emergency: ["в связи с тем, что я проживаю в жилом помещении, находящемся в зоне чрезвычайной ситуации (часть вторая статьи 128 ТК РФ)", 5],
  };
  const UNPAID_LABEL = {
    agreement: "По семейным обстоятельствам — по договорённости с работодателем",
    pensioner: "Я работающий пенсионер по старости — до 14 дней в году",
    disabled: "Я работающий инвалид — до 60 дней в году",
    event: "Рождение ребёнка, свадьба, смерть близкого — до 5 дней",
    military_dead: "Я член семьи погибшего военнослужащего — до 14 дней в году",
    military_care: "Ухаживаю за раненым членом семьи — военнослужащим — до 35 дней в году",
    emergency: "Моё жильё в зоне ЧС — до 5 дней",
  };
  const MOVE = {
    notpaid: "отпускные не были выплачены не позднее чем за три дня до начала отпуска (часть вторая статьи 124 ТК РФ)",
    late_notice: "я был(а) извещён(а) о времени начала отпуска позднее чем за две недели до его начала (часть вторая статьи 124 ТК РФ)",
    sick: "в период отпуска я был(а) временно нетрудоспособен(на) (часть первая статьи 124 ТК РФ)",
    wish: "семейные обстоятельства",
  };

  function derive(a) {
    const start = U.date(a.start_date);
    const days = typeof a.days === "number" && a.days > 0 ? Math.floor(a.days) : null;
    let end = null, holidays = 0;
    if (start && days) {
      const annual = a.kind === "annual" || a.kind === "dismissal" || a.kind === "move";
      let d = U.addDays(start, -1), k = 0;
      while (k < days) { d = U.addDays(d, 1); if (annual && C.isHoliday112(d)) holidays++; else k++; }
      end = d;
    }
    const hired = U.date(a.hired_date);
    const sixMonths = hired ? U.addMonths(hired, 6) : null;
    const tooEarly = a.kind === "annual" && sixMonths && start && start < sixMonths;
    const max = a.kind === "unpaid" ? UNPAID[a.unpaid_reason] && UNPAID[a.unpaid_reason][1] : null;
    const overMax = max && days && days > max;
    return { start, days, end, holidays, hired, sixMonths, tooEarly, max, overMax, filed: U.date(a.filed_date) };
  }

  const spec = {
    id: "d57",
    code: "Д-57",
    title: "Заявление на отпуск",
    lead: "Ежегодный отпуск, отпуск за свой счёт, отпуск с последующим увольнением или перенос отпуска. Посчитаем дату окончания с учётом праздников. Займёт около 3 минут.",
    status: "draft",

    steps: [
      {
        id: "leave", title: "Отпуск",
        questions: [
          { id: "kind", type: "choice", label: "Какой отпуск нужен?", options: [
            { value: "annual", label: "Ежегодный оплачиваемый" },
            { value: "unpaid", label: "Без сохранения зарплаты (за свой счёт)" },
            { value: "dismissal", label: "Отпуск с последующим увольнением", hint: "Уволят в последний день отпуска" },
            { value: "move", label: "Перенести уже запланированный отпуск" },
          ] },
          { id: "schedule", type: "choice", label: "Отпуск есть в графике отпусков на эти даты?", show: a => a.kind === "annual", options: [
            { value: "yes", label: "Да" },
            { value: "no", label: "Нет — прошу вне графика", hint: "Нужно согласие работодателя, кроме льготных категорий" },
          ] },
          { id: "priority", type: "choice", label: "Вам положен отпуск в удобное время?", show: a => a.kind === "annual" && a.schedule === "no", options: [
            { value: "no", label: "Нет" },
            { value: "many_kids", label: "У меня трое и больше детей, младшему нет 14 лет", hint: "Ст. 262.2 ТК" },
            { value: "disabled_child", label: "Я родитель ребёнка-инвалида до 18 лет", hint: "Ст. 262.1 ТК" },
            { value: "husband", label: "Жена в декретном отпуске, я муж", hint: "Ч. 4 ст. 123 ТК" },
          ] },
          { id: "unpaid_reason", type: "select", label: "Основание", show: a => a.kind === "unpaid", options: Object.entries(UNPAID_LABEL).map(([value, label]) => ({ value, label })) },
          { id: "old_start", type: "date", future: true, label: "Когда отпуск был запланирован", show: a => a.kind === "move" },
          { id: "move_reason", type: "select", label: "Почему переносите", show: a => a.kind === "move", options: [
            { value: "notpaid", label: "Отпускные не выплатили за 3 дня до начала" },
            { value: "late_notice", label: "О начале отпуска предупредили позже чем за 2 недели" },
            { value: "sick", label: "Заболел(а) во время отпуска" },
            { value: "wish", label: "По личным обстоятельствам — по договорённости" },
          ] },
          { id: "start_date", type: "date", future: true, label: "С какого дня отпуск", hint: "Для переноса — новая дата начала" },
          { id: "days", type: "number", label: "Сколько календарных дней", min: 1, hint: "Для ежегодного отпуска праздники 1–8 января, 23 февраля, 8 марта, 1 и 9 мая, 12 июня, 4 ноября в отпуск не входят — дату окончания посчитаем сами" },
          { id: "hired_date", type: "date", label: "Когда вы начали работать у этого работодателя", required: false, show: a => a.kind === "annual", hint: "Первый отпуск по закону положен через 6 месяцев работы" },
          { id: "filed_date", type: "date", future: true, label: "Дата заявления" },
        ],
      },
      { id: "job", title: "Работа", questions: C.jobQuestions() },
    ],

    derive,

    stop(a, d) {
      if (d.overMax) return { title: `По этому основанию положено не больше ${d.max} дней.`, text: `Больше — только по договорённости с работодателем: выберите «По семейным обстоятельствам» или уменьшите срок до ${d.max} дней.` };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      C.jobHeader(P, a);
      P.push({ text: "ЗАЯВЛЕНИЕ", align: "center", bold: true, after: 240 });
      const period = `продолжительностью ${F(d.days, "число")} ${d.days ? C.plural(d.days, "календарный день", "календарных дня", "календарных дней") : "календарных дней"} с ${F(U.fmtDate(d.start), "дата начала")} по ${F(U.fmtDate(d.end), "дата окончания")}`;
      if (a.kind === "annual") {
        T(`Прошу предоставить мне ежегодный основной оплачиваемый отпуск ${period}` + (a.schedule === "yes" ? " в соответствии с графиком отпусков." : a.priority && a.priority !== "no" ? `, в удобное для меня время (${{ many_kids: "статья 262.2", disabled_child: "статья 262.1", husband: "часть четвёртая статьи 123" }[a.priority]} Трудового кодекса РФ).` : "."));
      } else if (a.kind === "unpaid") {
        T(`Прошу предоставить мне отпуск без сохранения заработной платы ${period} ${UNPAID[a.unpaid_reason] ? UNPAID[a.unpaid_reason][0] : F(null, "основание")}.`);
      } else if (a.kind === "dismissal") {
        T(`Прошу предоставить мне неиспользованный ежегодный оплачиваемый отпуск ${period} с последующим увольнением по собственному желанию. Днём увольнения прошу считать последний день отпуска — ${F(U.fmtDate(d.end), "дата")} (часть вторая статьи 127 Трудового кодекса РФ).`);
        T("Прошу в последний рабочий день перед отпуском выдать мне трудовую книжку (сведения о трудовой деятельности) и произвести со мной окончательный расчёт.");
      } else if (a.kind === "move") {
        T(`Ежегодный оплачиваемый отпуск был запланирован с ${F(U.fmtDate(U.date(a.old_start)), "дата")}. В связи с тем, что ${MOVE[a.move_reason] || F(null, "причина")}, прошу перенести его и предоставить ${period}.`);
      }
      if (d.holidays) T(`В период отпуска приходятся нерабочие праздничные дни (${d.holidays}), которые в число календарных дней отпуска не включаются (часть вторая статьи 120 Трудового кодекса РФ).`);
      P.push({ text: `${F(U.fmtDate(d.filed), "дата")}            ____________ / ${F(U.shortName(a.buyer_name), "И. О. Фамилия")}`, align: "left", before: 360 });
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (a.kind === "annual" || a.kind === "move") g.push({ title: "Отпускные — не позднее чем за 3 дня до начала.", text: "Если не заплатили вовремя, вы вправе письменно потребовать перенести отпуск (ч. 2 ст. 124 ТК) и получить компенсацию за задержку (калькулятор К-4)." });
      if (a.kind === "annual" && a.schedule === "no" && (!a.priority || a.priority === "no")) g.push({ title: "Вне графика — только с согласия работодателя.", text: "Подайте заявление заранее и попросите визу руководителя. Отпуск по графику работодатель обязан дать, о начале должен известить под роспись за 2 недели." });
      if (d.tooEarly) g.push({ title: `Первый отпуск положен с ${U.fmtDate(d.sixMonths)}.`, text: "Раньше — по договорённости или если вы беременны, моложе 18 лет или усыновили ребёнка до 3 месяцев (ч. 3 ст. 122 ТК)." });
      if (d.days && d.days < 14 && (a.kind === "annual")) g.push({ title: "Хотя бы одна часть отпуска за год должна быть не меньше 14 дней.", text: "Делить отпуск можно только по соглашению с работодателем (ст. 125 ТК). Проверьте, что длинная часть у вас запланирована." });
      if (a.kind === "unpaid") g.push({ title: a.unpaid_reason === "agreement" ? "Отпуск за свой счёт по семейным обстоятельствам — по договорённости." : "В этом случае работодатель обязан дать отпуск.", text: a.unpaid_reason === "agreement" ? "Работодатель может отказать. Если нужен в обязательном порядке — проверьте, не подходите ли под случаи ч. 2 ст. 128 ТК." : "Приложите подтверждение: пенсионное удостоверение, справку об инвалидности, свидетельство о рождении, браке или смерти." });
      if (a.kind === "dismissal") g.push({ title: "Отозвать заявление можно до начала отпуска.", text: "Если на ваше место ещё не пригласили работника переводом (ч. 4 ст. 127 ТК). Расчёт и документы выдают в последний рабочий день перед отпуском." });
      g.push({ title: "Сдайте заявление под подпись.", text: "На вашем экземпляре пусть поставят дату приёма и подпись. Или отправьте на рабочую почту и в кадры." });
      return g;
    },

    fileName(a) { return "Заявление на отпуск" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d57 = spec;
})(typeof window !== "undefined" ? window : globalThis);
