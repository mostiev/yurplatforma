        const why = { illness: "в связи с болезнью пассажира (сопровождающего пассажира лица)", death: "в связи со смертью члена семьи (близкого родственника)", military: "в связи с призывом на военную службу по мобилизации (заключением контракта о прохождении военной службы)" }[a.reason];
        P.push({ text: `Я отказался(ась) от перевозки ${why}, что подтверждается документом: ${F(a.proof_doc, "документ")}. Перевозчик был уведомлён об отказе до окончания времени регистрации на рейс. Такой отказ является вынужденным (п. 2 ст. 108 ${vk}), и уплаченная провозная плата подлежит возврату в полном объёме.`, indent: true });
