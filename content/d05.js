      if (d.expenses > 0) P.push({ text: `В связи с ${a.reason === "cancel" ? "отменой" : "задержкой"} рейса я понёс(ла) расходы: ${F(a.expenses_desc, "какие расходы")} — всего ${U.money(d.expenses)} руб. Эти расходы являются убытками, причинёнными ненадлежащим исполнением договора перевозки, и подлежат возмещению (ст. 15, 393 ГК РФ).`, indent: true });

      P.push({ text: "ТРЕБУЮ:", indent: true, keepNext: true });
      const items = [];
      if (a.reason === "delay_flew") items.push(`выплатить штраф за просрочку доставки пассажира в размере ${F(U.money(d.fine), "сумма")} руб.`);
