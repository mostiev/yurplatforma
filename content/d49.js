/*
 * Д-49. Договор купли-продажи автомобиля между физическими лицами (с актом передачи в тексте).
 * Основа: ГК РФ — ст. 454 (купля-продажа), п. 1 ст. 223 (право собственности с передачи вещи, если договором не
 * предусмотрено иное), ст. 456 (передача вещи с принадлежностями и документами), ст. 460 (товар свободен от прав
 * третьих лиц), ст. 469, 474, 475 (качество, проверка, недостатки, о которых продавец не оговорил), п. 1 ст. 161
 * (простая письменная форма). Федеральный закон от 03.08.2018 № 283-ФЗ, п. 3 ч. 3 ст. 8: новый владелец обращается
 * за регистрацией в течение 10 дней со дня приобретения. Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const person = (prefix, who) => [
    { id: prefix + "_name", type: "text", label: `ФИО ${who} полностью` },
    { id: prefix + "_birth", type: "date", label: "Дата рождения" },
    { id: prefix + "_passport", type: "text", label: "Паспорт: серия, номер, кем и когда выдан", hint: "Данные остаются в вашем браузере",
      placeholder: "45 12 345678, выдан ГУ МВД России по г. Москве 01.02.2020" },
    { id: prefix + "_address", type: "text", label: "Адрес регистрации" },
    { id: prefix + "_phone", type: "tel", label: "Телефон" },
  ];

  function derive(a) {
    const vinOk = /^[A-HJ-NPR-Z0-9]{17}$/i.test(String(a.vin || "").trim());
    const price = typeof a.price === "number" && a.price > 0 ? a.price : null;
    const signed = U.date(a.doc_date);
    const regDeadline = signed ? U.addDays(signed, 10) : null;
    return { vinOk, price, signed, regDeadline, defects: String(a.defects || "").split("\n").map(s => s.trim()).filter(Boolean) };
  }

  const spec = {
    id: "d49",
    code: "Д-49",
    title: "Договор купли-продажи автомобиля",
    lead: "Договор продажи машины между людьми: данные автомобиля, цена, передача денег и ключей, известные недостатки. Займёт около 10 минут.",
    status: "draft",
    disclaimer: "Договор составлен по вашим ответам и не является юридической консультацией. Перед подписанием сверьте данные с ПТС и СТС и прочитайте договор обеим сторонам.",

    steps: [
      {
        id: "car", title: "Автомобиль",
        questions: [
          { id: "role", type: "choice", label: "Кто заполняет?", hint: "На текст договора не влияет, только на подсказки", options: [
            { value: "seller", label: "Продавец" },
            { value: "buyer", label: "Покупатель" },
          ] },
          { id: "make", type: "text", label: "Марка и модель", placeholder: "Lada Vesta" },
          { id: "vin", type: "text", label: "VIN", hint: "17 знаков — в ПТС и СТС", placeholder: "XTA000000000000000",
            validate: v => /^[A-HJ-NPR-Z0-9]{17}$/i.test(String(v).trim()) ? null : "VIN — 17 латинских букв и цифр, без I, O и Q" },
          { id: "year", type: "number", label: "Год выпуска", min: 1950, validate: v => v > new Date().getFullYear() + 1 ? "Проверьте год" : null },
          { id: "color", type: "text", label: "Цвет" },
          { id: "plate", type: "text", label: "Государственный регистрационный знак", required: false, placeholder: "А123ВС777" },
          { id: "pts", type: "text", label: "ПТС или электронный ПТС: номер и дата выдачи", placeholder: "ЭПТС № 164301000000000 от 10.03.2021" },
          { id: "sts", type: "text", label: "СТС: серия, номер", required: false, placeholder: "99 00 123456" },
          { id: "mileage", type: "number", label: "Пробег по одометру, км", required: false },
          { id: "defects", type: "textarea", label: "Известные недостатки", required: false, hint: "Каждый с новой строки. Всё, что указано, покупатель потом не сможет предъявить продавцу",
            placeholder: "Скол на лобовом стекле\nКоррозия на арке заднего правого колеса" },
          { id: "keys", type: "number", label: "Сколько комплектов ключей?", min: 1 },
        ],
      },
      {
        id: "deal", title: "Цена и передача",
        questions: [
          { id: "city", type: "text", label: "Город", placeholder: "г. Москва" },
          { id: "doc_date", type: "date", future: true, label: "Дата договора" },
          { id: "price", type: "money", label: "Цена", suffix: "₽", min: 1 },
          { id: "pay", type: "choice", label: "Как платит покупатель?", options: [
            { value: "cash", label: "Наличными при подписании" },
            { value: "transfer_before", label: "Переводом до подписания" },
            { value: "transfer_after", label: "Переводом после подписания", hint: "Укажем срок оплаты" },
          ] },
          { id: "pay_days", type: "number", label: "В течение скольких дней после подписания оплатить?", min: 1, show: a => a.pay === "transfer_after" },
          { id: "handover", type: "choice", label: "Когда передаётся машина?", options: [
            { value: "now", label: "При подписании договора" },
            { value: "after_pay", label: "После полной оплаты" },
          ] },
        ],
      },
      {
        id: "parties", title: "Стороны",
        questions: [...person("seller", "продавца"), ...person("buyer", "покупателя")],
      },
    ],

    derive,

    render(a, d) {
      const P = [];
      const H = t => P.push({ text: t, align: "center", bold: true, before: 180, after: 60, keepNext: true });
      const T = t => P.push({ text: t, indent: true });
      const who = (p, role) => `${F(a[p + "_name"], "ФИО")}, ${F(U.fmtDate(U.date(a[p + "_birth"])), "дата рождения")} г. р., паспорт ${F(a[p + "_passport"], "паспорт")}, зарегистрированный(ая) по адресу: ${F(a[p + "_address"], "адрес")}, именуемый(ая) в дальнейшем «${role}»`;
      const money = d.price ? C.rubles(d.price) : F(null, "цена");

      P.push({ text: "ДОГОВОР КУПЛИ-ПРОДАЖИ ТРАНСПОРТНОГО СРЕДСТВА", align: "center", bold: true, after: 120 });
      P.push({ text: `${F(a.city, "город")}                                                                          ${F(U.fmtDateLong(d.signed), "дата")}`, align: "left", after: 240 });
      T(`${who("seller", "Продавец")}, с одной стороны, и ${who("buyer", "Покупатель")}, с другой стороны, заключили настоящий договор о нижеследующем.`);

      H("1. Предмет договора");
      T("1.1. Продавец передаёт в собственность Покупателю, а Покупатель принимает и оплачивает транспортное средство (далее — Автомобиль):");
      P.push({ text: [
        `марка, модель: ${F(a.make, "марка и модель")}`,
        `идентификационный номер (VIN): ${F(a.vin ? String(a.vin).trim().toUpperCase() : null, "VIN")}`,
        `год выпуска: ${F(a.year, "год")}`,
        `цвет: ${F(a.color, "цвет")}`,
        a.plate ? `государственный регистрационный знак: ${String(a.plate).toUpperCase()}` : null,
        `паспорт транспортного средства: ${F(a.pts, "ПТС")}`,
        a.sts ? `свидетельство о регистрации ТС: ${a.sts}` : null,
        a.mileage ? `пробег по показаниям одометра: ${U.money(a.mileage)} км` : null,
      ].filter(Boolean).join("\n"), align: "left", leftIndent: 709 });
      T("1.2. Продавец гарантирует, что Автомобиль принадлежит ему на праве собственности, не продан, не заложен, в споре и под арестом (запретом) не состоит, не является предметом прав третьих лиц (ст. 460 ГК РФ).");

      H("2. Цена и порядок расчётов");
      T(`2.1. Цена Автомобиля составляет ${money}.`);
      T({
        cash: "2.2. Покупатель уплачивает цену наличными денежными средствами при подписании договора. Получение денег Продавец подтверждает собственноручной записью в разделе 6 договора.",
        transfer_before: "2.2. Цена уплачена Покупателем до подписания договора переводом на банковский счёт Продавца. Подписывая договор, Продавец подтверждает получение денежных средств в полном объёме.",
        transfer_after: `2.2. Покупатель уплачивает цену переводом на банковский счёт Продавца в течение ${F(a.pay_days, "число")} дней со дня подписания договора по реквизитам: ______________________________________. Обязанность считается исполненной в день зачисления денежных средств на счёт Продавца.`,
      }[a.pay] || F(null, "порядок оплаты"));

      H("3. Передача Автомобиля");
      T(a.handover === "after_pay"
        ? "3.1. Продавец передаёт Покупателю Автомобиль в течение одного дня после получения цены в полном объёме по акту приёма-передачи."
        : "3.1. Продавец передаёт Покупателю Автомобиль при подписании договора. Договор одновременно является актом приёма-передачи Автомобиля.");
      T(`3.2. Вместе с Автомобилем передаются: паспорт транспортного средства (либо сведения электронного паспорта), свидетельство о регистрации ТС (при наличии), ${F(a.keys, "число")} комплект(а) ключей (ст. 456 ГК РФ).`);
      T("3.3. Право собственности на Автомобиль, а также риск его случайной гибели и повреждения переходят к Покупателю с момента передачи Автомобиля (ст. 223, 459 ГК РФ).");

      H("4. Состояние Автомобиля");
      T("4.1. Покупатель осмотрел Автомобиль, проверил его комплектность и техническое состояние. Автомобиль передаётся в состоянии, в котором он находится на момент передачи, с учётом износа, соответствующего году выпуска и пробегу.");
      if (d.defects.length) T("4.2. Продавец сообщил Покупателю о следующих недостатках Автомобиля, с которыми Покупатель согласен:" + d.defects.map(x => `\n— ${x}`).join(""));
      else T("4.2. О недостатках Автомобиля, не оговорённых в договоре, Продавцу неизвестно.");
      T(`4.3. Продавец отвечает за недостатки, которые возникли до передачи Автомобиля и не были оговорены в договоре (ст. 475 ГК РФ), если Покупатель докажет, что Продавец знал или должен был знать о них.`);

      H("5. Заключительные положения");
      T("5.1. Покупатель обязан в течение десяти дней со дня приобретения Автомобиля обратиться в регистрационное подразделение Госавтоинспекции для внесения изменений в регистрационные данные в связи со сменой владельца (п. 3 ч. 3 ст. 8 Федерального закона от 03.08.2018 № 283-ФЗ) и застраховать свою гражданскую ответственность по ОСАГО.");
      T("5.2. Договор составлен в трёх экземплярах: по одному для каждой из сторон и один для регистрационного подразделения (если потребуется).");

      H("6. Подписи сторон");
      if (a.pay === "cash") P.push({ text: `Деньги в сумме ${money} получил(а) полностью:\n\n____________________ (подпись)    __________________________________________ (ФИО продавца полностью)`, align: "left", after: 240 });
      if (a.handover !== "after_pay") P.push({ text: "Автомобиль, документы и ключи получил(а), претензий к комплектности и внешнему состоянию не имею:\n\n____________________ (подпись)    __________________________________________ (ФИО покупателя полностью)", align: "left", after: 240 });
      P.push({ text: `Продавец: ${F(a.seller_name, "ФИО")}\nТел.: ${F(a.seller_phone, "телефон")}\n\n____________ / ${F(U.shortName(a.seller_name), "И. О. Фамилия")}`, align: "left", after: 240 });
      P.push({ text: `Покупатель: ${F(a.buyer_name, "ФИО")}\nТел.: ${F(a.buyer_phone, "телефон")}\n\n____________ / ${F(U.shortName(a.buyer_name), "И. О. Фамилия")}`, align: "left" });
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (a.role !== "seller") {
        g.push({ title: "До оплаты проверьте машину по базам.", text: "Ограничения и розыск — на сайте Госавтоинспекции (проверка автомобиля по VIN). Залог — в реестре уведомлений о залоге на reestr-zalogov.ru. Если машина в залоге у банка, её могут забрать и у нового владельца." });
        g.push({ title: "Сверьте VIN на кузове с ПТС и СТС.", text: "И паспорт продавца с данными собственника в ПТС." });
        g.push({ title: `Зарегистрируйте машину до ${d.regDeadline ? U.fmtDate(d.regDeadline) : "истечения 10 дней"}.`, text: "Через Госуслуги или в Госавтоинспекции. Перед этим оформите полис ОСАГО на себя: полис продавца на вас не распространяется." });
      } else {
        g.push({ title: "Не отдавайте машину до получения денег.", text: "Наличные пересчитайте, перевод дождитесь на счёте." });
        g.push({ title: "Проследите за регистрацией.", text: "Пока машина числится за вами, вам могут приходить штрафы с камер и налог. Если покупатель не зарегистрировал машину за 10 дней, вы можете прекратить её регистрацию сами по заявлению в Госавтоинспекцию, приложив договор. На штрафы, пришедшие после продажи, — жалоба с этим договором (Д-50)." });
      }
      g.push({ title: "Распечатайте три экземпляра и подпишите все.", text: "Нотариус не нужен." });
      return g;
    },

    fileName(a) { return "Договор купли-продажи автомобиля" + (a.make ? " — " + String(a.make).slice(0, 30) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d49 = spec;
})(typeof window !== "undefined" ? window : globalThis);
