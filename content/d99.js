/*
 * Д-99. Договор дарения денег (с распиской о получении) — в том числе родителям на покупку жилья ребёнку в браке.
 * Основа: ГК РФ — ст. 572 (дарение; обещание дарения — в будущем), ст. 574 (письменная форма обязательна для
 * обещания дарения и если даритель — юрлицо, а сумма больше 3 000 руб.), ст. 575 (запрет дарения свыше 3 000 руб.
 * от имени малолетних и т. п.), ст. 577 (отказ от исполнения обещания), ст. 578 (отмена дарения). СК РФ — п. 1
 * ст. 36 (подаренное одному супругу — его личное имущество). НК РФ — п. 18.1 ст. 217 (деньги в дар от физлица
 * НДФЛ не облагаются). 115-ФЗ — банк может спросить об источнике крупных сумм.
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;
  const num = x => (typeof x === "number" && x > 0 ? x : 0);

  function derive(a) {
    const amount = num(a.amount);
    const future = a.when === "future";
    return { amount, future, transfer: a.method === "transfer" };
  }

  const spec = {
    id: "d99",
    code: "Д-99",
    title: "Договор дарения денег",
    lead: "Родители дарят деньги на квартиру, бабушка — внуку, друг — на свадьбу. Договор с распиской: подтвердит, что деньги подарены и в браке не делятся, а налог платить не нужно. Займёт около 4 минут.",
    status: "draft",
    actual: "17.11.2026",
    defaults: { when: "now", method: "transfer" },

    steps: [
      {
        id: "gift", title: "Подарок",
        questions: [
          { id: "amount", type: "money", label: "Сумма", suffix: "₽" },
          { id: "method", type: "choice", label: "Как передаются деньги", options: [
            { value: "transfer", label: "Переводом на счёт", hint: "Надёжнее: в выписке останется след" },
            { value: "cash", label: "Наличными" },
          ] },
          { id: "account", type: "text", label: "Счёт получателя", show: a => a.method === "transfer", required: false, placeholder: "счёт № 40817… в ПАО «Банк»" },
          { id: "when", type: "choice", label: "Когда", options: [
            { value: "now", label: "Сейчас, при подписании" },
            { value: "future", label: "Позже — обещаю подарить", hint: "Например, к дате покупки квартиры" },
          ] },
          { id: "pay_date", type: "date", label: "До какой даты", show: a => a.when === "future", future: true },
          { id: "purpose", type: "text", label: "На что, если хотите указать", required: false, placeholder: "на приобретение квартиры по адресу: …", hint: "Цель не обязательна. Но помогает доказать, что квартира куплена на подаренные деньги и является личной собственностью одаряемого" },
          { id: "personal", type: "choice", label: "Получатель в браке — подарок только ему (ей)?", options: [
            { value: "yes", label: "Да, лично ему (ей)" }, { value: "no", label: "Неважно или не в браке" },
          ] },
        ],
      },
      {
        id: "parties", title: "Стороны",
        questions: [
          { id: "donor_name", type: "text", label: "Даритель — ФИО" },
          { id: "donor_birth", type: "date", label: "Дата рождения дарителя" },
          { id: "donor_passport", type: "text", label: "Паспорт дарителя", required: false, placeholder: "4510 123456, выдан ГУ МВД России по г. Москве 01.02.2015" },
          { id: "donor_address", type: "text", label: "Адрес дарителя" },
          { id: "relation", type: "text", label: "Кем даритель приходится получателю", required: false, placeholder: "мать" },
          { id: "buyer_name", type: "text", label: "Одаряемый — ФИО", autocomplete: "name" },
          { id: "buyer_birth", type: "date", label: "Дата рождения одаряемого" },
          { id: "buyer_passport", type: "text", label: "Паспорт одаряемого", required: false },
          { id: "buyer_address", type: "text", label: "Адрес одаряемого", autocomplete: "street-address" },
          { id: "city", type: "text", label: "Город подписания", placeholder: "Москва" },
        ],
      },
    ],

    derive,

    stop(a, d) {
      const b = U.date(a.buyer_birth);
      if (b && U.daysBetween(b, U.today()) < 14 * 365.25 && d.amount > 3000) return { soft: true, title: "Одаряемому меньше 14 лет.", text: "Договор за ребёнка подписывает родитель как законный представитель. Деньги на счёт ребёнка расходовать можно только в его интересах, крупные снятия — с разрешения опеки (ст. 37 ГК)." };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      const donor = F(a.donor_name, "даритель"), donee = F(a.buyer_name, "одаряемый");
      const sum = d.amount ? `${U.money(d.amount)} (${C.words(d.amount)}) рублей` : F(null, "сумма");
      C.title(P, "ДОГОВОР", "дарения денежных средств");
      P.push({ text: `г. ${F(a.city, "город")}                                                   «___» ____________ 20__ г.`, align: "left", after: 240 });
      T(`${donor}, ${F(U.fmtDate(U.date(a.donor_birth)), "дата")} г. р., ${C.passport(a.donor_passport)}, зарегистрированный(ая) по адресу: ${F(a.donor_address, "адрес")} (далее — Даритель), и ${donee}, ${F(U.fmtDate(U.date(a.buyer_birth)), "дата")} г. р., ${C.passport(a.buyer_passport)}, зарегистрированный(ая) по адресу: ${F(a.buyer_address, "адрес")} (далее — Одаряемый), заключили настоящий договор.`);
      T(`1. Даритель ${d.future ? "обязуется безвозмездно передать" : "безвозмездно передаёт"} Одаряемому в собственность денежные средства в сумме ${sum}` + (a.purpose ? ` ${String(a.purpose).trim().replace(/\.$/, "")}` : "") + ".");
      T(`2. Деньги передаются ${d.transfer ? "безналичным переводом на счёт Одаряемого" + (a.account ? ` (${a.account})` : "") : "наличными"} ${d.future ? `в срок до ${F(U.fmtDate(U.date(a.pay_date)), "дата")}` : (d.transfer ? "в день подписания договора" : "при подписании договора")}. ${d.transfer ? "Подтверждение — банковский документ о переводе с указанием «дарение по договору от …»." : "Передача подтверждается распиской Одаряемого."}`);
      if (a.relation) T(`3. Даритель приходится Одаряемому: ${String(a.relation).trim()}.`);
      let n = a.relation ? 4 : 3;
      if (a.personal === "yes") T(`${n++}. Денежные средства дарятся лично Одаряемому и являются его (её) личной собственностью; на них и на имущество, приобретённое на них, не распространяется режим общей собственности супругов (п. 1 ст. 36 Семейного кодекса РФ).`);
      T(`${n++}. Даритель подтверждает, что денежные средства принадлежат ему на законных основаниях и не обременены правами третьих лиц.`);
      T(`${n++}. Доход в виде денежных средств, полученных в дар от физического лица, не облагается налогом на доходы физических лиц (п. 18.1 ст. 217 Налогового кодекса РФ).`);
      if (d.future) T(`${n++}. Даритель вправе отказаться от исполнения обещания дарения, если его имущественное, семейное положение или состояние здоровья изменилось настолько, что исполнение договора приведёт к существенному снижению уровня его жизни (п. 1 ст. 577 ГК РФ).`);
      T(`${n++}. Договор вступает в силу с момента подписания, составлен в двух экземплярах — по одному для каждой стороны.`);
      P.push({ text: `Даритель: ____________ / ${F(U.shortName(a.donor_name), "И. О. Фамилия")}\n\nОдаряемый: ____________ / ${F(U.shortName(a.buyer_name), "И. О. Фамилия")}`, align: "left", before: 360 });
      if (!d.transfer && !d.future) {
        P.push({ pageBreak: true });
        C.title(P, "РАСПИСКА", "в получении денежных средств в дар");
        T(`Я, ${donee}, получил(а) от ${donor} в дар по договору дарения денежных средств от «___» ____________ 20__ г. наличные денежные средства в сумме ${sum}. Деньги пересчитаны, претензий не имею.`);
        P.push({ text: `«___» ____________ 20__ г.            ____________ / ${F(U.shortName(a.buyer_name), "И. О. Фамилия")}`, align: "left", before: 360 });
      }
      return P;
    },

    guidance(a, d) {
      const g = [
        { title: "Нотариус не нужен.", text: "Договор дарения денег между людьми — в простой письменной форме. Подпишите два экземпляра, по одному каждому." },
        d.transfer ? { title: "Переведите с пометкой «дарение».", text: "В назначении платежа: «Дарение по договору от …». Сохраните выписку — это главное доказательство." } : { title: "Сохраните расписку.", text: "Наличные сложнее подтвердить. Если это деньги на квартиру, лучше перевести на счёт или положить на аккредитив." },
        { title: "Налога нет.", text: "Деньги в подарок от любого физического лица НДФЛ не облагаются. Декларацию подавать не нужно. Банк при крупном поступлении может спросить, откуда деньги, — покажите договор." },
      ];
      if (a.personal === "yes") g.push({ title: "Если покупаете на эти деньги квартиру.", text: "Платите за неё с того же счёта и сохраните выписку, договор дарения и договор покупки. При разводе это поможет доказать, что квартира — ваша личная (ст. 36 СК)." });
      return g;
    },

    fileName() { return "Договор дарения денег"; },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d99 = spec;
})(typeof window !== "undefined" ? window : globalThis);
