    const amount = typeof a.amount === "number" && a.amount > 0 ? a.amount : null;
    const money = ["refund", "price_cut", "costs"].includes(a.demand);
    const claimSum = a.demand === "refund" ? price : money ? amount : null;
    const fee = claimSum ? C.courtFee(claimSum) : null;
    return { work, handed, found, wEnd, twoY, inWarranty, late, price, amount, money, claimSum, fee, date: U.date(a.doc_date) };
