/*
 * К-7. Калькулятор госпошлины в суд общей юрисдикции (мировой судья, районный суд).
 * Основа: НК РФ в ред. 259-ФЗ от 08.08.2024 (с 08.09.2024; после этого ст. 333.19 не менялась):
 * ст. 333.19 п. 1 — пп. 1 (шкала по цене иска: до 100 000 — 4 000; …; свыше 100 млн — 314 000 + 0,15%, не более 900 000),
 * пп. 2 (судебный приказ — 50% пошлины по иску), пп. 3 (неимущественный — 3 000 для физлица), пп. 5 (развод — 5 000),
 * пп. 12 (дубликат листа, отмена заочного решения — 1 500), пп. 13 (восстановление срока предъявления листа — 3 000),
 * пп. 19 (апелляционная, частная жалоба — 3 000), пп. 20 (кассационная — 5 000), пп. 21 (в ВС РФ — 7 000);
 * ст. 333.20 п. 1 — пп. 1 (имущественное + неимущественное — обе пошлины), пп. 12 (развод + раздел имущества — обе),
 * пп. 13 (пошлина за отменённый судебный приказ засчитывается); ст. 333.36 п. 1 пп. 1–4 (трудовые, алименты, вред
 * здоровью и кормилец, вред от преступления — освобождены), п. 2 пп. 2–5 и п. 3 (инвалиды I, II групп, дети-инвалиды,
 * инвалиды с детства, ветераны боевых действий, потребители, пенсионеры по искам к СФР — освобождены при цене до 1 млн;
 * свыше — пошлина по шкале минус пошлина с 1 млн); ст. 333.40 п. 1 пп. 3 (возврат 70/50/30%); ст. 52 п. 6 (округление до
 * рубля). Подсудность — ст. 23, 24 ГПК (мировой судья: имущественные до 50 000, потребительские до 100 000).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const rub = n => U.money(Math.round(n)) + " ₽";
  const pct = x => String(x).replace(".", ",") + "%";

  // [нижняя граница, фикс, процент] — пп. 1 п. 1 ст. 333.19
  const SCALE = [
    [0, 4000, 0], [100000, 4000, 3], [300000, 10000, 2.5], [500000, 15000, 2], [1000000, 25000, 1],
    [3000000, 45000, 0.7], [8000000, 80000, 0.35], [24000000, 136000, 0.3], [50000000, 214000, 0.2], [100000000, 314000, 0.15],
  ];
  function scale(price) {
    let row = SCALE[0];
    for (const r of SCALE) if (price > r[0]) row = r;
    const fee = Math.min(900000, row[1] + (price - row[0]) * row[2] / 100);
    return { fee: Math.round(fee), row };
  }
  const formula = (price, row) => row[2] ? `${U.money(row[1])} + ${pct(row[2])} × (${U.money(price)} − ${U.money(row[0])})` : "фиксированная";

  const FULL = { labor: "трудовой спор", alimony: "взыскание алиментов", health: "вред здоровью или смерть кормильца", crime: "вред от преступления" };
  const CAP = { consumer: "защита прав потребителей", disabled: "инвалид I или II группы, ребёнок-инвалид, инвалид с детства", veteran: "ветеран боевых действий или военной службы", pensioner: "пенсионер — иск к Социальному фонду или НПФ" };
  const FIXED = { nonprop: 3000, divorce: 5000, appeal: 3000, cassation: 5000, supreme: 7000, duplicate: 1500, restore: 3000 };

  const spec = {
    id: "k7",
    code: "К-7",
    title: "Госпошлина в суд",
    lead: "Сколько платить за иск, судебный приказ, развод или жалобу по новым ставкам НК. Учтём льготы — потребителям, работникам, по алиментам — и зачёт пошлины за отменённый приказ.",
    status: "draft",
    defaults: { kind: "claim", benefit: "none", moral: "no", had_order: "no" },

    fields: [
      { id: "kind", type: "select", label: "Что подаёте", options: [
        { value: "claim", label: "Иск о взыскании денег или имущества" },
        { value: "order", label: "Заявление о судебном приказе" },
        { value: "nonprop", label: "Иск без суммы: моральный вред, обязать что-то сделать" },
        { value: "divorce", label: "Иск о разводе" },
        { value: "split", label: "Развод и раздел имущества" },
        { value: "appeal", label: "Апелляционная или частная жалоба" },
        { value: "cassation", label: "Кассационная жалоба" },
        { value: "supreme", label: "Жалоба в Верховный суд" },
        { value: "duplicate", label: "Дубликат исполнительного листа или отмена заочного решения" },
        { value: "restore", label: "Восстановление срока предъявления исполнительного листа" },
      ] },
      { id: "price", type: "money", label: a => a.kind === "split" ? "Стоимость имущества, которое просите себе" : a.kind === "order" ? "Сумма долга" : "Цена иска", suffix: "₽",
        show: a => ["claim", "order", "split"].includes(a.kind), hint: a => a.kind === "split" ? "Сумма, которую вы просите выделить себе" : "Сумма всех денежных требований: долг, неустойка, проценты. Судебные расходы и моральный вред в цену иска не входят" },
      { id: "moral", type: "choice", label: "Требуете ещё компенсацию морального вреда или другое требование без суммы?", show: a => a.kind === "claim", options: [
        { value: "no", label: "Нет" },
        { value: "yes", label: "Да", hint: "За него отдельно 3 000 ₽ (п. 1 ст. 333.20 НК)" },
      ] },
      { id: "benefit", type: "select", label: "Льгота", show: a => ["claim", "order", "nonprop"].includes(a.kind), hint: "Если подходит несколько — выберите любую", options: [
        { value: "none", label: "Нет льготы" },
        { value: "consumer", label: "Спор с продавцом, исполнителем, застройщиком (права потребителей)" },
        { value: "labor", label: "Спор с работодателем: зарплата, увольнение и другое" },
        { value: "alimony", label: "Взыскиваю алименты" },
        { value: "health", label: "Вред здоровью или смерть кормильца" },
        { value: "crime", label: "Вред от преступления" },
        { value: "disabled", label: "Я инвалид I или II группы, ребёнок-инвалид, инвалид с детства" },
        { value: "veteran", label: "Я ветеран боевых действий или военной службы (спор о льготах ветерана)" },
        { value: "pensioner", label: "Я пенсионер, иск к Социальному фонду или НПФ" },
      ] },
      { id: "had_order", type: "choice", label: "По этому долгу уже был судебный приказ, и его отменили?", show: a => a.kind === "claim", options: [
        { value: "no", label: "Нет" },
        { value: "yes", label: "Да", hint: "Уплаченная за приказ пошлина засчитывается" },
      ] },
      { id: "order_paid", type: "money", label: "Сколько заплатили за приказ", suffix: "₽", show: a => a.kind === "claim" && a.had_order === "yes" },
    ],

    compute(a) {
      const k = a.kind;
      const notes = [];
      let fee = 0, rows = [], court = null;
      const price = typeof a.price === "number" && a.price > 0 ? a.price : null;
      const needPrice = ["claim", "order", "split"].includes(k);
      if (needPrice && !price) return null;
      const benefit = ["claim", "order", "nonprop"].includes(k) ? a.benefit : "none";

      if (k === "claim" || k === "order" || k === "split") {
        const s = scale(price);
        let base = k === "order" ? Math.round(s.fee / 2) : s.fee;
        rows.push([k === "order" ? "Судебный приказ: 50% пошлины по иску" : k === "split" ? "Раздел имущества" : "Имущественное требование", `${formula(price, s.row)}` + (k === "order" ? ` = ${rub(s.fee)}; × 50%` : ""), rub(base)]);
        if (FULL[benefit]) {
          base = 0; rows.push([`Льгота: ${FULL[benefit]}`, "освобождены полностью (п. 1 ст. 333.36 НК)", "−"]);
        } else if (CAP[benefit]) {
          if (price <= 1000000) { base = 0; rows.push([`Льгота: ${CAP[benefit]}`, "цена до 1 000 000 ₽ — освобождены (п. 2, 3 ст. 333.36 НК)", "−"]); }
          else {
            const minus = k === "order" ? 12500 : 25000;
            base = Math.max(0, base - minus);
            rows.push([`Льгота: ${CAP[benefit]}`, `цена больше 1 млн — пошлина минус пошлина с 1 000 000 ₽ (п. 3 ст. 333.36 НК)`, "−" + rub(minus)]);
          }
        }
        fee += base;
        if (k === "claim" && a.moral === "yes") {
          const m = FULL[benefit] || CAP[benefit] ? 0 : 3000;
          fee += m;
          rows.push(["Требование без суммы (моральный вред)", m ? "пп. 3 п. 1 ст. 333.19 НК" : "по льготе не платится", rub(m)]);
        }
        if (k === "split") { fee += 5000; rows.push(["Расторжение брака", "пп. 5 п. 1 ст. 333.19 НК", rub(5000)]); notes.push("При разводе с разделом имущества платят обе пошлины (пп. 12 п. 1 ст. 333.20 НК)."); }
        if (k === "claim" || k === "order") {
          const limit = benefit === "consumer" ? 100000 : 50000;
          court = k === "order" || price <= limit ? "мировой судья" : "районный суд";
          if (k === "claim") notes.push(price <= limit
            ? `Цена до ${U.money(limit)} ₽ — иск к мировому судье (ст. 23 ГПК).`
            : `Цена больше ${U.money(limit)} ₽ — иск в районный суд (ст. 24 ГПК).`);
        }
        if (k === "order") notes.push("Судебный приказ выдаёт мировой судья по бесспорным требованиям до 500 000 ₽: по письменной сделке, расписке, начисленной, но не выплаченной зарплате и др. (ст. 121, 122 ГПК). Если должник возразит, приказ отменят, а пошлину зачтут при подаче иска.");
        if (k === "order" && price > 500000) return { error: "Судебный приказ выдают при сумме до 500 000 ₽ (ч. 1 ст. 121 ГПК). Для большей суммы — иск." };
      } else {
        let base = FIXED[k];
        const names = { nonprop: ["Требование без суммы", "пп. 3 п. 1 ст. 333.19 НК"], divorce: ["Расторжение брака", "пп. 5 п. 1 ст. 333.19 НК"], appeal: ["Апелляционная или частная жалоба", "пп. 19 п. 1 ст. 333.19 НК"], cassation: ["Кассационная жалоба", "пп. 20 п. 1 ст. 333.19 НК"], supreme: ["Жалоба в Верховный суд", "пп. 21 п. 1 ст. 333.19 НК"], duplicate: ["Дубликат листа или отмена заочного решения", "пп. 12 п. 1 ст. 333.19 НК"], restore: ["Восстановление срока предъявления листа", "пп. 13 п. 1 ст. 333.19 НК"] }[k];
        rows.push([names[0], names[1], rub(base)]);
        if (k === "nonprop" && (FULL[benefit] || CAP[benefit])) { base = 0; rows.push([`Льгота: ${FULL[benefit] || CAP[benefit]}`, "освобождены (ст. 333.36 НК)", "−"]); }
        fee = base;
        if (k === "divorce") notes.push("Если детей нет и оба согласны — дешевле развестись в ЗАГСе (Д-20). Если есть спор о детях или имуществе — через суд.");
        if (["appeal", "cassation", "supreme"].includes(k)) notes.push("Истцы по трудовым спорам, алиментам, вреду здоровью, а также потребители и другие льготники по ст. 333.36 НК, как правило, не платят пошлину и за жалобу — уточните в суде по своему делу.");
      }

      let toPay = fee;
      const paid = typeof a.order_paid === "number" && a.order_paid > 0 ? Math.round(a.order_paid) : 0;
      if (k === "claim" && a.had_order === "yes" && fee > 0 && paid) {
        toPay = Math.max(0, fee - paid);
        rows.push(["Зачёт пошлины за отменённый приказ", "пп. 13 п. 1 ст. 333.20 НК", "−" + rub(Math.min(paid, fee))]);
        notes.push("К иску приложите определение об отмене приказа и квитанцию об уплате пошлины за него — суд зачтёт её.");
      }
      if (fee > 0) notes.push("Если стороны заключат мировое соглашение, истец откажется от иска или ответчик признает его, вернут 70% пошлины в первой инстанции, 50% — в апелляции, 30% — в кассации (пп. 3 п. 1 ст. 333.40 НК).");
      if (fee > 0 && ["claim", "order", "split", "nonprop"].includes(k)) notes.push("Выиграете — пошлину вам возместит проигравшая сторона (ст. 98 ГПК).");
      notes.push("Реквизиты для оплаты — на сайте суда. Можно оплатить на Госуслугах. Приложите квитанцию к заявлению.");

      return {
        summary: [
          { label: "Госпошлина", value: rub(fee), big: toPay === fee },
          toPay !== fee ? { label: "Доплатить с учётом зачёта", value: rub(toPay), big: true } : null,
          court ? { label: "Куда подавать", value: court } : null,
        ].filter(Boolean),
        table: { head: ["Что", "Как считается", "Сумма"], rows },
        notes,
        related: k === "divorce" || k === "split" ? [{ id: "d21", text: "Иск о расторжении брака" }] : k === "order" ? [{ id: "d35", text: "Претензия о возврате долга", fill: { amount: a.price } }] : k === "restore" ? [{ id: "d60", text: "Восстановить срок", fill: { route: "restore" } }] : k === "duplicate" ? [{ id: "d60", text: "Исполнительный лист" }] : [{ id: "d60", text: "Исполнительный лист после суда", fill: k === "claim" ? { what: "money", sum: a.price } : null }],
      };
    },
  };

  spec.scale = scale;
  global.CALCS = global.CALCS || {};
  global.CALCS.k7 = spec;
})(typeof window !== "undefined" ? window : globalThis);
