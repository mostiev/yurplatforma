/*
 * Д-51. Претензия (заявление) в страховую компанию по ОСАГО.
 * Основа: Федеральный закон от 25.04.2002 № 40-ФЗ — п. 15.1 ст. 12 (для легковых машин граждан основная форма —
 * организация и оплата ремонта), п. 16.1 ст. 12 (выплата деньгами — в перечисленных случаях, в т. ч. по письменному
 * соглашению), п. 19 ст. 12 (выплата — по Единой методике с учётом износа не более 50%), п. 14 ст. 12 (стоимость
 * независимой экспертизы — в составе убытков), п. 21 ст. 12 (20 календарных дней, за исключением нерабочих
 * праздничных, на выплату или направление на ремонт; неустойка 1% в день от размера возмещения; финансовая санкция
 * 0,05% от страховой суммы за просрочку мотивированного отказа), п. 1 ст. 16.1 (заявление страховщику обязательно до
 * суда; рассмотрение 10 календарных дней без нерабочих праздничных), п. 3 ст. 16.1 (штраф 50% в суде).
 * ППВС № 31 от 08.11.2022, п. 56 — если страховщик не организовал ремонт, потерпевший вправе требовать убытки.
 * Далее — финансовый уполномоченный (123-ФЗ). Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  // «нерабочие праздничные дни» — только дни из ч. 1 ст. 112 ТК (1–8 января, 23 февраля, 8 марта, 1 и 9 мая, 12 июня,
  // 4 ноября), без обычных выходных и без перенесённых выходных
  const HOLI = ["01-01", "01-02", "01-03", "01-04", "01-05", "01-06", "01-07", "01-08", "02-23", "03-08", "05-01", "05-09", "06-12", "11-04"];
  function addCalendarExHolidays(start, n) {
    let d = start, k = 0;
    while (d && k < n) { d = U.addDays(d, 1); if (!HOLI.includes(U.iso(d).slice(5))) k++; }
    return d;
  }

  function derive(a) {
    const filed = U.date(a.filed_date);
    const due = filed ? addCalendarExHolidays(filed, 20) : null;
    const paid = typeof a.paid === "number" ? a.paid : 0;
    const expert = typeof a.expert_sum === "number" ? a.expert_sum : null;
    const diff = a.problem === "underpaid" || a.problem === "cash_instead" ? (expert != null ? Math.max(0, Math.round((expert - paid) * 100) / 100) : null) : expert;
    // неустойка 1% в день с 21-го дня: база — недоплаченная сумма, конец — сегодня или дата выплаты
    const payDate = U.date(a.paid_date);
    let penalty = null, penaltyDays = 0;
    if (due && a.claim_penalty === "yes") {
      const base = a.problem === "nothing" ? (expert || null) : (a.problem === "late" ? (typeof a.paid === "number" ? a.paid : null) : diff);
      const end = a.problem === "late" && payDate ? payDate : U.today();
      if (base && end > due) { penaltyDays = U.daysBetween(due, end); penalty = Math.round(base * 0.01 * penaltyDays * 100) / 100; }
    }
    const answerDue = U.date(a.submit_date) ? addCalendarExHolidays(U.date(a.submit_date), 10) : null;
    return { filed, due, paid, expert, diff, penalty, penaltyDays, answerDue };
  }

  const PROBLEM = {
    nothing: "Ничего не выплатили и не выдали направление на ремонт",
    underpaid: "Выплатили слишком мало",
    cash_instead: "Выплатили деньгами вместо ремонта без моего согласия",
    late: "Выплатили, но позже 20 дней",
  };

  const spec = {
    id: "d51",
    code: "Д-51",
    title: "Претензия в страховую по ОСАГО",
    lead: "Страховая не заплатила, заплатила мало или вместо ремонта перечислила деньги с износом. Претензия — обязательный шаг перед финансовым уполномоченным и судом. Займёт около 7 минут.",
    status: "draft",

    steps: [
      {
        id: "case", title: "Случай",
        questions: [
          { id: "insurer", type: "text", label: "Страховая компания", placeholder: "ПАО СК «Страховая»" },
          { id: "insurer_address", type: "text", label: "Адрес страховой (филиала)", required: false },
          { id: "case_no", type: "text", label: "Номер убытка (выплатного дела)", required: false, placeholder: "ПР1234567" },
          { id: "accident", type: "text", label: "Дата и место ДТП", placeholder: "10.08.2026, г. Москва, ул. Профсоюзная, д. 1" },
          { id: "car", type: "text", label: "Ваш автомобиль и госномер", placeholder: "Kia Rio, А123ВС777" },
          { id: "policy", type: "text", label: "Полис ОСАГО (ваш или виновника)", required: false, placeholder: "ХХХ 0123456789" },
          { id: "filed_date", type: "date", label: "Когда вы подали заявление о страховом случае со всеми документами?" },
          { id: "problem", type: "choice", label: "Что не так?", options: Object.entries(PROBLEM).map(([value, label]) => ({ value, label })) },
          { id: "paid", type: "money", label: "Сколько выплатили?", suffix: "₽", min: 1, show: a => ["underpaid", "cash_instead", "late"].includes(a.problem) },
          { id: "paid_date", type: "date", label: "Когда выплатили?", show: a => ["underpaid", "cash_instead", "late"].includes(a.problem) },
          { id: "expert_sum", type: "money", label: "Сколько должно быть по независимой экспертизе?", suffix: "₽", min: 1, show: a => a.problem !== "late",
            hint: "Для «вместо ремонта» — стоимость ремонта без учёта износа. Нет экспертизы — оставьте пустым", required: false },
          { id: "expert", type: "text", label: "Экспертное заключение: кто и когда", required: false, show: a => typeof a.expert_sum === "number", placeholder: "ООО «Эксперт», заключение № 45 от 01.09.2026" },
          { id: "expert_cost", type: "money", label: "Сколько заплатили за экспертизу?", suffix: "₽", required: false, show: a => typeof a.expert_sum === "number" },
          { id: "claim_penalty", type: "choice", label: "Требовать неустойку 1% в день за просрочку?", options: [
            { value: "yes", label: "Да" },
            { value: "no", label: "Нет" },
          ] },
          { id: "submit_date", type: "date", future: true, label: "Когда отправите претензию?" },
        ],
      },
      {
        id: "you", title: "Вы",
        questions: [
          ...C.personQuestions(),
          { id: "refund_method", type: "choice", label: "Как получить деньги?", options: [
            { value: "requisites", label: "На счёт по реквизитам", hint: "Оставим строку, впишете от руки" },
            { value: "same", label: "По реквизитам, указанным в заявлении о страховом случае" },
          ] },
        ],
      },
    ],

    derive,

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      C.header({ name: a.insurer, nameLabel: "страховая компания", address: a.insurer_address, blank: true }, C.from(a), P);
      C.title(P, "ЗАЯВЛЕНИЕ (ПРЕТЕНЗИЯ)", "по договору ОСАГО (ст. 16.1 Федерального закона от 25.04.2002 № 40-ФЗ)");
      T(`В результате дорожно-транспортного происшествия ${F(a.accident, "дата и место")} повреждён принадлежащий мне автомобиль ${F(a.car, "автомобиль")}.` + (a.policy ? ` Гражданская ответственность застрахована по полису ОСАГО ${a.policy}.` : ""));
      T(`${F(U.fmtDate(d.filed), "дата")} я обратился(ась) к вам с заявлением о страховом возмещении и представил(а) все необходимые документы` + (a.case_no ? ` (убыток № ${a.case_no})` : "") + `. Страховое возмещение должно было быть предоставлено не позднее ${F(U.fmtDate(d.due), "дата")} — в течение 20 календарных дней, за исключением нерабочих праздничных дней (п. 21 ст. 12 Закона об ОСАГО).`);
      const pd = U.date(a.paid_date);
      if (a.problem === "nothing") T("До настоящего времени страховое возмещение не осуществлено: выплата не произведена, направление на ремонт не выдано, мотивированный отказ не направлен.");
      if (a.problem === "underpaid") T(`${F(U.fmtDate(pd), "дата")} вы выплатили ${F(U.money(d.paid), "сумма")} руб. Этой суммы недостаточно для возмещения ущерба.`);
      if (a.problem === "cash_instead") T(`${F(U.fmtDate(pd), "дата")} вы в одностороннем порядке заменили восстановительный ремонт денежной выплатой в размере ${F(U.money(d.paid), "сумма")} руб., рассчитанной с учётом износа. Соглашения о страховой выплате в денежной форме я не заключал(а), оснований для замены формы возмещения, предусмотренных п. 16.1 ст. 12 Закона об ОСАГО, нет. Для легковых автомобилей граждан страховое возмещение осуществляется путём организации и оплаты восстановительного ремонта (п. 15.1 ст. 12). Поскольку ремонт не организован, я вправе требовать возмещения убытков в размере стоимости восстановительного ремонта без учёта износа (ст. 15, 393, 397 ГК РФ; п. 56 постановления Пленума Верховного Суда РФ от 08.11.2022 № 31).`);
      if (a.problem === "late") T(`Страховое возмещение в размере ${F(U.money(d.paid), "сумма")} руб. выплачено только ${F(U.fmtDate(pd), "дата")}, то есть с нарушением срока.`);
      if (d.expert != null && a.problem !== "late") T(`Согласно ${F(a.expert, "экспертное заключение")}, ${a.problem === "cash_instead" ? "стоимость восстановительного ремонта без учёта износа" : "размер ущерба"} составляет ${U.money(d.expert)} руб.` + (a.problem !== "nothing" ? ` Недоплата — ${U.money(d.diff)} руб.` : ""));
      if (d.penalty) T(`За несоблюдение срока подлежит уплате неустойка в размере 1% от размера страхового возмещения за каждый день просрочки (п. 21 ст. 12 Закона об ОСАГО): ${U.money(a.problem === "late" ? d.paid : a.problem === "nothing" ? d.expert : d.diff)} руб. × 1% × ${d.penaltyDays} дн. = ${U.money(d.penalty)} руб.` + (a.problem === "late" ? "" : ` по состоянию на ${U.fmtDate(U.today())}`) + ".");
      P.push({ text: "ПРОШУ в течение 10 календарных дней (за исключением нерабочих праздничных дней) со дня получения настоящего заявления (п. 1 ст. 16.1 Закона об ОСАГО):", indent: true, keepNext: true });
      const items = [];
      if (a.problem === "nothing") items.push(d.expert != null ? `Выплатить страховое возмещение в размере ${U.money(d.expert)} руб. либо выдать направление на восстановительный ремонт.` : "Осуществить страховое возмещение: выдать направление на восстановительный ремонт либо произвести выплату в установленных законом случаях.");
      if (a.problem === "underpaid") items.push(`Доплатить страховое возмещение в размере ${F(d.diff != null ? U.money(d.diff) : null, "сумма")} руб.`);
      if (a.problem === "cash_instead") items.push(`Возместить убытки в размере разницы между стоимостью восстановительного ремонта без учёта износа и выплаченной суммой — ${F(d.diff != null ? U.money(d.diff) : null, "сумма")} руб.`);
      if (typeof a.expert_cost === "number" && a.expert_cost > 0) items.push(`Возместить расходы на независимую экспертизу — ${U.money(a.expert_cost)} руб. (п. 14 ст. 12 Закона об ОСАГО).`);
      if (d.penalty) items.push(`Уплатить неустойку в размере ${U.money(d.penalty)} руб.` + (a.problem === "late" ? "" : " и далее по день исполнения обязательства."));
      else if (a.claim_penalty === "yes") items.push("Уплатить неустойку за нарушение срока страхового возмещения (п. 21 ст. 12 Закона об ОСАГО).");
      items.forEach((x, i) => T(`${i + 1}. ${x}`));
      if (a.refund_method === "same") T("Денежные средства прошу перечислить по реквизитам, указанным в заявлении о страховом возмещении.");
      else P.push({ text: "Денежные средства прошу перечислить по реквизитам:\n________________________________________________________________\n________________________________________________________________", indent: true, align: "left" });
      T("В случае отказа я обращусь к уполномоченному по правам потребителей финансовых услуг, а затем в суд, где потребую также штраф в размере 50% (п. 3 ст. 16.1 Закона об ОСАГО) и компенсацию морального вреда.");
      C.attachments(P, [d.expert != null ? "Копия экспертного заключения." : null, typeof a.expert_cost === "number" ? "Документ об оплате экспертизы." : null, "Копия документа, удостоверяющего личность."].filter(Boolean));
      C.sign(P, a);
      return P;
    },

    guidance(a, d) {
      const g = [
        { title: "Отправьте заказным письмом с описью или отдайте в офис под отметку.", text: "Можно и через личный кабинет страховой. Страховая отвечает за 10 календарных дней, не считая нерабочих праздничных." },
        { title: "Не ответили или отказали — к финансовому уполномоченному.", text: "Обращение на finombudsman.ru, бесплатно. Без этого суд иск не примет. Решение финуполномоченного можно обжаловать в суд." },
      ];
      if (a.problem === "cash_instead" || a.problem === "underpaid") g.push({ title: "Сделайте независимую экспертизу, если её ещё нет.", text: "Эксперт-техник должен быть в реестре Минюста. Для спора о ремонте нужна стоимость ремонта без учёта износа по рыночным ценам и по Единой методике." });
      g.push({ title: "Сроки считаются по календарю.", text: `20 календарных дней без нерабочих праздничных дней (1–8 января, 23 февраля, 8 марта, 1 и 9 мая, 12 июня, 4 ноября). По нашему расчёту — до ${d.due ? U.fmtDate(d.due) : "—"}.` });
      return g;
    },

    reminders(a, d) { return [{ date: d.answerDue, title: "Страховщик должен ответить на претензию", text: "Если ответа нет или он не устраивает — обращение к финансовому уполномоченному." }]; },

    fileName(a) { return "Претензия ОСАГО" + (a.insurer ? " — " + String(a.insurer).replace(/[«»"]/g, "").slice(0, 30) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d51 = spec;
})(typeof window !== "undefined" ? window : globalThis);
