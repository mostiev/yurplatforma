/*
 * Д-18. Претензия застройщику о неустойке за просрочку передачи квартиры по ДДУ.
 * Основа: ч. 2 ст. 6 214-ФЗ (1/300 ставки ЦБ, действующей на день исполнения обязательства, от цены договора за каждый
 * день; гражданину — в двойном размере); ВС РФ, определение от 27.02.2024 № 127-КГ23-18-К4 (ставка — на последний день
 * срока по договору, для всего периода просрочки); моратории, когда неустойка не начисляется: ПП № 423 от 02.04.2020
 * (03.04.2020–31.12.2020), ПП № 479 от 26.03.2022 (29.03.2022–30.06.2023), ПП № 326 от 18.03.2024 с продлениями
 * ПП № 1916, № 925, № 2227 (22.03.2024–31.12.2025); п. 2 ПП № 326 — с 01.07.2023 по 31.12.2025 ставка не выше
 * действовавшей на 01.07.2023 (7,5%); ПП № 2227 от 30.12.2025 — отсрочка уплаты до 31.12.2026. Штраф в суде — 5%
 * (ч. 3 ст. 10 в ред. 266-ФЗ с 01.09.2024), моральный вред — ч. 2 ст. 10. Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  function derive(a) {
    const due = U.date(a.due_date);
    const end = a.handed === "yes" ? U.date(a.handed_date) : U.today();
    const price = typeof a.price === "number" ? a.price : null;
    return { due, end, price, calc: C.dduPenalty(price, due, end) };
  }

  const pct = x => String(x).replace(".", ",");

  const spec = {
    id: "d18",
    code: "Д-18",
    title: "Претензия застройщику о неустойке за просрочку",
    lead: "Застройщик сдал квартиру позже срока по ДДУ или до сих пор не сдал. Посчитаем неустойку с учётом всех мораториев и ограничений ставки. Займёт около 5 минут.",
    status: "draft",

    steps: [
      {
        id: "ddu", title: "Договор",
        questions: [
          { id: "developer", type: "text", label: "Застройщик", placeholder: "ООО «СЗ Новый дом»" },
          C.innQuestion("developer_inn", "ИНН застройщика"),
          { id: "developer_address", type: "text", label: "Адрес застройщика", hint: "Юридический адрес — в договоре или ЕГРЮЛ" },
          { id: "ddu", type: "text", label: "Договор участия в долевом строительстве: номер и дата", placeholder: "№ ДДУ-123/45 от 10.03.2023" },
          { id: "object", type: "text", label: "Квартира: адрес и номер", placeholder: "кв. № 45, г. Москва, ул. Строителей, корп. 2" },
          { id: "price", type: "money", label: "Цена договора", suffix: "₽", min: 1 },
          { id: "due_date", type: "date", label: "Срок передачи квартиры по договору (последний день)", hint: "Если в договоре «не позднее 4 квартала 2025» — это 31.12.2025" },
          { id: "handed", type: "choice", label: "Квартиру уже передали по акту?", options: [
            { value: "yes", label: "Да" },
            { value: "no", label: "Нет" },
          ] },
          { id: "handed_date", type: "date", label: "Дата передаточного акта", show: a => a.handed === "yes" },
          { id: "extension", type: "choice", label: "Вы подписывали допсоглашение о переносе срока?", options: [
            { value: "no", label: "Нет" },
            { value: "yes", label: "Да", hint: "Тогда срок — из допсоглашения. Уведомление застройщика без вашей подписи срок не меняет" },
          ] },
          { id: "refund", type: "choice", label: "Куда перечислить?", options: [
            { value: "requisites", label: "По реквизитам", hint: "Оставим строку" },
          ] },
        ],
      },
      {
        id: "you", title: "Вы",
        questions: [...C.personQuestions()],
      },
    ],

    derive,

    stop(a, d) {
      if (d.due && d.end && d.end <= d.due) return { title: "Просрочки нет.", text: "Квартира передана в срок или срок ещё не наступил." };
      if (d.calc && d.calc.error) return { title: "Нет ставки ЦБ на дату срока.", text: "Для сроков до 17.06.2019 расчёт пока не поддерживается — посчитайте вручную или обратитесь к юристу." };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      C.header({ name: a.developer, nameLabel: "застройщик", inn: a.developer_inn, address: a.developer_address }, C.from(a), P);
      C.title(P, "ПРЕТЕНЗИЯ", "о выплате неустойки за нарушение срока передачи объекта долевого строительства");
      T(`Между мной и ${F(a.developer, "застройщик")} заключён договор участия в долевом строительстве ${F(a.ddu, "номер и дата")}. Объект долевого строительства — ${F(a.object, "квартира")}. Цена договора — ${F(U.money(d.price), "цена")} руб., оплачена мною полностью.`);
      T(`Застройщик обязался передать объект не позднее ${F(U.fmtDate(d.due), "дата")}` + (a.extension === "yes" ? " (с учётом дополнительного соглашения)" : "") + ". " + (a.handed === "yes" ? `Объект передан только ${F(U.fmtDate(d.end), "дата")}.` : "До настоящего времени объект не передан."));
      T("В соответствии с ч. 2 ст. 6 Федерального закона от 30.12.2004 № 214-ФЗ за нарушение срока передачи объекта застройщик уплачивает участнику-гражданину неустойку в размере 1/300 ставки рефинансирования (ключевой ставки) Банка России, действующей на день исполнения обязательства, от цены договора за каждый день просрочки в двойном размере. Ставка определяется на последний день срока исполнения обязательства по договору (определение Верховного Суда РФ от 27.02.2024 № 127-КГ23-18-К4).");
      if (d.calc && !d.calc.error) {
        T(`На ${F(U.fmtDate(d.due), "дата")} ключевая ставка составляла ${pct(d.calc.base)}%. Расчёт выполнен с учётом периодов, за которые неустойка не начисляется (постановления Правительства РФ от 02.04.2020 № 423, от 26.03.2022 № 479, от 18.03.2024 № 326 с изменениями), и ограничения ставки 7,5% за период с 01.07.2023 по 31.12.2025 (п. 2 постановления № 326):`);
        const lines = d.calc.parts.map(p => p.rate === 0
          ? `${U.fmtDate(p.from)}–${U.fmtDate(p.to)} (${p.days} дн.) — мораторий, неустойка не начисляется`
          : `${U.money(d.price)} руб. × ${p.days} дн. (${U.fmtDate(p.from)}–${U.fmtDate(p.to)}) × ${pct(p.rate)}% / 300 × 2 = ${U.money(p.sum)} руб.`);
        P.push({ text: lines.join("\n") + `\nИтого: ${U.money(d.calc.total)} руб.` + (a.handed === "yes" ? "" : ` по состоянию на ${U.fmtDate(d.end)}`), align: "left", leftIndent: 709 });
      }
      P.push({ text: "ТРЕБУЮ:", indent: true, keepNext: true });
      T(`1. Выплатить неустойку за нарушение срока передачи объекта долевого строительства в размере ${F(d.calc && !d.calc.error ? U.money(d.calc.total) : null, "сумма")} руб.` + (a.handed === "yes" ? "" : ", а также неустойку за последующие дни по день фактической передачи объекта") + " в течение 10 дней со дня получения претензии.");
      if (a.handed !== "yes") T("2. Сообщить мне срок передачи объекта долевого строительства.");
      P.push({ text: "Денежные средства прошу перечислить по реквизитам:\n________________________________________________________________\n________________________________________________________________", indent: true, align: "left" });
      T("В случае отказа я обращусь в суд с требованием о взыскании неустойки, компенсации морального вреда (ч. 2 ст. 10 Федерального закона № 214-ФЗ) и штрафа в размере 5% от присуждённой суммы (ч. 3 ст. 10 Федерального закона № 214-ФЗ).");
      C.attachments(P, ["Копия договора участия в долевом строительстве.", "Документ об оплате цены договора.", a.handed === "yes" ? "Копия передаточного акта." : null].filter(Boolean));
      C.sign(P, a);
      return P;
    },

    guidance(a, d) {
      return [
        { title: "Отправьте ценным письмом с описью по юридическому адресу застройщика.", text: "Сохраните опись, чек и трек-номер. Можно вручить в офисе под отметку." },
        { title: "Застройщики сейчас вправе отложить выплату до 31.12.2026.", text: "Такую отсрочку дало постановление Правительства № 326 (в ред. от 30.12.2025 № 2227). Но претензию и иск откладывать не стоит: суд взыщет неустойку, а срок исковой давности — 3 года." },
        { title: "Моратории уже учтены.", text: `За периоды 03.04.2020–31.12.2020, 29.03.2022–30.06.2023 и 22.03.2024–31.12.2025 неустойка не начисляется. Всего дней просрочки — ${d.calc && !d.calc.error ? d.calc.days : "—"}, из них с начислением — ${d.calc && !d.calc.error ? d.calc.paidDays : "—"}.` },
        { title: "В суде — ещё штраф 5% и моральный вред.", text: "С 01.09.2024 штраф по ДДУ — 5% вместо 50%. Иск можно подать по месту своего жительства; госпошлину при цене иска до 1 млн ₽ не платите (ст. 17 закона о защите прав потребителей)." },
        { title: "Суд может снизить неустойку по ст. 333 ГК.", text: "Если застройщик заявит, что она несоразмерна. Обычно снижают, но не до нуля." },
      ];
    },

    fileName(a) { return "Претензия застройщику о неустойке" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d18 = spec;
})(typeof window !== "undefined" ? window : globalThis);
