/*
 * Д-47. Возврат части страховки при полном досрочном погашении кредита.
 * Основа: ч. 10 ст. 11 Закона № 353-ФЗ (коллективное страхование / услуга кредитора или третьего лица — возврат
 * за вычетом части, пропорциональной времени, в течение которого заёмщик был застрахован, в течение 7 рабочих дней),
 * ч. 12 ст. 11 (индивидуальный договор страхования, заключённый в целях обеспечения исполнения обязательств по кредиту
 * (ч. 2.4 ст. 7) — страховщик возвращает премию за вычетом части, пропорциональной времени действия страхования,
 * в течение 7 рабочих дней со дня заявления); условие — нет страховых случаев. Информационное письмо Банка России
 * от 13.07.2021 № ИН-06-59/50: возвращать нужно по всем рискам договора, а не выборочно. Если страховка не была связана
 * с кредитом — п. 3 ст. 958 ГК (возврат, только если предусмотрен договором). Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  function derive(a) {
    const start = U.date(a.start_date), end = U.date(a.end_date), paid = U.date(a.repaid_date);
    const premium = typeof a.premium === "number" ? a.premium : null;
    let total = null, used = null, refund = null;
    if (start && end && paid && end > start && premium != null) {
      total = U.daysBetween(start, end) + 1;
      used = Math.max(0, Math.min(total, U.daysBetween(start, paid) + 1));
      refund = Math.round(premium * (total - used) / total * 100) / 100;
    }
    const collective = a.form === "collective";
    return { start, end, paid, premium, total, used, refund, collective };
  }

  const spec = {
    id: "d47",
    code: "Д-47",
    title: "Возврат страховки при досрочном погашении",
    lead: "Погасили кредит досрочно — страховка, оформленная при кредите, больше не нужна. Можно вернуть часть денег за неиспользованный срок. Посчитаем сумму. Займёт около 5 минут.",
    status: "draft",
    actual: "08.11.2026",

    steps: [
      {
        id: "loan", title: "Кредит и страховка",
        questions: [
          { id: "full", type: "choice", label: "Кредит погашен полностью?", options: [
            { value: "yes", label: "Да, полностью досрочно" },
            { value: "part", label: "Нет, только частично" },
          ] },
          { id: "bank", type: "text", label: "Банк (кредитор)", placeholder: "ПАО «Банк»" },
          { id: "loan", type: "text", label: "Кредитный договор: номер и дата", placeholder: "№ 625/0000-0012345 от 15.03.2025" },
          { id: "repaid_date", type: "date", label: "Когда погасили кредит полностью?", show: a => a.full === "yes", hint: "Дата из справки банка о закрытии кредита" },
          { id: "linked", type: "choice", label: "Страховка была связана с кредитом?", options: [
            { value: "rate", label: "Да, со страховкой ставка ниже или без неё не давали кредит" },
            { value: "bank_benef", label: "Да, выгодоприобретатель — банк, или страховая сумма равна долгу" },
            { value: "no", label: "Нет, это отдельная страховка", hint: "Тогда закон о возврате при досрочном погашении не применяется" },
          ] },
          { id: "form", type: "choice", label: "Как оформлена страховка?", options: [
            { value: "individual", label: "Полис на моё имя — договор со страховой" },
            { value: "collective", label: "Подключение к программе страхования банка" },
          ] },
          { id: "insurer", type: "text", label: "Страховая компания", placeholder: "ООО СК «Страховая»" },
          { id: "insurer_address", type: "text", label: "Адрес страховой", required: false, show: a => a.form === "individual" },
          { id: "bank_address", type: "text", label: "Адрес банка", required: false, show: a => a.form === "collective" },
          { id: "policy_no", type: "text", label: "Номер полиса или заявления о присоединении" },
          { id: "premium", type: "money", label: "Сколько заплатили за страховку?", suffix: "₽", min: 1 },
          { id: "start_date", type: "date", label: "Страхование действует с", hint: "Даты — в полисе или заявлении" },
          { id: "end_date", type: "date", future: true, label: "по" },
          { id: "events", type: "choice", label: "Были страховые случаи?", options: [
            { value: "no", label: "Нет" },
            { value: "yes", label: "Да" },
          ] },
        ],
      },
      {
        id: "you", title: "Вы",
        questions: [
          ...C.personQuestions(),
          { id: "passport", type: "text", label: "Паспорт: серия и номер", required: false },
        ],
      },
    ],

    derive,

    stop(a, d) {
      if (a.full === "part") return { title: "При частичном погашении закон возврат не предусматривает.", text: "Часть страховки возвращают только после полного досрочного погашения кредита (ч. 10, 12 ст. 11 закона о потребкредите). Проверьте условия полиса: иногда страховая сумма уменьшается вместе с долгом." };
      if (a.events === "yes") return { title: "Если был страховой случай, возврат по этим правилам не положен.", text: "Посоветуйтесь с юристом." };
      if (a.linked === "no") return { title: "Для страховки, не связанной с кредитом, эти правила не действуют.", text: "Вернуть часть премии можно, только если это предусмотрено договором страхования (п. 3 ст. 958 ГК). Проверьте раздел о досрочном прекращении в правилах страхования. Если прошло меньше 14 дней с оформления — отказ в период охлаждения (Д-46)." };
      if (d.paid && d.end && d.paid > d.end) return { title: "Кредит погашен после окончания страхования.", text: "Возвращать нечего." };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      C.header(d.collective ? { name: a.bank, nameLabel: "банк", address: a.bank_address, blank: true } : { name: a.insurer, nameLabel: "страховая компания", address: a.insurer_address, blank: true }, C.from(a), P);
      C.title(P, "ЗАЯВЛЕНИЕ", "о возврате части страховой премии в связи с досрочным погашением кредита");
      T(`Между мной` + (a.passport ? ` (паспорт ${a.passport})` : "") + ` и ${F(a.bank, "банк")} был заключён договор потребительского кредита ${F(a.loan, "номер и дата")}. ` +
        (d.collective ? `При его заключении я был(а) подключён(а) к программе страхования (${F(a.policy_no, "номер")}, страховщик — ${F(a.insurer, "страховая")})` : `В целях обеспечения исполнения обязательств по нему заключён договор страхования ${F(a.policy_no, "номер")} с ${F(a.insurer, "страховая")}`) +
        ` на срок с ${F(U.fmtDate(d.start), "дата")} по ${F(U.fmtDate(d.end), "дата")}. Плата за страхование составила ${F(U.money(d.premium), "сумма")} руб.`);
      T({ rate: "Страхование являлось условием предоставления кредита на указанных в договоре условиях: от его наличия зависела процентная ставка (ч. 2.4 ст. 7 Федерального закона от 21.12.2013 № 353-ФЗ).", bank_benef: "Страхование обеспечивало исполнение моих обязательств по кредиту (ч. 2.4 ст. 7 Федерального закона от 21.12.2013 № 353-ФЗ)." }[a.linked] || F(null, "связь страховки с кредитом"));
      T(`${F(U.fmtDate(d.paid), "дата")} я полностью досрочно исполнил(а) обязательства по кредитному договору. События, имеющие признаки страхового случая, не наступали.`);
      T(`В соответствии с ч. ${d.collective ? "10" : "12"} ст. 11 Федерального закона № 353-ФЗ прошу возвратить мне часть платы за страхование за вычетом части, исчисляемой пропорционально времени, в течение которого действовало страхование, в течение семи рабочих дней со дня получения настоящего заявления.`);
      if (d.refund != null) P.push({ text: `Расчёт: срок страхования — ${d.total} дн.; страхование действовало ${d.used} дн.\n${U.money(d.premium)} руб. × (${d.total} − ${d.used}) / ${d.total} = ${U.money(d.refund)} руб.`, align: "left", leftIndent: 709 });
      T(`Сумма к возврату: ${F(d.refund != null ? U.money(d.refund) : null, "сумма")} руб. Возврат прошу произвести по всем рискам, включённым в договор (информационное письмо Банка России от 13.07.2021 № ИН-06-59/50).`);
      P.push({ text: "Денежные средства прошу перечислить по реквизитам:\n________________________________________________________________\n________________________________________________________________", align: "left", indent: true });
      C.attachments(P, ["Справка банка о полном погашении кредита.", "Копия полиса (заявления о присоединении к программе страхования).", "Документ об оплате страховки."]);
      C.sign(P, a);
      return P;
    },

    guidance(a, d) {
      return [
        { title: "Возьмите в банке справку о полном погашении.", text: "Без неё страховая не примет заявление." },
        { title: d.collective ? "Подайте заявление в банк." : "Подайте заявление в страховую.", text: "Лично под отметку о приёме или заказным письмом с описью. Срок возврата — 7 рабочих дней со дня получения заявления." },
        { title: "Отказали или вернули меньше — к финансовому уполномоченному.", text: "Сначала претензия в организацию, затем обращение на finombudsman.ru (бесплатно), потом суд." },
      ];
    },

    fileName(a) { return "Возврат страховки при досрочном погашении" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d47 = spec;
})(typeof window !== "undefined" ? window : globalThis);
