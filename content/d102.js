/*
 * Д-102. Отказали в вычете или не возвращают НДФЛ: возражения на акт, апелляционная жалоба или жалоба в УФНС.
 * Основа: НК РФ — ст. 88 (камеральная проверка 3 месяца; п. 5 — акт при нарушениях), ст. 100 п. 6 (возражения на
 * акт — 1 месяц), ст. 101 п. 9 (решение вступает в силу через 1 месяц), ст. 137, 138 (обязательный досудебный
 * порядок), ст. 139 (жалоба через налоговый орган, решение которого обжалуется, — в течение 1 года; п. 1, 2),
 * ст. 139.1 (апелляционная жалоба — до вступления решения в силу), ст. 139.2 (содержание жалобы), п. 6 ст. 140
 * (жалоба на решение по проверке — 1 месяц, прочие — 15 рабочих дней), ст. 79 (возврат с единого налогового счёта: срок — п. 3,
 * проценты с 11-го дня просрочки — п. 9),
 * ст. 219, 220 (социальные и имущественные вычеты), ст. 221.1 (упрощённый порядок).
 * Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;
  const num = x => (typeof x === "number" && x > 0 ? x : 0);

  const STAGE = {
    akt: { label: "Пришёл акт налоговой проверки", title: "ВОЗРАЖЕНИЯ", sub: "на акт налоговой проверки", months: 1, law: "п. 6 ст. 100 НК РФ" },
    decision: { label: "Пришло решение об отказе в вычете", title: "АПЕЛЛЯЦИОННАЯ ЖАЛОБА", sub: "на решение налогового органа", months: 1, law: "ст. 139.1, п. 9 ст. 101 НК РФ" },
    delay: { label: "Вычет одобрили, но деньги не вернули", title: "ЖАЛОБА", sub: "на бездействие налогового органа", months: 12, law: "п. 2 ст. 139 НК РФ" },
  };
  const KIND = { property: "имущественный вычет на покупку жилья (ст. 220 НК РФ)", mortgage: "имущественный вычет по процентам по ипотеке (ст. 220 НК РФ)", treatment: "социальный вычет на лечение (ст. 219 НК РФ)", study: "социальный вычет на обучение (ст. 219 НК РФ)", sport: "социальный вычет на спорт (ст. 219 НК РФ)", other: "налоговый вычет" };

  function derive(a) {
    const st = STAGE[a.stage] || STAGE.decision;
    const got = U.date(a.got_date);
    let deadline = got ? C.nextWorkday(U.addMonths(got, st.months)) : null;
    const late = !!(deadline && U.today() > deadline);
    const lateDecision = a.stage === "decision" && late;
    // решение вступило в силу — обычная жалоба в течение года (п. 2 ст. 139)
    if (lateDecision && got) deadline = C.nextWorkday(U.addMonths(got, 13));
    const yearLate = !!(deadline && U.today() > deadline);
    return { st, got, deadline, late, lateDecision, yearLate };
  }

  const spec = {
    id: "d102",
    code: "Д-102",
    title: "Отказали в налоговом вычете: жалоба в налоговую",
    lead: "Налоговая отказала в вычете за квартиру, лечение или учёбу, или вычет одобрили, а деньги не пришли. Возражения на акт, апелляционная жалоба или жалоба в управление ФНС — подаётся из личного кабинета. Займёт около 6 минут.",
    status: "draft",
    actual: "17.11.2026",
    defaults: { stage: "decision", kind: "property" },

    steps: [
      {
        id: "what", title: "Что случилось",
        questions: [
          { id: "stage", type: "choice", label: "Что вы получили", options: Object.entries(STAGE).map(([value, s]) => ({ value, label: s.label })) },
          { id: "kind", type: "select", label: "Какой вычет", options: Object.entries(KIND).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1).replace(/ \(ст\.[^)]*\)$/, "") })) },
          { id: "year", type: "number", label: "За какой год декларация", min: 2020, placeholder: "2025" },
          { id: "decl_date", type: "date", label: "Когда подали декларацию 3-НДФЛ" },
          { id: "ifns", type: "text", label: "Налоговая, которая проверяла", placeholder: "Инспекция ФНС России № 4 по г. Москве" },
          { id: "doc_no", type: "text", label: a => a.stage === "akt" ? "Номер и дата акта" : a.stage === "decision" ? "Номер и дата решения" : "Номер и дата заявления о возврате", placeholder: "№ 1234 от 20.10.2026" },
          { id: "got_date", type: "date", label: a => a.stage === "delay" ? "Когда подали заявление о возврате" : "Когда получили документ", hint: a => a.stage === "akt" ? "Месяц на возражения (п. 6 ст. 100 НК)" : a.stage === "decision" ? "Пока решение не вступило в силу — месяц на апелляционную жалобу" : "Срок возврата — по п. 3 ст. 79 НК; проценты за просрочку — с 11-го дня" },
          { id: "amount", type: "money", label: "Сколько налога к возврату", suffix: "₽" },
          { id: "reason", type: "textarea", label: a => a.stage === "delay" ? "Что происходит" : "Почему отказали — как написано в документе", placeholder: a => a.stage === "delay" ? "Камеральная проверка завершена 15.08.2026 без нарушений, заявление о возврате подано 20.08.2026, деньги не поступили" : "не представлены документы, подтверждающие оплату; квартира оформлена на супругу" },
          { id: "args", type: "textarea", label: "Почему вы не согласны", show: a => a.stage !== "delay",
            placeholder: "Документы об оплате (выписка банка, расписка продавца) были приложены к декларации. Квартира приобретена в браке — вычет может получить любой из супругов (п. 1 ст. 220 НК, письмо ФНС)." },
          { id: "attach", type: "textarea", label: "Что прикладываете", required: false, hint: "Каждый документ с новой строки", placeholder: "Договор купли-продажи\nВыписка банка об оплате\nСвидетельство о браке" },
        ],
      },
      {
        id: "you", title: "Вы",
        questions: [
          { id: "ufns", type: "text", label: "Управление ФНС по региону", show: a => a.stage !== "akt", placeholder: "УФНС России по г. Москве", hint: "Жалоба адресуется ему, а подаётся через вашу инспекцию" },
          { id: "buyer_name", type: "text", label: "Ваши фамилия, имя и отчество", autocomplete: "name" },
          C.innQuestion("buyer_inn", "Ваш ИНН"),
          { id: "buyer_address", type: "text", label: "Адрес", autocomplete: "street-address" },
          { id: "buyer_phone", type: "tel", label: "Телефон", autocomplete: "tel" },
        ],
      },
    ],

    derive,

    stop(a, d) {
      if (d.yearLate) return { title: "Прошло больше года.", text: "Жалобу на решение налоговой подают в течение года со дня, когда вы узнали о нарушении (п. 2 ст. 139 НК); пропущенный срок восстанавливают только по уважительной причине. Проще подать уточнённую декларацию с недостающими документами — вычет можно заявить за 3 последних года." };
      if (a.stage === "decision" && d.late) return { soft: true, title: "Решение уже вступило в силу.", text: `Месяц на апелляционную жалобу прошёл. Составим обычную жалобу — её можно подать в течение года, до ${U.fmtDate(d.deadline)} (п. 2 ст. 139 НК).` };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      const st = d.st;
      const title = a.stage === "decision" && d.lateDecision ? "ЖАЛОБА" : st.title;
      const to = a.stage === "akt" ? `Кому: руководителю — ${F(a.ifns, "налоговая")}` : `Кому: ${F(a.ufns, "УФНС по региону")}\nПодаётся через: ${F(a.ifns, "налоговая")}`;
      P.push({ text: `${to}\nот ${F(a.buyer_name, "ваши ФИО")}\nИНН ${F(a.buyer_inn, "ИНН")}\nАдрес: ${F(a.buyer_address, "адрес")}\nТел.: ${F(a.buyer_phone, "телефон")}`, align: "left", leftIndent: 4500, after: 360 });
      C.title(P, title, st.sub);
      T(`${F(U.fmtDate(U.date(a.decl_date)), "дата")} я подал(а) декларацию 3-НДФЛ за ${F(a.year, "год")} год и заявил(а) ${KIND[a.kind] || KIND.other}; сумма налога к возврату — ${num(a.amount) ? U.money(num(a.amount)) + " руб." : F(null, "сумма")}.`);
      if (a.stage === "delay") {
        T(`${F(U.fmtDate(d.got), "дата")} я подал(а) заявление о возврате (${F(a.doc_no, "номер")}). ${F(a.reason ? String(a.reason).trim().replace(/\.$/, "") : null, "что происходит")}.`);
        T("Налоговый орган обязан направить поручение на возврат в срок, установленный п. 3 ст. 79 НК РФ. При нарушении срока возврата более чем на десять дней на сумму начисляются проценты по ключевой ставке ЦБ РФ за каждый календарный день просрочки начиная с 11-го дня (п. 9 ст. 79 НК РФ).");
      } else {
        T(`${a.stage === "akt" ? "По результатам камеральной проверки составлен акт" : "Решением"} ${F(a.doc_no, "номер и дата")} в вычете отказано. Основание: ${F(a.reason ? String(a.reason).trim().replace(/\.$/, "") : null, "основание")}.`);
        T(`С ${a.stage === "akt" ? "выводами акта" : "решением"} не согласен(на): ${F(a.args ? String(a.args).trim().replace(/\.$/, "") : null, "доводы")}.`);
        T("Если налоговому органу недостаточно документов, он вправе истребовать их в ходе камеральной проверки (п. 3 ст. 88, ст. 93 НК РФ); недостаток документов, о котором налогоплательщику не сообщили, сам по себе не является основанием для отказа в вычете, если право на него подтверждено.");
      }
      P.push({ text: `На основании ${a.stage === "akt" ? "п. 6 ст. 100" : "ст. 137, 138, 139" + (a.stage === "decision" && !d.lateDecision ? ", 139.1" : "") + ", 139.2"} Налогового кодекса РФ`, indent: true, keepNext: true });
      P.push({ text: "ПРОШУ:", indent: true, keepNext: true });
      const ask = a.stage === "akt"
        ? ["Учесть настоящие возражения и прилагаемые документы при рассмотрении материалов проверки.", `Предоставить заявленный ${KIND[a.kind] || KIND.other} в полном объёме.`, "Известить меня о времени и месте рассмотрения материалов проверки (п. 2 ст. 101 НК РФ)."]
        : a.stage === "decision"
          ? [`Отменить решение ${F(a.doc_no, "номер и дата")}.`, `Подтвердить право на ${KIND[a.kind] || KIND.other} и возврат налога ${num(a.amount) ? U.money(num(a.amount)) + " руб." : ""}`.trim() + "."]
          : ["Обязать инспекцию вернуть мне налог" + (num(a.amount) ? ` ${U.money(num(a.amount))} руб.` : "") + ".", "Начислить проценты за нарушение срока возврата (п. 9 ст. 79 НК РФ)."];
      ask.forEach((x, i) => T(`${i + 1}. ${x}`));
      C.attachments(P, String(a.attach || "").split("\n").map(s => s.trim()).filter(Boolean).map(s => s.replace(/\.$/, "") + "."));
      C.sign(P, a);
      return P;
    },

    guidance(a, d) {
      const g = [];
      if (d.deadline && !d.yearLate) g.push({ title: `Подайте не позднее ${U.fmtDate(d.deadline)}.`, text: d.st.law + "." });
      g.push({ title: "Удобнее всего — из личного кабинета на nalog.ru.", text: "Раздел «Жизненные ситуации» → «Подать жалобу» (или «Обратиться в ФНС»): прикрепите этот файл и сканы документов. Можно и на бумаге — в инспекцию лично или заказным письмом." });
      if (a.stage === "decision") g.push({ title: "Управление ФНС рассматривает жалобу в течение месяца.", text: "Срок могут продлить ещё на месяц (п. 6 ст. 140 НК). Если откажут — можно в суд в течение 3 месяцев." });
      if (a.stage === "delay") g.push({ title: "Управление ФНС ответит за 15 рабочих дней.", text: "Срок могут продлить ещё на 15 рабочих дней (п. 6 ст. 140 НК). Если не помогло — можно в суд в течение 3 месяцев." });
      g.push({ title: "Иногда быстрее подать уточнённую декларацию.", text: "Если отказали из-за нехватки документов — подайте «уточнёнку» с полным комплектом. Новая проверка — до 3 месяцев." });
      return g;
    },

    reminders(a, d) { return d.deadline && !d.yearLate ? [{ date: d.deadline, title: "Последний день — жалоба или возражения в налоговую", text: d.st.law }] : []; },

    fileName(a) { return a.stage === "akt" ? "Возражения на акт налоговой проверки" : "Жалоба в налоговую — отказ в вычете"; },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d102 = spec;
})(typeof window !== "undefined" ? window : globalThis);
