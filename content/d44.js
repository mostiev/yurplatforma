/*
 * Д-44. Требование в банк о снятии блокировки карты, счёта или онлайн-банка.
 * Основа: 115-ФЗ — ст. 7: банк обязан сообщить клиенту дату и причины отказа не позднее 5 рабочих дней; клиент вправе
 * представить документы об отсутствии оснований (п. 13.4), банк рассматривает их (по разъяснению ЦБ — 7 рабочих дней);
 * затем — межведомственная комиссия при Банке России. 161-ФЗ — ч. 11.6, 11.7, 11.10 ст. 9: приостановление карты и
 * ДБО, если сведения о клиенте есть в базе ЦБ о переводах без согласия; заявление об исключении — через свой банк
 * (передаёт в ЦБ не позднее следующего рабочего дня) или в ЦБ; ЦБ решает за 15 рабочих дней (cbr.ru/contactBR/161-FZ,
 * обновлено 13.01.2026). П. 1, 3 ст. 859 ГК — расторжение договора счёта по заявлению клиента в любое время, выдача
 * остатка не позднее 7 дней. Статус: ЧЕРНОВИК, не проверен юристом.
 */
(function (global) {
  "use strict";
  const { U } = global.Engine;
  const C = global.Common;
  const F = U.F;

  const WHAT = {
    card: "заблокирована банковская карта",
    dbo: "ограничен доступ к дистанционному банковскому обслуживанию (мобильное приложение, интернет-банк)",
    op: "отказано в проведении операции",
    account: "ограничены операции по счёту",
  };

  function derive(a) {
    return { redirect: ["bailiffs", "tax"].includes(a.reason), what: (a.what || []).map(k => WHAT[k]).filter(Boolean) };
  }

  const spec = {
    id: "d44",
    code: "Д-44",
    title: "Требование о разблокировке карты или счёта",
    lead: "Банк заблокировал карту, приложение или перевод — «по 115-ФЗ» или «подозрение на мошенничество». Требование объяснить причину, рассмотреть документы и снять ограничения. Займёт около 5 минут.",
    status: "draft",

    steps: [
      {
        id: "block", title: "Блокировка",
        questions: [
          { id: "reason", type: "choice", label: "Что сказал банк о причине?", options: [
            { value: "aml", label: "Запросил документы, сослался на 115-ФЗ или «сомнительные операции»" },
            { value: "fraud", label: "Сослался на базу Банка России, мошенничество или 161-ФЗ", hint: "Например, вам переводили деньги, которые потом оспорили как похищенные" },
            { value: "unknown", label: "Ничего не объяснил" },
            { value: "bailiffs", label: "Арест от приставов" },
            { value: "tax", label: "Блокировка налоговой (для ИП)" },
          ] },
          { id: "what", type: "multi", label: "Что заблокировано?", options: Object.entries(WHAT).map(([value, label]) => ({ value, label: label[0].toUpperCase() + label.slice(1) })) },
          { id: "since", type: "date", label: "Когда это произошло?" },
          { id: "card_last4", type: "text", label: "Последние 4 цифры карты", required: false, show: a => (a.what || []).includes("card"), hint: "Полный номер карты не нужен",
            validate: v => /^\d{4}$/.test(String(v).trim()) ? null : "Ровно 4 цифры" },
          { id: "account", type: "text", label: "Номер счёта", required: false, hint: "20 цифр — в приложении банка или в договоре",
            validate: v => /^\d{20}$/.test(String(v).replace(/\s/g, "")) ? null : "Номер счёта — 20 цифр" },
          { id: "ops", type: "textarea", label: "Какие операции вызвали вопросы и откуда деньги", required: false, show: a => a.reason === "aml" || a.reason === "unknown",
            hint: "Коротко и по делу: это поможет банку быстрее снять ограничение", placeholder: "10.09.2026 получил(а) 180 000 ₽ от покупателя за проданный автомобиль по договору купли-продажи от 09.09.2026" },
          { id: "docs", type: "textarea", label: "Какие документы прикладываете?", required: false, show: a => a.reason === "aml" || a.reason === "unknown",
            hint: "Каждый с новой строки", placeholder: "Договор купли-продажи автомобиля от 09.09.2026\nСправка о доходах за 2026 год" },
          { id: "fraud_desc", type: "textarea", label: "Почему вы не связаны с мошенничеством?", required: false, show: a => a.reason === "fraud",
            placeholder: "Перевод 15 000 ₽ от 05.09.2026 — возврат долга от знакомого, переписка прилагается. Свою карту никому не передавал(а)" },
          { id: "close", type: "choice", label: "Если банк не снимет ограничения — закрыть счёт и выдать деньги?", options: [
            { value: "no", label: "Нет, хочу продолжить обслуживание" },
            { value: "yes", label: "Да, прошу закрыть счёт и выдать остаток" },
          ] },
          { id: "payout", type: "choice", label: "Как получить остаток?", show: a => a.close === "yes", options: [
            { value: "cash", label: "Наличными в отделении" },
            { value: "other_bank", label: "Переводом на мой счёт в другом банке", hint: "Оставим строку для реквизитов" },
          ] },
        ],
      },
      {
        id: "you", title: "Вы и банк",
        questions: [
          { id: "bank", type: "text", label: "Банк", placeholder: "АО «Банк»" },
          { id: "bank_address", type: "text", label: "Адрес банка или отделения", required: false },
          ...C.personQuestions(),
          { id: "passport", type: "text", label: "Паспорт: серия и номер", required: false, hint: "Помогает банку быстрее найти вас. Данные остаются в вашем браузере" },
        ],
      },
    ],

    derive,

    stop(a) {
      if (a.reason === "bailiffs") return { title: "Арест от приставов снимают не в банке.", text: "Если арестовали пособия, алименты и другие защищённые выплаты — заявление приставу о снятии ареста (Д-40). Чтобы на счёте оставался прожиточный минимум — заявление приставу (Д-38)." };
      if (a.reason === "tax") return { title: "Блокировку налоговой снимает налоговая.", text: "Обычно — после того, как сдана декларация или погашен долг. Решение налоговой можно обжаловать в вышестоящий налоговый орган. Этот документ не подходит." };
      return null;
    },

    render(a, d) {
      const P = [];
      const T = t => P.push({ text: t, indent: true });
      C.header({ name: a.bank, nameLabel: "банк", address: a.bank_address , blank: true }, C.from(a), P);
      C.title(P, "ЗАЯВЛЕНИЕ", "о снятии ограничений по счёту (карте) и дистанционному обслуживанию");
      const acc = a.account ? String(a.account).replace(/\s/g, "") : null;
      T(`Я являюсь клиентом банка` + (a.passport ? ` (паспорт ${a.passport})` : "") + (acc ? `, счёт № ${acc}` : "") + (a.card_last4 ? `, карта, последние цифры номера ${a.card_last4}` : "") + `. ${F(U.fmtDate(U.date(a.since)), "дата")} ${d.what.length ? d.what.join("; ") : F(null, "что заблокировано")}.`);
      if (a.reason === "aml" || a.reason === "unknown") {
        if (a.reason === "unknown") T("Причины ограничений мне не сообщены.");
        T("В соответствии со ст. 7 Федерального закона от 07.08.2001 № 115-ФЗ банк обязан проинформировать клиента о дате и причинах принятого решения об отказе в проведении операции не позднее пяти рабочих дней со дня его принятия. Клиент вправе представить в банк документы и сведения об отсутствии оснований для такого решения.");
        if (a.ops) T(`Поясняю: ${String(a.ops).trim().replace(/\.$/, "")}. Операции носят законный характер и не связаны с легализацией доходов, полученных преступным путём.`);
      }
      if (a.reason === "fraud") {
        T("Со слов банка, ограничение связано со сведениями, содержащимися в базе данных Банка России о случаях и попытках осуществления переводов денежных средств без добровольного согласия клиента (ст. 9 Федерального закона от 27.06.2011 № 161-ФЗ).");
        T(`К таким переводам я отношения не имею.` + (a.fraud_desc ? ` ${String(a.fraud_desc).trim().replace(/\.$/, "")}.` : ""));
      }
      P.push({ text: "ПРОШУ:", indent: true, keepNext: true });
      const items = [];
      if (a.reason !== "fraud") items.push("Сообщить мне в письменной форме дату и причины введения ограничений, а также перечень документов, которые необходимо представить для их снятия.");
      if ((a.reason === "aml" || a.reason === "unknown") && a.docs) items.push("Рассмотреть прилагаемые документы и сведения об отсутствии оснований для отказа в проведении операций.");
      if (a.reason === "fraud") items.push("Направить в Банк России моё заявление об исключении сведений обо мне из базы данных о случаях и попытках осуществления переводов денежных средств без добровольного согласия клиента не позднее следующего рабочего дня и сообщить мне о решении Банка России.");
      items.push("Снять ограничения и восстановить обслуживание в полном объёме: " + (d.what.length ? "по карте, счёту и дистанционному обслуживанию" : "по счёту") + ".");
      if (a.close === "yes") items.push(`Если ограничения не будут сняты — расторгнуть договор банковского счёта${acc ? ` № ${acc}` : ""} на основании п. 1 ст. 859 ГК РФ и не позднее семи дней выдать мне остаток денежных средств (п. 3 ст. 859 ГК РФ) ` + (a.payout === "other_bank" ? "переводом по реквизитам: ________________________________________________." : "наличными в отделении банка."));
      items.push("Ответ направить мне письменно по указанному адресу или по электронной почте.");
      items.forEach((x, i) => T(`${i + 1}. ${x}`));
      if (a.reason === "aml" || a.reason === "unknown") C.attachments(P, String(a.docs || "").split("\n").map(s => s.trim()).filter(Boolean));
      C.sign(P, a);
      return P;
    },

    guidance(a) {
      const g = [
        { title: "Подайте заявление в отделении и возьмите второй экземпляр с отметкой.", text: "Можно и через чат приложения, если он работает, но сохраните скриншоты. Ответ по документам банк обычно даёт в течение нескольких рабочих дней." },
      ];
      if (a.reason === "aml" || a.reason === "unknown") g.push({ title: "Банк не снял ограничения — жалоба в межведомственную комиссию при Банке России.", text: "Подаётся через интернет-приёмную ЦБ (раздел о 115-ФЗ). Приложите ответ банка и свои документы. Сроки подачи ограничены — не затягивайте." });
      if (a.reason === "fraud") g.push({ title: "Можно подать заявление об исключении из базы прямо в Банк России.", text: "Через интернет-приёмную cbr.ru, тема «Информационная безопасность». ЦБ решает за 15 рабочих дней. Пока ограничение действует, деньгами можно распорядиться в отделении банка по паспорту." });
      g.push({ title: "Параллельно — жалоба в Банк России (Д-52).", text: "Если банк не отвечает или отказывает без объяснений." });
      return g;
    },

    fileName(a) { return "Заявление о снятии блокировки" + (a.buyer_name ? " — " + U.shortName(a.buyer_name) : ""); },
  };

  global.DOCS = global.DOCS || {};
  global.DOCS.d44 = spec;
})(typeof window !== "undefined" ? window : globalThis);
